#!/usr/bin/env python3
"""fs131_ikc4_checks -- FS131-IKC4: write the check modules of the p = 19 certificate (one or two kernel declarations
each, chained by imports so that `scripts/build.sh` compiles one heavy module per batch) and the module that assembles
`cert19_ok` and the class-ratio bound at p = 19.

UNTRUSTED, like every generator: it writes statements the kernel checks. What each check module states is fixed here;
what it means is proved in `Arith/FibreCertFast` (each fast form equal to the checker's) and `Arith/FibreCertSound`.

Usage: fs131_ikc4_checks.py P1JSON OUTDIR [--unum U --scale L]
  P1JSON is the converter's `<out>.p1.json` (the phase-1 chunk bounds); OUTDIR receives the .lean files.
"""
import json, os, sys, argparse

ap = argparse.ArgumentParser()
ap.add_argument('p1json'); ap.add_argument('outdir')
ap.add_argument('--unum', required=True); ap.add_argument('--scale', required=True)
ap.add_argument('--nseg', type=int, default=4); ap.add_argument('--nkt', type=int, default=8)
ap.add_argument('--nb1', type=int, default=19); ap.add_argument('--nbq', type=int, default=1)
a = ap.parse_args()
bounds = json.load(open(a.p1json))['bounds']
nchunk = len(bounds) - 1
npairs = bounds[-1]
os.makedirs(a.outdir, exist_ok=True)
A = 'Proofs.HadwigerNelson.Arith.'
HDR = '-- GENERATED by tools/fs131_ikc4_checks.py; do not edit.\n'
chain = []          # (module, imports, doc, body)


def add(mod, doc, body):
    prev = chain[-1][0] if chain else None
    imps = [A + 'FibreCert19', A + 'FibreCertFast'] if prev is None else [A + prev]
    chain.append((mod, imps, doc, body))


ORDER = ('The import of the previous module only orders the build (one heavy module per batch).')
# the K table, two pieces a module
for i in range(0, a.nkt, 2):
    body = ''
    for r in (i, i + 1):
        if r >= a.nkt:
            continue
        body += (f'/-- Maps `{5 * r}` to `{5 * r + 4}` of the checker\'s K table `ktable cert19` are the literal `cert19_kt{r}`. -/\n'
                 f'theorem cert19_kt{r}_ok : ktEq (((ktable cert19).drop (5 * {r})).take 5) cert19_kt{r} = true := by\n'
                 f'  decide +kernel\n\n')
    add(f'FibreCert19Kt{i // 2}',
        f'# The certificate at `p = 19`: the K table, maps {5 * i}–{5 * min(i + 1, a.nkt - 1) + 4} (FS131-IKC4)\n\n'
        f'Two declarations by kernel reduction: the kernel computes these maps of `ktable cert19` and compares each entry '
        f'with the literal (`ktEq`, which is equality: `ktEq_eq`). {ORDER}', body)
# phase 1 in chunks
B0 = '(bucket16 (cert19.orbits.map fun o => (o.1, o.2, 0, 0)))'
for r in range(nchunk):
    n, ln = bounds[r], bounds[r + 1] - bounds[r]
    Br = f'cert19_p1s{r}'
    bdr = '0' if r == 0 else f'cert19_p1b{r}'
    pre = ('/-- Phase 1\'s orbit rows before its first pair: every row zero (`phase1`\'s start). -/\n'
           f'def cert19_p1s0 : List (List ORow) := {B0}\n\n') if r == 0 else ''
    body = pre + (f'/-- Phase 1 over pairs `{n}` to `{n + ln - 1}` of `{npairs}`, from the state after the first `{n}` '
            f'(`p1AtF`), ends with the orbit rows `cert19_p1s{r + 1}`, every transporter checked and the bound '
            f'`cert19_p1b{r + 1}`. -/\n'
            f'theorem cert19_p1c{r} : p1CoreEq ((((repPairs cert19.reps.length).drop {n}).take {ln}).foldl\n'
            f'    (p1stepF cert19 cert19_kt (cert19.blocks1.map (kmax cert19))) (p1AtF cert19 {Br} true {bdr} {n}))\n'
            f'    cert19_p1s{r + 1} cert19_p1b{r + 1} = true := by\n'
            f'  decide +kernel\n')
    add(f'FibreCert19C{r}',
        f'# The certificate at `p = 19`: phase 1, chunk {r} of {nchunk} (FS131-IKC4)\n\n'
        f'One declaration by kernel reduction: pairs `{n}` to `{n + ln - 1}` of phase 1 (`p1stepF`, which is the '
        f'checker\'s `p1step`: `p1stepF_eq`, `p1stepZ_eq`), the K table read from its literal. {ORDER}', body)
# the shape, from phase 1's result
add('FibreCert19Global',
    '# The certificate at `p = 19`: the shape, from phase 1\'s result (FS131-IKC4)\n\n'
    'One declaration by kernel reduction: `globalOK`\'s conjuncts with phase 1\'s result read from the last chunk '
    f'(`globalOKP`): the orbit rows against the certificate\'s literals, the q-part\'s transporters, the shape. {ORDER}',
    f'/-- `globalOK`\'s conjuncts hold at phase 1\'s result `(cert19_p1s{nchunk}.flatten, true, cert19_p1b{nchunk})`. -/\n'
    f'theorem cert19_globalP : globalOKP cert19 (cert19_p1s{nchunk}.flatten, true, cert19_p1b{nchunk}) = true := by\n'
    f'  decide +kernel\n')
# the identity segments
for k in range(a.nseg):
    add(f'FibreCert19Seg{k}',
        f'# The certificate at `p = 19`: identity segment {k} of {a.nseg} (FS131-IKC4)\n\n'
        f'One declaration by kernel reduction: the identity\'s ops without its zero ops (`segCheckZ`, which is the '
        f'checker\'s `segCheck`: `segCheck_eq_Z`), segment {k}. {ORDER}',
        f'/-- Segment {k} of the `p = 19` identity passes (zero ops left out). -/\n'
        f'theorem cert19_seg{k} : segCheckZ cert19 {k} = true := by\n'
        f'  decide +kernel\n')
# PSD, two blocks a module
blks = [(f'cert19_psd{k}', f'cert19_b{k}', f'times-1 block {k}') for k in range(a.nb1)] + \
       [(f'cert19_psdq{k}', f'cert19_q{k}', f'times-q block {k}') for k in range(a.nbq)]
for i in range(0, len(blks), 2):
    body = ''
    for (thm, b, what) in blks[i:i + 2]:
        body += (f'/-- The {what} of the `p = 19` certificate passes the PSD check. -/\n'
                 f'theorem {thm} : psdCheck {b} = true := by\n  decide +kernel\n\n')
    add(f'FibreCert19Psd{i // 2}',
        f'# The certificate at `p = 19`: positive definiteness, {" and ".join(w for (_, _, w) in blks[i:i + 2])} '
        f'(FS131-IKC4)\n\n'
        f'Kernel reduction, one declaration per block: `s·R − M·Mᵀ` diagonally dominant (`psdCheck`). {ORDER}', body)

for (mod, imps, doc, body) in chain:
    txt = HDR + ''.join(f'import {m}\n' for m in imps) + '\n/-!\n' + doc + '\n-/\n\nnamespace HadwigerNelson.FibreCert\n\n' + \
        body.rstrip('\n') + '\n\nend HadwigerNelson.FibreCert\n'
    open(os.path.join(a.outdir, mod + '.lean'), 'w').write(txt)

# the assembly
last = chain[-1][0]
kts = ', '.join(f'cert19_kt{r}' for r in range(a.nkt))
lines = []
L = lines.append
L(HDR + f'import {A}{last}\nimport {A}FibreCertSound\n')
L('/-!\n# The certificate at `p = 19` accepted, and the class-ratio bound at `p = 19` (FS131-IKC4)\n')
L('**Read aloud.** `cert19_ok`: the reduced certificate at `p = 19` (`data/search/2026-10-14/certs/v-p19-phi0-13-qs.json`)')
L('passes the whole check, `certOK cert19 = true`, assembled from the check modules `Arith/FibreCert19Kt0` … with no')
L('evaluation: the K table equal to its literal (`ktable_cert19`), phase 1 equal to its last chunk\'s result')
L('(`cert19_phase1`), the shape (`cert19_global`), the four identity segments and the twenty PSD blocks. Every fast form')
L('used is proved equal to the checker\'s in `Arith/FibreCertFast`; `certOK` is the checker of `Arith/FibreCert`, unchanged.\n')
L(f'`sum_le_nineteen`: every `φ : (ℤ/19)² → [0, 1]` with `q(φ) ≥ 0` has `Σ φ ≤ U/L`, `U = {a.unum}`, `L = {a.scale}`')
L('(`U/L = 88.6434…`), from `FibreCertSound.sum_le_of_certOK`. `card_le_nineteen`: an independent set of')
L('`Cay((ℤ/19)², S)` has at most `U/L` points; `card_div_lt_quarter_nineteen`: so its density is below `1/4`')
L('(`U/(361·L) = 0.2455…`, `bound_nineteen_lt_quarter`).\n')
L('**Model.** `model_nineteen`: the hypotheses of the bounds hold together — `φ = 0`, and the independent set `{0}`.\n-/\n')
L('namespace HadwigerNelson.FibreCert\n')
L('/-- `cert19`\'s modulus. -/\ntheorem cert19_p : cert19.p = 19 := rfl\n')
L(f'/-- `cert19`\'s numerator `U`. -/\ntheorem cert19_unum : cert19.unum = {a.unum} := rfl\n')
L(f'/-- `cert19`\'s scale `L`. -/\ntheorem cert19_scale : cert19.scale = {a.scale} := rfl\n')
L(f'/-- `cert19`\'s number of identity segments. -/\ntheorem cert19_nseg : cert19.nseg = {a.nseg} := rfl\n')
L('/-- The checker\'s K table at `p = 19` is the literal, piece by piece (`cert19_kt0_ok` …). -/')
L('theorem ktable_cert19 : ktable cert19 = cert19_kt := by')
L('  have hlen : (ktable cert19).length = 40 := by decide +kernel')
L(f'  refine (eq_flatten_of_pieces 5 [{kts}] (ktable cert19) (fun i hi => ?_)')
L('    (by rw [hlen]; decide)).trans rfl')
L('  match i, hi with')
for r in range(a.nkt):
    L(f'  | {r}, _ => exact ktEq_eq _ _ cert19_kt{r}_ok')
L(f'  | n + {a.nkt}, h => exact absurd h (by simp)\n')
L(f'/-- Phase 1 at `p = 19` is its last chunk\'s result (`cert19_p1c0` … `cert19_p1c{nchunk - 1}`). -/')
L(f'theorem cert19_phase1 : phase1KZ cert19 cert19_kt = (cert19_p1s{nchunk}.flatten, true, cert19_p1b{nchunk}) := by')
L('  have h1 : 0 < cert19.per1 := by decide +kernel')
L(f'  have hpl : (repPairs cert19.reps.length).length = {npairs} := by decide +kernel')
L(f'  have hs : ({B0}, true, 0, (⟨0, 0, cert19.p1⟩ : Rd), cert19.blocks1.map Blk.pairCoefs) =')
L(f'      p1At cert19 cert19_p1s0 true 0 0 := by')
L('    simp only [p1At, cert19_p1s0, List.drop_zero]')
L('    try rfl')
L(f'  have e : (repPairs cert19.reps.length).foldl (p1stepZ cert19 cert19_kt (cert19.blocks1.map (kmax cert19)))')
L(f'      (p1At cert19 cert19_p1s0 true 0 0) = p1At cert19 cert19_p1s{nchunk} true cert19_p1b{nchunk} {npairs} := by')
L('    rw [← List.drop_zero (l := repPairs cert19.reps.length)]')
for r in range(nchunk):
    n, ln = bounds[r], bounds[r + 1] - bounds[r]
    Br = f'cert19_p1s{r}'
    bdr = '0' if r == 0 else f'cert19_p1b{r}'
    L(f'    rw [fold_drop_chunkF cert19 cert19_kt _ _ {Br} {bdr} {n} {ln} cert19_p1s{r + 1} cert19_p1b{r + 1}')
    L(f'      (Nat.le_trans (by decide) (Nat.le_of_eq hpl.symm)) h1 (by decide +kernel) cert19_p1c{r}, show {n} + {ln} = {n + ln} from rfl]')
L(f'    rw [List.drop_eq_nil_of_le (Nat.le_of_eq hpl), List.foldl_nil]')
L('  simp only [phase1KZ]')
L('  rw [hs, e]')
L('  rfl\n')
L('/-- The shape check at `p = 19`, through the K table\'s literal and phase 1\'s chunks. -/')
L('theorem cert19_global : globalOK cert19 = true := by')
L('  rw [globalOK_eq_K, ktable_cert19, ← globalOKKZ_eq, globalOKKZ_eq_P, cert19_phase1]')
L('  exact cert19_globalP\n')
L('/-- **The `p = 19` certificate passes**: the shape (`cert19_global`), the identity segments (`cert19_seg0` …) and')
L('positive definiteness (`cert19_psd0` …), each checked by the kernel in its own module. -/')
L('theorem cert19_ok : certOK cert19 = true := by')
L('  have hs : segAll cert19 = true := by')
L('    change (List.range cert19.nseg).all (segCheck cert19) = true')
L('    rw [cert19_nseg]')
L('    refine List.all_eq_true.2 fun k hk => ?_')
L('    rw [List.mem_range] at hk')
L('    rw [segCheck_eq_Z]')
L('    match k, hk with')
for k in range(a.nseg):
    L(f'    | {k}, _ => exact cert19_seg{k}')
L(f'    | n + {a.nseg}, h => exact absurd h (by omega)')
L('  have hp : psdAll cert19 = true := by')
L('    change (cert19.blocks1 ++ cert19.blocksq).all psdCheck = true')
b1 = ', '.join(f'cert19_b{k}' for k in range(a.nb1)); bq = ', '.join(f'cert19_q{k}' for k in range(a.nbq))
L(f'    rw [show cert19.blocks1 = [{b1}] from rfl, show cert19.blocksq = [{bq}] from rfl]')
psds = ', '.join([f'cert19_psd{k}' for k in range(a.nb1)] + [f'cert19_psdq{k}' for k in range(a.nbq)])
L(f'    simp only [List.cons_append, List.nil_append, List.all_cons, List.all_nil, {psds}, Bool.and_self]')
L('  change (globalOK cert19 && segAll cert19 && psdAll cert19) = true')
L('  rw [cert19_global, hs, hp]')
L('  rfl\n')
L('end HadwigerNelson.FibreCert\n')
L('namespace HadwigerNelson.FibreCertSound\n\nopen HadwigerNelson.FibreCert\n')
L(f'/-- **The class-ratio bound at `p = 19`** (FS-66\'s L4, from the reduced certificate): every `φ : (ℤ/19)² → [0, 1]`')
L(f'with `q(φ) ≥ 0` has `Σ φ ≤ {a.unum} / {a.scale}`. -/')
L('theorem sum_le_nineteen (φ : V 19 → ℝ) (h0 : ∀ x, 0 ≤ φ x) (h1 : ∀ x, φ x ≤ 1) (hq : 0 ≤ qform 19 φ) :')
L(f'    ∑ x, φ x ≤ ({a.unum} : ℝ) / {a.scale} := by')
L('  haveI : NeZero cert19.p := ⟨by rw [cert19_p]; decide⟩')
L('  have h := sum_le_of_certOK cert19 cert19_ok φ h0 h1 hq')
L('  rw [cert19_unum, cert19_scale] at h')
L('  exact_mod_cast h\n')
L('/-- **Level one at `p = 19`**: an independent set of `Cay((ℤ/19)², S)` has at most')
L(f'`{a.unum} / {a.scale}` points. -/')
L('theorem card_le_nineteen (I : Finset (V 19)) (hI : ∀ x ∈ I, ∀ y ∈ I, y - x ∉ unitCircle 19) :')
L(f'    (I.card : ℝ) ≤ ({a.unum} : ℝ) / {a.scale} := by')
L('  haveI : NeZero cert19.p := ⟨by rw [cert19_p]; decide⟩')
L('  have h := card_le_of_certOK cert19 cert19_ok I hI')
L('  rw [cert19_unum, cert19_scale] at h')
L('  exact_mod_cast h\n')
L('/-- The bound at `p = 19` against the plane\'s `361` points: `U/(361·L) < 1/4` (the chain\'s K5 at 19). -/')
L(f'theorem bound_nineteen_lt_quarter : ({a.unum} : ℝ) / {a.scale} / 361 < 1 / 4 := by')
L('  norm_num\n')
L('/-- **An independent set of `Cay((ℤ/19)², S)` has density below `1/4`.** -/')
L('theorem card_div_lt_quarter_nineteen (I : Finset (V 19)) (hI : ∀ x ∈ I, ∀ y ∈ I, y - x ∉ unitCircle 19) :')
L('    (I.card : ℝ) / 361 < 1 / 4 :=')
L('  lt_of_le_of_lt (div_le_div_of_nonneg_right (card_le_nineteen I hI) (by norm_num)) bound_nineteen_lt_quarter\n')
L('/-- The hypotheses of `sum_le_nineteen` and `card_le_nineteen` hold together: `φ = 0`, and the independent set `{0}`. -/')
L('theorem model_nineteen : (∃ φ : V 19 → ℝ, (∀ x, 0 ≤ φ x) ∧ (∀ x, φ x ≤ 1) ∧ 0 ≤ qform 19 φ) ∧')
L('    ∃ I : Finset (V 19), I.Nonempty ∧ ∀ x ∈ I, ∀ y ∈ I, y - x ∉ unitCircle 19 :=')
L('  ⟨⟨fun _ => 0, fun _ => le_rfl, fun _ => zero_le_one, by simp [qform]⟩,')
L('    ⟨{0}, Finset.singleton_nonempty _, fun x hx y hy => by')
L('      rw [Finset.mem_singleton] at hx hy')
L('      subst hx; subst hy')
L('      simp only [sub_self, unitCircle, Finset.mem_filter, Finset.mem_univ, true_and]')
L('      decide⟩⟩\n')
L('end HadwigerNelson.FibreCertSound')
open(os.path.join(a.outdir, 'FibreCert19Bound.lean'), 'w').write('\n'.join(lines) + '\n')
print(f'wrote {len(chain)} check modules and FibreCert19Bound into {a.outdir}: ' + ' '.join(m for (m, _, _, _) in chain))
