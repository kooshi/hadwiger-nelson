#!/usr/bin/env python3
"""FS131-IJN1 — the draft of `scripts/Axioms.lean`'s block for the joined chain, generated from the print of
`data/fs131/ijn1/lean/AxiomsAll.lean` (every theorem and definition of the chain's 54 compiled modules, at the last build).

Every PUBLIC record is classed as the audit classes it (`scripts/axioms.sh`, `LEAN.md` § Trust ledger):
- CLEAN: a subset of the standard three — a `#print axioms` line for the CLEAN section;
- IMPORTED <imports>: the standard three and declared outside theorems, at least one — a line under the `declareImport`
  of the first import it names (`Rigidity.positive_entropy_rigidity`'s is new; `StandingFive.kloosterman_bound`'s exists);
- OPEN: `sorryAx` among its axioms — NOT auditable (the audit fails on `sorryAx`); listed with the sources the printer
  names, for the landing to add when those leaves are proved;
- BAD: any other axiom — the generator stops.
Writes the block to <out> and prints the counts. `--control` plants an unknown axiom into one record and requires the
generator to stop on it (exit 1, naming it).
Usage: fs131_ijn1_audit_block.py <axioms-all.txt> <out.lean> [--control]
"""
import re
import sys

STANDARD = {"propext", "Classical.choice", "Quot.sound"}
IMPORTS = ["HadwigerNelson.Rigidity.positive_entropy_rigidity", "HadwigerNelson.StandingFive.kloosterman_bound",
           "HadwigerNelson.Outside.OAI158.no_proper_five_coloring", "HadwigerNelson.Outside.OAI158.proper_to_borel_weak"]


def main():
    control = "--control" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    recs, srcs = [], {}
    for ln in open(args[0], encoding="utf-8"):
        m = re.match(r"AXIOMS (\S+) (public|private) (\S+) : \[(.*)\]$", ln.rstrip("\n"))
        if m:
            recs.append((m.group(1), m.group(2), m.group(3), {a.strip() for a in m.group(4).split(",") if a.strip()}))
            continue
        m = re.match(r"SORRY-FROM (\S+) : \[(.*)\]$", ln.rstrip("\n"))
        if m:
            srcs[m.group(1)] = sorted(a.strip() for a in m.group(2).split(",") if a.strip())
    if not recs:
        print("NO RECORDS — the printer or the reader is broken")
        return 2
    if control:
        recs = [(a, b, c, set(d) | ({"planted.unknownAxiom"} if c.endswith(".noRamifiedStableDyadic_of_tca") else set()))
                for (a, b, c, d) in recs]
    clean, imported, opened, bad = [], {i: [] for i in IMPORTS}, [], []
    for mod, kind, name, ax in recs:
        if mod == "PLANT" or kind != "public":
            continue
        extra = ax - STANDARD
        if not extra:
            clean.append((mod, name))
        elif "sorryAx" in extra:
            opened.append((mod, name, srcs.get(name, [])))
        elif extra <= set(IMPORTS):
            first = next(i for i in IMPORTS if i in extra)
            imported[first].append((mod, name, sorted(extra)))
        else:
            bad.append((mod, name, sorted(extra)))
    if bad:
        for b in bad:
            print(f"BAD {b[1]} ({b[0]}): {b[2]}")
        print(f"STOP: {len(bad)} record(s) on an axiom that is neither standard nor declared")
        return 1
    out = ["-- FS131-IJN1: DRAFT of the joined chain's block (generated by tools/fs131_ijn1_audit_block.py from",
           "-- data/fs131/ijn1/axioms-all.txt). Not filed: the landing places it.", "",
           f"-- IMPORTED: the records resting on `Rigidity.positive_entropy_rigidity` "
           f"({len(imported[IMPORTS[0]])}; `[EinsiedlerLindenstrauss2022]` Thm 1.3)",
           "#eval AxiomAudit.declareImport ``HadwigerNelson.Rigidity.positive_entropy_rigidity"]
    out += [f"#print axioms {n}" for (_, n, _) in sorted(imported[IMPORTS[0]], key=lambda r: r[1])]
    for i in IMPORTS[1:]:
        if imported[i]:
            out += ["", f"-- IMPORTED, under the existing declareImport of `{i}` ({len(imported[i])})"]
            out += [f"#print axioms {n}" for (_, n, _) in sorted(imported[i], key=lambda r: r[1])]
    out += ["", f"-- CLEAN ({len(clean)}): each on a subset of the standard three"]
    by_mod = {}
    for mod, n in clean:
        by_mod.setdefault(mod, []).append(n)
    for mod in sorted(by_mod):
        out.append(f"-- {mod}")
        out += [f"#print axioms {n}" for n in sorted(by_mod[mod])]
    out += ["", f"-- NOT AUDITABLE YET ({len(opened)}): `sorryAx` through the leaves named; add each when they are proved"]
    for mod, n, s in sorted(opened, key=lambda r: r[1]):
        out.append(f"--   {n} ({mod}): {', '.join(s)}")
    with open(args[1], "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"public records: {len(clean) + sum(len(v) for v in imported.values()) + len(opened)}; CLEAN {len(clean)}; "
          + "; ".join(f"IMPORTED {i.split('.')[-1]} {len(v)}" for i, v in imported.items()) + f"; OPEN {len(opened)}")
    if control:
        print("CONTROL: THE PLANT DID NOT STOP THE GENERATOR")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
