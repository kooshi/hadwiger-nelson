#!/usr/bin/env python3
"""FS131-L10B — the audit records wave 10's second landing still lacks, from the kernel's own list of theorems (after
`tools/fs131_l6a_register.py`).

  tools/fs131_l10b_register.py MAIN_COUNT LANDING_COUNT            list
  tools/fs131_l10b_register.py MAIN_COUNT LANDING_COUNT --write    append one block "FS131-L10B" above the PURCHASED banner
  tools/fs131_l10b_register.py MAIN_COUNT LANDING_COUNT --self-test

MAIN_COUNT, LANDING_COUNT: the two outputs of `data/fs131/l5/count-modules.lean` (`DECL <kind> <module> <name>` lines), taken on
`main`'s library and on the landing's. The landing's theorems are the `DECL THM` names of the landing that `main` does not hold as
theorems; every one must be of a module of the landing — the eleven new modules of `Arith/`, `Plane/MetricalBoundary`, or
`Plane/FalconerReduction` (whose axiom became a theorem) — FOREIGN-MODULE otherwise: the landing would be adding a theorem to
another module of `main`. A name Lean generates (`f.eq_1`, `congr_simp`, `mk.inj`, …: the pattern of `tools/fs131_l5_records.py`,
whose check this registration is made for) is counted and asked no record. Listed: the hand-written theorems with no
`#print axioms` line in `scripts/Axioms.lean` (MISSING), and the `#print axioms` lines of the wave's blocks (headings naming
`FS131-K10b`, `-I10D`, `-I10E`, `-I10F`, `-K10c`, `-L10B`) that name no declaration of the landing library (STALE: a record of a
deleted declaration, which would not elaborate).
--self-test: on the lists as read, a wave theorem's record removed in memory must read MISSING, and a record naming nothing,
planted in a wave block, must read STALE.
"""
import collections
import re
import sys

AX = "scripts/Axioms.lean"
BANNER = '#eval IO.println "=== PURCHASED ==="'
WAVE_MODS = {"Proofs.HadwigerNelson.Arith." + m for m in (
    "FactorAction Floor128 FloorPlanes GapSeven MajorityVote NegCircleModel NormOneTarget ProductFactor RatioBound TargetFloors "
    "WeilKloosterman").split()} | {"Proofs.HadwigerNelson.Plane.MetricalBoundary", "Proofs.HadwigerNelson.Plane.FalconerReduction"}
GENERATED = re.compile(r"\.(eq_\d+|eq_def|congr_simp|brecOn|binductionOn)$|\.mk\.(inj|injEq|sizeOf_spec)$")
BLOCK = re.compile(r"^/-! ## .*?\b(FS131-(?:K10b|I10D|I10E|I10F|K10c|L10B))\b")


def decls(path):
    thm, every = {}, set()
    for ln in open(path, encoding="utf-8"):
        p = ln.split()
        if ln.startswith("DECL ") and len(p) >= 4:
            every.add(p[3])
            if p[1] == "THM":
                thm[p[3]] = p[2]
    return thm, every


def wave_block_records(ax_text):
    out, job = [], None
    for ln in ax_text.split("\n"):
        if ln.startswith("/-! ## ") or ln.startswith("#eval IO.println"):
            m = BLOCK.match(ln)
            job = m.group(1) if m else None
        elif job and ln.startswith("#print axioms "):
            out.append((job, ln.split()[2]))
    return out


def survey(main_thm, land_thm, land_all, ax_text):
    have = collections.Counter(re.findall(r"^#print axioms (\S+)", ax_text, re.M))
    wave = {n: m for n, m in land_thm.items() if n not in main_thm}
    foreign = sorted(n for n, m in wave.items() if m not in WAVE_MODS)
    gen = sorted(n for n in wave if GENERATED.search(n))
    hand = {n: m for n, m in wave.items() if not GENERATED.search(n)}
    missing = sorted((m, n) for n, m in hand.items() if have[n] == 0)
    stale = sorted(n for _, n in wave_block_records(ax_text) if n not in land_all)
    return wave, gen, hand, missing, stale, foreign


def main(argv):
    flags = {a for a in argv if a.startswith("--")}
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 2:
        print(__doc__)
        return 2
    main_thm, _ = decls(args[0])
    land_thm, land_all = decls(args[1])
    if not main_thm or not land_thm:
        print("a count file holds no DECL THM line")
        return 2
    src = open(AX, encoding="utf-8").read()
    wave, gen, hand, missing, stale, foreign = survey(main_thm, land_thm, land_all, src)
    gone = sorted(n for n in main_thm if n not in land_thm)
    bymod = collections.Counter(m.split(".")[-1] for m in wave.values())
    blocks = collections.Counter(j for j, _ in wave_block_records(src))
    print(f"kernel: main {len(main_thm)} theorems, landing {len(land_thm)}; gone from main {len(gone)} {gone}; the wave adds {len(wave)} "
          f"({', '.join(f'{k} {v}' for k, v in sorted(bymod.items()))}); generated by Lean {len(gen)} {gen}; "
          f"hand-written {len(hand)}; with a record {len(hand) - len(missing)}; MISSING {len(missing)}; STALE {len(stale)} {stale}; "
          f"FOREIGN-MODULE {len(foreign)} {foreign}")
    print("records in the wave's blocks: " + ", ".join(f"{k} {v}" for k, v in sorted(blocks.items())) + f" (sum {sum(blocks.values())})")
    if "--self-test" in flags:
        victim = next(n for n in sorted(hand) if re.search(r"^#print axioms " + re.escape(n) + r"$", src, re.M))
        s1 = re.sub(r"^#print axioms " + re.escape(victim) + r"\n", "", src, count=1, flags=re.M)
        m1 = survey(main_thm, land_thm, land_all, s1)[3]
        f1 = any(n == victim for _, n in m1)
        anchor = "#print axioms " + victim + "\n"
        s2 = src.replace(anchor, anchor + "#print axioms HadwigerNelson.StandingFive.zz_planted_nothing\n", 1)
        st2 = survey(main_thm, land_thm, land_all, s2)[4]
        f2 = "HadwigerNelson.StandingFive.zz_planted_nothing" in st2
        print(f"plant (the record of {victim} removed): {'MISSING fired' if f1 else 'DID NOT FIRE'}")
        print(f"plant (a record naming no declaration, in a wave block): {'STALE fired' if f2 else 'DID NOT FIRE'}")
        print("self-test: PASS" if f1 and f2 else "self-test: FAIL")
        return 0 if f1 and f2 else 1
    if "--write" in flags and missing:
        assert src.count(BANNER) == 1
        blk = ["/-! ## FS-131 wave 10's second landing (job FS131-L10B) — the theorems of the wave's eleven new modules that the planners' and",
               "the implementers' blocks did not list. Read from the kernel's own list of the library's theorems",
               "(`data/fs131/l5/count-modules.lean`), by `tools/fs131_l10b_register.py`; checked by `tools/fs131_l5_records.py`. -/"]
        last = None
        for m, n in missing:
            if m != last:
                blk.append(f"-- {m[len('Proofs.HadwigerNelson.'):].replace('.', '/')}")
                last = m
            blk.append(f"#print axioms {n}")
        src = src.replace(BANNER, "\n".join(blk) + "\n\n" + BANNER)
        open(AX, "w", encoding="utf-8").write(src)
        print(f"wrote {len(missing)} records")
    else:
        for m, n in missing[:400]:
            print(f"  MISSING {m.split('.')[-1]} {n}")
    return 1 if (stale or foreign) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
