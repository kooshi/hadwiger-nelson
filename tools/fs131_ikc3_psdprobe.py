#!/usr/bin/env python3
"""fs131_ikc3_psdprobe -- FS131-IKC3: one probe file per chosen PSD block of an FS-66 certificate, for measuring F2's
"one block per declaration" cut (plans/FS131-KC13-certificates.md section 3.2, item 4) with the library's unchanged
`FibreCert.psdCheck`.

Each output file imports `Proofs.HadwigerNelson.Arith.FibreCert`, defines the block `blk` exactly as
tools/fs131_ikc1_gen.py emits a block (same widths, same tags, same Cholesky witness), and states
`theorem ok : psdCheck blk = true := by decide +kernel` (or `= false` under --corrupt, a planted fault).

UNTRUSTED, like the converter: the kernel is the check. Functions are imported from tools/fs131_ikc1_gen.py
(FS131-IKC1's converter, not edited); the block emission below is that converter's `emit.blk`, copied.

Usage: fs131_ikc3_psdprobe.py CERT.json OUTDIR --blocks 0,5,37 [--corrupt digit|entry] [--sbits 120]
  --corrupt digit : M[0][0] doubled (row 0 of s.R - M.M^T is no longer diagonally dominant)
  --corrupt entry : R[1][2] and R[2][1] moved by a large amount (the dominance fails)
"""
import argparse, importlib.util, json, pathlib, random, sys

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("gen", HERE / "fs131_ikc1_gen.py")
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)


def blk_lean(b, M, sbits, CB=8192):
    R = b['R']; m = len(R)
    wr = max(abs(v) for row in R for v in row).bit_length() + 2
    off = 1 << (wr - 1)
    per0, row0 = gen.chunks([R[0][j] + off for j in range(m)], wr, CB)
    fl = [R[i][j] + off for i in range(1, m) for j in range(i, m)]
    per, rest = gen.chunks(fl, wr, CB)
    assert per == per0
    wm = max(61, max(1, max(abs(v) for row in M for v in row).bit_length()) + 2)
    Cm = (1 << (wm - 1)) + 1
    wB = (m * (2 * Cm) ** 2).bit_length() + 1
    rg = random.Random(1000 * m + len(fl))
    fwd = [(rg.getrandbits(60) | (1 << 59)) + sum((M[i][k] + Cm) << (wB * (k + 1)) for k in range(m)) for i in range(m)]
    L = gen.lean_list
    nl = '[' + ', '.join(str(x) for x in b['weights']) + ']'
    return ('{ wts := ' + nl + ', m := ' + str(m) + ', wr := ' + str(wr) + ', per := ' + str(per) +
            ', sb := ' + str(sbits) + ', wm := ' + str(wm) + ', wB := ' + str(wB) +
            ', mrows := ' + L([hex(x) for x in fwd], '        ') +
            ', row0 := ' + L([hex(x) for x in row0], '        ') +
            ', rest := ' + L([hex(x) for x in rest], '        ') + ' }'), dict(m=m, wr=wr, wm=wm, wB=wB,
            mrow_bits=max(x.bit_length() for x in fwd), r_fields=m + len(fl))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cert'); ap.add_argument('outdir'); ap.add_argument('--blocks', required=True)
    ap.add_argument('--corrupt', default=None, choices=['digit', 'entry'])
    ap.add_argument('--sbits', type=int, default=120, help='the witness scale 2^sbits (the converter uses 120)')
    a = ap.parse_args()
    C = json.load(open(a.cert))
    out = pathlib.Path(a.outdir); out.mkdir(parents=True, exist_ok=True)
    for bi in [int(x) for x in a.blocks.split(',')]:
        b = C['blocks'][bi]
        R = b['R']
        M, sbits = gen.mp_cholesky_int(R, a.sbits)
        ok, row = gen.check_dd(R, M, sbits)
        if not ok:
            raise SystemExit(f'block {bi}: dominance fails at row {row} (model)')
        tag = ''
        if a.corrupt == 'digit':
            M = [r[:] for r in M]; M[0][0] *= 2; tag = 'digit'
        elif a.corrupt == 'entry':
            b = dict(b); b['R'] = [r[:] for r in R]; big = 1 << 200
            b['R'][1][2] += big; b['R'][2][1] += big; tag = 'entry'
        body, info = blk_lean(b, M, sbits)
        want = 'false' if a.corrupt else 'true'
        name = f'B{bi}{tag}' + ('' if a.sbits == 120 else f's{a.sbits}')
        text = ('import Proofs.HadwigerNelson.Arith.FibreCert\n'
                f'-- GENERATED by tools/fs131_ikc3_psdprobe.py from {a.cert}, block {bi} ({b["times"]}), '
                f'corrupt={a.corrupt}. A probe, not a library module.\n'
                'namespace FS131IKC3Psd\nopen HadwigerNelson.FibreCert\n'
                f'def blk : Blk := {body}\n'
                f'theorem ok : psdCheck blk = {want} := by decide +kernel\n'
                'end FS131IKC3Psd\n')
        (out / f'{name}.lean').write_text(text)
        print(f'{name}: times={b["times"]} {info} bytes={len(text)}', flush=True)


if __name__ == '__main__':
    main()
