#!/usr/bin/env python3
"""SEARCH-2026-10-06 — the maps searched, the CNF of `CountData M k`, and the solver's driver.

The CNF (variables X(f, c) = f*k + c + 1, "face f has colour c"), one group of clauses per field of `CountData`, generated by
`clauses` — the one generator the controls read (`tools/search_20261006_controls.py`) and the runs solve:
  onehot           each face one colour
  proper           Adj f g                                  ->  not both colour c
  edge_rainbow     g != h edge-neighbours of f              ->  not both colour c
  repeat_one_side  dart d, f = face d, g = face (alpha d), z in vertNbrs f, z' in vertNbrs g
                                                            ->  not (z, g colour c and z', f colour c')
  partner_unique   z != z' in vertNbrs f, g edge-neighbour  ->  not all three colour c
  absent_cap       a 4-subset S of vertNbrs f, colour j     ->  some edge-neighbour of f has j, or some z in S has not
`three_le_deg` and `mu_zero` do not read the colouring: they are checked on the map before any solve.

A WINDOW (`centres`) keeps only the clauses centred at the given faces, leaving the others free: on a large torus quotient of
a periodic tiling, with the centres chosen so that no clause reaches the seam, the formula is a free-boundary patch of the
infinite tiling, and its unsatisfiability excludes the tiling's every finite quotient (record, Stage 1).

Symmetry: one centre face takes colour 0 and its edge-neighbours 1, 2, ... in index order (`proper` and `edge_rainbow` at
that face make them pairwise distinct in every model, and a permutation of the colours carries any model to such a one).
"""
import math
import os
import subprocess
import sys
import time
from itertools import combinations

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from search_20261006_check import CMap  # noqa: E402

CADICAL = os.path.expanduser("~/.elan/toolchains/leanprover--lean4---v4.32.0/bin/cadical")
CAKE = os.path.expanduser("~/source/cake_lpr/cake_lpr")


def clauses(M, k, centres=None, skip=()):
    X = lambda f, c: f * k + c + 1  # noqa: E731
    K = range(k)
    for f in range(M.F):
        yield "onehot", [X(f, c) for c in K]
        for c in K:
            for c2 in range(c + 1, k):
                yield "onehot", [-X(f, c), -X(f, c2)]
    Cs = set(range(M.F)) if centres is None else set(centres)
    for f in sorted(Cs):
        if "proper" not in skip:
            for g in sorted(M.adj[f]):
                if f < g or g not in Cs:
                    for c in K:
                        yield "proper", [-X(f, c), -X(g, c)]
        if "edge_rainbow" not in skip:
            for g, h in combinations(sorted(M.eadj[f]), 2):
                for c in K:
                    yield "edge_rainbow", [-X(g, c), -X(h, c)]
        if "partner_unique" not in skip:
            for z, z2 in combinations(sorted(M.vn[f]), 2):
                for g in sorted(M.eadj[f]):
                    for c in K:
                        yield "partner_unique", [-X(z, c), -X(z2, c), -X(g, c)]
        if "absent_cap" not in skip:
            E = sorted(M.eadj[f])
            for S in combinations(sorted(M.vn[f]), 4):
                for j in K:
                    yield "absent_cap", [X(g, j) for g in E] + [-X(z, j) for z in S]
    if "repeat_one_side" not in skip:
        for d in range(M.n):
            f, g = M.face[d], M.face[M.alpha[d]]
            if f not in Cs or (g in Cs and M.alpha[d] < d):     # the clause of alpha d is the same clause
                continue
            for z in sorted(M.vn[f]):
                for z2 in sorted(M.vn[g]):
                    for c in K:
                        for c2 in K:
                            yield "repeat_one_side", sorted({-X(z, c), -X(g, c), -X(z2, c2), -X(f, c2)})


def pins(M, k, f0):
    return [[f0 * k + 1]] + [[g * k + i + 2] for i, g in enumerate(sorted(M.eadj[f0])) if i + 1 < k]


def write_cnf(cls, nv, path):
    with open(path + ".cnf", "w") as h:
        h.write(f"p cnf {nv} {len(cls)}\n")
        h.writelines(" ".join(map(str, c)) + " 0\n" for c in cls)


def formula(M, k, centres=None, f0=0):
    return [c for _, c in clauses(M, k, centres)] + pins(M, k, f0)


def solve(cls, nv, path, timeout=None):
    """cadical with a text LRAT proof; UNSAT is returned only after cake_lpr verifies the proof against the same CNF."""
    write_cnf(cls, nv, path)
    t = time.time()
    r = subprocess.run([CADICAL, "-q", "--lrat", "--no-binary", path + ".cnf", path + ".lrat"], capture_output=True, text=True,
                       timeout=timeout)
    dt = time.time() - t
    if r.returncode == 10:
        os.remove(path + ".lrat")
        model = {int(x) for ln in r.stdout.splitlines() if ln.startswith("v ") for x in ln[2:].split()}
        return "SAT", {x for x in model if x > 0}, dt
    if r.returncode == 20:
        q = subprocess.run([CAKE, path + ".cnf", path + ".lrat"], capture_output=True, text=True)
        if q.returncode != 0 or "s VERIFIED UNSAT" not in q.stdout:
            raise RuntimeError(f"cake_lpr did not verify {path}.lrat: rc {q.returncode} {q.stdout[-200:]!r} {q.stderr[-200:]!r}")
        return "UNSAT", None, dt
    raise RuntimeError(f"cadical rc {r.returncode} on {path}.cnf: {r.stderr[-300:]!r}")


def colouring(M, k, model):
    col = [[c for c in range(k) if f * k + c + 1 in model] for f in range(M.F)]
    assert all(len(c) == 1 for c in col)
    return [c[0] for c in col]


# ---------------------------------------------------------------------------------------------------------------- the maps

def periodic(verts, edges, a1, a2, A, B, Dd):
    """The torus quotient of a periodic straight-line tiling by the lattice <(A, 0), (B, Dd)> of unit cells.
    verts: positions in the cell; edges: (u, v, (di, dj)), u in a cell joined to v in the cell (di, dj) on.
    Darts: (edge, cell, side); sigma sorts the darts at a vertex counter-clockwise by angle. Returns sigma, alpha and
    dcell (the cell of each dart's vertex)."""
    def red(i, j):
        q, j2 = divmod(j, Dd)
        return ((i - q * B) % A, j2)
    cells = [(i, j) for i in range(A) for j in range(Dd)]
    ci = {c: t for t, c in enumerate(cells)}
    n = len(edges) * len(cells) * 2
    alpha, dcell, at = [0] * n, [None] * n, {}
    for e, (u, v, (di, dj)) in enumerate(edges):
        pu = verts[u]
        pv = (verts[v][0] + di * a1[0] + dj * a2[0], verts[v][1] + di * a1[1] + dj * a2[1])
        ang0 = math.atan2(pv[1] - pu[1], pv[0] - pu[0])
        ang1 = math.atan2(pu[1] - pv[1], pu[0] - pv[0])
        for c in cells:
            c2 = red(c[0] + di, c[1] + dj)
            d0 = (e * len(cells) + ci[c]) * 2
            d1 = d0 + 1
            alpha[d0], alpha[d1], dcell[d0], dcell[d1] = d1, d0, c, c2
            at.setdefault((u, c), []).append((ang0, d0))
            at.setdefault((v, c2), []).append((ang1, d1))
    sigma = [0] * n
    for L in at.values():
        L.sort()
        assert all(L[i + 1][0] - L[i][0] > 1e-6 for i in range(len(L) - 1)), "two edges in one direction at a vertex"
        for i in range(len(L)):
            sigma[L[i][1]] = L[(i + 1) % len(L)][1]
    return sigma, alpha, dcell


def diag_tiling(pat):
    """The square grid with diagonals: pat[i][j] in {0 none, 1 '/', 2 '\\'} for the cell with south-west corner (i, j),
    periodic in the p x q supercell. Returns verts, edges, a1, a2 with the supercell as the unit cell."""
    p, q = len(pat), len(pat[0])
    vid = lambda i, j: (i % p) * q + (j % q)  # noqa: E731
    off = lambda i, j: (i // p, j // q)  # noqa: E731
    verts = [(float(i), float(j)) for i in range(p) for j in range(q)]
    edges = []
    for i in range(p):
        for j in range(q):
            edges.append((vid(i, j), vid(i + 1, j), off(i + 1, j)))
            edges.append((vid(i, j), vid(i, j + 1), off(i, j + 1)))
            if pat[i][j] == 1:
                edges.append((vid(i, j), vid(i + 1, j + 1), off(i + 1, j + 1)))
            if pat[i][j] == 2:
                o1, o2 = off(i + 1, j), off(i, j + 1)
                edges.append((vid(i + 1, j), vid(i, j + 1), (o2[0] - o1[0], o2[1] - o1[1])))
    return verts, edges, (float(p), 0.0), (0.0, float(q))


def deltoidal():
    """The deltoidal trihexagonal tiling (dual of 3.4.6.4): hexagon centres (degree 6), edge midpoints (4), hexagon
    vertices (3); six kites per cell; V3 : V4 : V6 = 2 : 3 : 1."""
    a1, a2 = (1.0, 0.0), (0.5, math.sqrt(3) / 2)
    P = lambda x, y: (x * a1[0] + y * a2[0], x * a1[1] + y * a2[1])  # noqa: E731
    verts = [P(0, 0), P(.5, 0), P(0, .5), P(.5, .5), P(1 / 3, 1 / 3), P(2 / 3, 2 / 3)]    # c, m1, m2, m3, t1, t2
    edges = [(0, 1, (0, 0)), (0, 1, (-1, 0)), (0, 2, (0, 0)), (0, 2, (0, -1)), (0, 3, (-1, 0)), (0, 3, (0, -1)),
             (4, 1, (0, 0)), (4, 2, (0, 0)), (4, 3, (0, 0)), (5, 2, (1, 0)), (5, 1, (0, 1)), (5, 3, (0, 0))]
    return verts, edges, a1, a2


NAMED = {
    "square": lambda: diag_tiling([[0]]),
    "triangular": lambda: diag_tiling([[1]]),
    "elongated": lambda: diag_tiling([[0, 1]]),
    "snub": lambda: diag_tiling([[1, 0], [0, 2]]),
    "deltoidal": deltoidal,
}
DUAL_OF = {"hexagonal": "triangular", "prismatic-pentagonal": "elongated", "cairo": "snub", "rhombitrihexagonal": "deltoidal"}


def build(name_or_tiling, A, B, Dd, dual=False):
    if isinstance(name_or_tiling, str):
        if name_or_tiling in DUAL_OF:
            name_or_tiling, dual = DUAL_OF[name_or_tiling], True
        name_or_tiling = NAMED[name_or_tiling]()
    sigma, alpha, dcell = periodic(*name_or_tiling, A, B, Dd)
    M = CMap(sigma, alpha)
    if dual:
        M = CMap(M.phi, alpha)       # the dual map: its vertices are the faces; the darts and their cells are kept
    return M, dcell


def window(M, dcell, N):
    """Centres of a free-boundary patch on the N x N torus: the faces with every corner in cells [m, N-1-m]^2, for the least
    m such that every face a clause centred there reads has every corner in [1, N-2]^2 (so no clause reaches the seam)."""
    fc = [set() for _ in range(M.F)]
    for d in range(M.n):
        fc[M.face[d]].add(dcell[d])
    inside = lambda f, lo, hi: all(lo <= c[0] <= hi and lo <= c[1] <= hi for c in fc[f])  # noqa: E731
    for m in range(1, N // 2):
        cen = [f for f in range(M.F) if inside(f, m, N - 1 - m)]
        read = set()
        for f in cen:
            read |= {f} | M.adj[f]
            for g in M.eadj[f]:
                read |= M.vn[g]
        if cen and all(inside(f, 1, N - 2) for f in read):
            mid = (N - 1) / 2
            f0 = min(cen, key=lambda f: max(abs(c[0] - mid) + abs(c[1] - mid) for c in fc[f]))
            return cen, m, f0
    return None, None, None


def run(M, k, path, centres=None, f0=0, timeout=None):
    cls = formula(M, k, centres, f0)
    v, model, dt = solve(cls, M.F * k, path, timeout)
    return v, (colouring(M, k, model) if model else None), dt, len(cls)
