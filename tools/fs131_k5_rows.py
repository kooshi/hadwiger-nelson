#!/usr/bin/env python3
"""FS131-K5: copy wave 5's rows verbatim from plans/LEAN-BACKLOG.md into data/fs131/k5/rows.md.

Each row's section runs from its `### ` heading to the next `### ` heading; nothing is paraphrased.
`--check` re-extracts and compares with the committed file; `--plant` drops one id and must fail.
"""
import sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
BACKLOG = ROOT / "plans" / "LEAN-BACKLOG.md"
OUT = ROOT / "data" / "fs131" / "k5" / "rows.md"
IDS = ["FS114-BV-HEX", "FS114-CVB-THOM", "FS112-N3-COR3", "FS112-ROTHEX", "FS112-N3-BASE", "FS112-N3-DENSE3",
       "FS114-CV-EXISTS", "FS129-OR1-LOCALDENSE", "FS129-SR2-DISC1TS", "FS114-CV-HD", "FS112-N2-TERM", "FS112-C-ENDS",
       "FS112-C-DOUBLE",
       # merged into wave-5 rows
       "FS112-DISC1", "FS112-N2-RED",
       # carried obligations from wave 4 (context only)
       "FS112-N2-FLANK-Q", "FS112-N3-END", "FS114-L60-WALK"]

def sections(text):
    lines = text.splitlines()
    heads = [i for i, l in enumerate(lines) if l.startswith("### ")]
    out = {}
    for a, b in zip(heads, heads[1:] + [len(lines)]):
        title = lines[a]
        rid = title.split(". ", 1)[-1].strip()
        out[rid] = "\n".join(lines[a:b]).rstrip() + "\n"
    return out

def build(ids):
    sec = sections(BACKLOG.read_text())
    missing = [i for i in ids if i not in sec]
    if missing:
        raise SystemExit(f"FAIL: ids not found in the backlog: {missing}")
    head = ("# Wave 5's rows, verbatim from `plans/LEAN-BACKLOG.md` (FS131-K5)\n\n"
            "*Generated by `tools/fs131_k5_rows.py`; do not edit. The first 13 are wave 5's rows; FS112-DISC1 and FS112-N2-RED merge into "
            "FS129-SR2-DISC1TS and FS112-N2-TERM; the last three are wave 4's rows whose obligations reach wave 5.*\n\n")
    return head + "\n".join(sec[i] for i in ids)

if __name__ == "__main__":
    if "--plant" in sys.argv:
        txt = build(IDS[1:])
        ok = txt == OUT.read_text()
        print("plant (one id dropped):", "NOT FIRED" if ok else "FIRED")
        sys.exit(1 if ok else 0)
    txt = build(IDS)
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print("check:", "OK" if ok else "FAIL", f"({len(IDS)} rows)")
        sys.exit(0 if ok else 1)
    OUT.write_text(txt)
    print(f"wrote {OUT} ({len(IDS)} rows, {len(txt)} bytes)")
