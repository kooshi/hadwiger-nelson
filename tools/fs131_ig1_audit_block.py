#!/usr/bin/env python3
"""FS131-IG1 (FS131-IDG1's `tools/fs131_idg1_audit_block.py`, for `Rigidity/Pieces`) — the draft block for `scripts/Axioms.lean`'s
CLEAN section: one `#print axioms` line per PUBLIC record of `Rigidity/Pieces` whose axioms are a subset of the standard
three, read from the output of `data/fs131/ig1/lean/Axioms.lean` on the built tree. The records resting on `sorryAx`
through the named leaves of other modules (`haar_or_zero_entropy`, `ksEntropy_eq_iSup_ksEntropyOn`) are left out and
listed in a comment, each with the leaves its `sorry` comes from; the `DOWNSTREAM` rows are not this job's and are
skipped.  Generated names Lean
makes on demand (`.congr_simp`, `.eq_n`, `.induct`, …) are left out: no author declares them.

Usage: fs131_ig1_audit_block.py <axioms.txt> > <block.lean>
Exit 2 if the input holds no record (a block from a broken read is never written as an empty block).
"""
import sys

STANDARD = {"propext", "Classical.choice", "Quot.sound"}
GENERATED = (".congr_simp", ".eq_def", ".induct", ".splitter")
# what `structure` generates beside the fields (the fields themselves — `AdmissiblePair.u`, `.w`, `.injective`,
# `.generates` — are kept: the file declares them)
STRUCTURE_GENERATED = (".casesOn", ".ctorIdx", ".mk.inj", ".mk.injEq", ".mk.noConfusion", ".mk.sizeOf_spec",
                       ".noConfusion", ".noConfusionType", ".recOn")


def main():
    rows, src = [], {}
    for ln in open(sys.argv[1]).read().splitlines():
        if ln.startswith("SORRY-FROM "):
            h, l = ln.split(" : ", 1)
            src[h.split(" ")[1]] = l.strip()
            continue
        if not ln.startswith("AXIOMS ") or ln.startswith("AXIOMS-COUNT"):
            continue
        head, axs = ln.split(" : ", 1)
        _, mod, kind, name = head.split(" ")
        body = axs.strip()[1:-1].strip()
        ax = set() if not body else {x.strip() for x in body.split(",")}
        if mod == "PLANT" or mod.startswith("DOWNSTREAM-") or kind != "public":
            continue
        if any(g in name for g in GENERATED) or ".eq_" in name or name.endswith(STRUCTURE_GENERATED):
            continue
        rows.append((mod, name, ax))
    if not rows:
        print("no records read", file=sys.stderr)
        sys.exit(2)
    out = ["/-! ## FS131-IG1 — the pieces, PE-1′ and Lemma Γ (`Rigidity/Pieces`); generated by",
           "`tools/fs131_ig1_audit_block.py` -/",
           "-- FS131-IG1"]
    left = []
    cur = None
    for mod, name, ax in rows:
        if not ax <= STANDARD:
            left.append(f"--   {name} : {sorted(ax)}; sorry from {src.get(name, '[]')}")
            continue
        if mod != cur:
            out.append(f"-- {mod.removeprefix('Proofs.HadwigerNelson.').replace('.', '/')}")
            cur = mod
        out.append(f"#print axioms {name}")
    if left:
        out.append("-- left out until the leaves of other modules they read land (each rests on `sorryAx` through them):")
        out.extend(left)
    print("\n".join(out))


if __name__ == "__main__":
    main()
