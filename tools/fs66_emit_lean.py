#!/usr/bin/env python3
"""fs66_emit_lean -- put an FS-66 witness through the repository's kernel pipeline.

UNTRUSTED, like everything in tools/. It writes two hand-shaped data modules and then calls
`tools/emit_mask.py` for the certificate; Lean re-derives every claim from the emitted data, so a
mistake here can only produce modules that fail to build:

    <dir>/Pts.lean     `<name>Packed : Nat` -- the vertex table as ONE packed literal, the w-bit
                       field at offset w*i holding `a*n + b`.  Read by `unpackPt n w` (ResidueTower).
                       Imports nothing; it is the geometry, and geometry never sits upstream of a
                       certificate (ARCHITECTURE.md section 4).
    <dir>/Edges.lean   `<name>Edges : List (Fin N x Fin N)` -- the listed pairs, in chunks flattened,
                       in the witness's own order, because the LRAT addresses clauses by position.
    <dir>/Cnf/         `tools/emit_mask.py`'s clause table and segmented certificate.

Why a packed literal and not `![...]` or a `List` indexed by position: access to either is linear in
the table (CLAUDE.md, "The kernel's cost model"), and the edge check makes 2*|E| accesses.  Why the
points are naturals and not `ZMod n`: a numeral at an unsimplified type index is paid per numeral.

Usage (from the repository root):
    python3 tools/fs66_emit_lean.py data/fs66/witness-p11-l2-k4/witness.json \
        --name zmod121Four --dir Proofs/HadwigerNelson/Instances/ZMod121Four \
        [--width 14] [--per-chunk 100] [--segments 2] [--table-modules 8] [--dry-run DIR]
"""
import gzip
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import coloring  # noqa: E402

sys.set_int_max_str_digits(4_000_000)

HEAD = ("/-! Generated by `tools/fs66_emit_lean.py` — **untrusted**; the kernel re-derives every\n"
        "claim from this data. -/")


def arg(flag, default=None, cast=str):
    return cast(sys.argv[sys.argv.index(flag) + 1]) if flag in sys.argv else default


def pack(points, n, w):
    """The vertex table as one natural number: the `w`-bit field at offset `w*i` holds `a*n + b`."""
    acc = 0
    for i, (a, b) in enumerate(points):
        pid = a * n + b
        assert 0 <= a < n and 0 <= b < n, f"point {i} = ({a}, {b}) is not in [0, {n})^2"
        assert pid < (1 << w), f"point {i} packs to {pid}, which needs more than {w} bits"
        acc |= pid << (w * i)
    return acc


def chunked(items, per):
    return [items[s:s + per] for s in range(0, len(items), per)]


def emit_pts(path, name, points, n, w, packed):
    body = "\n".join([
        # the smallest import that gives `ℕ`: this module must not reach the certificate's ancestors
        "import Mathlib.Data.Nat.Notation", "", HEAD, "",
        "namespace HadwigerNelson", "",
        f"/-- The {len(points)} points of `(ℤ/{n})²` this witness lists, packed into one natural-number",
        f"literal: the {w}-bit field at offset {w}·i holds `a·{n} + b` for the `i`-th point. Read by",
        f"`unpackPt {n} {w}` (`ResidueTower.lean`), which is one shift and one mask per access — where a",
        "`![…]` vector or a position-indexed `List` costs a walk of the whole table per access.",
        "",
        "Untrusted: `Instances/ZMod121Four.lean` re-derives in the kernel that every listed pair of these",
        "points really has unit quadrance modulo the modulus, which is the only property of this number",
        "anything below uses. -/",
        f"def {name}Packed : ℕ :=", f"  {packed}", "",
        "end HadwigerNelson"]) + "\n"
    path.write_text(body)


def emit_edges(path, name, nverts, edges, per_chunk, module_of_pts):
    chunks = chunked(edges, per_chunk)
    lines = ["import Proofs.HadwigerNelson.EdgeList", "", HEAD, "",
             "/-!",
             f"# The refutation's own subgraph of `UD(ℤ/121, 2)`, as an edge list on `Fin {nverts}`",
             "",
             f"**{len(edges)} pairs of the {nverts} points of `{module_of_pts}`**, in the order the DIMACS was",
             "written in. The order must not change: the certificate under `Cnf/` addresses clauses by position.",
             "",
             "A subgraph that refuses to be coloured refutes every graph it maps into, so this list is all the",
             "kernel is ever shown — never the 14,641-vertex, 966,306-edge level-two plane, whose formula is",
             "3,879,868 clauses against this one's 14,650.",
             "-/", "",
             "namespace HadwigerNelson", ""]
    for ci, ch in enumerate(chunks):
        lo, hi = ci * per_chunk, ci * per_chunk + len(ch) - 1
        lines += [f"/-- Edges {lo}–{hi}. -/",
                  f"def {name}Chunk{ci:03d} : List (Fin {nverts} × Fin {nverts}) :="]
        # eight pairs a line, wrapped
        rows, cur = [], []
        for e in ch:
            cur.append(f"({e[0]},{e[1]})")
            if len(cur) == 8:
                rows.append(", ".join(cur))
                cur = []
        if cur:
            rows.append(", ".join(cur))
        lines.append("  [" + ",\n   ".join(rows) + "]")
        lines.append("")
    lines += [f"/-- The {len(chunks)} chunks, in edge order. -/",
              f"def {name}Chunks : List (List (Fin {nverts} × Fin {nverts})) :=",
              "  [" + ",\n   ".join(f"{name}Chunk{ci:03d}" for ci in range(len(chunks))) + "]", "",
              "/-- The edge list: the chunks flattened, so the chunking cannot drift from the list the",
              "certificate is about. -/",
              f"def {name}Edges : List (Fin {nverts} × Fin {nverts}) := {name}Chunks.flatten", "",
              "end HadwigerNelson"]
    path.write_text("\n".join(lines) + "\n")


def main():
    wpath = Path(sys.argv[1])
    W = json.load(open(wpath))
    n, k = W["n"], W["k"]
    points = [tuple(p) for p in W["points"]]
    edges = [tuple(e) for e in W["edges"]]
    pin = list(W["pin"])
    nv = len(points)
    name = arg("--name", "zmod121Four")
    outdir = Path(arg("--dir", "Proofs/HadwigerNelson/Instances/ZMod121Four"))
    w = arg("--width", max(1, (n * n - 1).bit_length()), int)
    per_chunk = arg("--per-chunk", 100, int)
    segments = arg("--segments", 2, int)
    table_modules = arg("--table-modules", 8, int)
    dry = arg("--dry-run")
    if dry:
        outdir = Path(dry)

    assert edges == sorted(edges) and all(i < j for i, j in edges), "edge list must be sorted with i < j"
    assert len(set(edges)) == len(edges), "duplicate edge"
    eset = set(edges)
    for a in range(3):
        for b in range(a + 1, 3):
            assert (min(pin[a], pin[b]), max(pin[a], pin[b])) in eset, "the pin is not a listed clique"
    # the pin the emitter will write, in `cubeCNF` order, against the one the witness's proof refutes
    pins = [(pin[c], c) for c in range(len(pin))]

    packed = pack(points, n, w)
    # read the table back out the way `unpackPt` does, and compare against the witness
    mask = (1 << w) - 1
    for i, (a, b) in enumerate(points):
        pid = (packed >> (w * i)) & mask
        assert (pid // n, pid % n) == (a, b), f"packing does not round-trip at point {i}"

    module = str(outdir).replace("/", ".")
    outdir.mkdir(parents=True, exist_ok=True)
    emit_pts(outdir / "Pts.lean", name, points, n, w, packed)
    emit_edges(outdir / "Edges.lean", name, nv, edges, per_chunk, f"{module}.Pts")

    # the formula the proof refutes, built here, against the one `tools/coloring.py` will build
    scratch = Path(arg("--scratch", str(ROOT / "build" / f"fs66-emit-{name}")))
    scratch.mkdir(parents=True, exist_ok=True)
    cl = coloring.base_clauses(nv, edges, k) + coloring.pin_clauses(pins, k)
    dimacs = f"p cnf {k * nv} {len(cl)}\n" + "".join(" ".join(map(str, c)) + " 0\n" for c in cl)
    sha = hashlib.sha256(dimacs.encode()).hexdigest()
    want = W["provenance"]["cnf_sha256"]
    assert sha == want, f"CNF digest {sha[:12]}… does not match the witness's {want[:12]}…"

    text = gzip.decompress((wpath.parent / "witness.lrat.gz").read_bytes())
    psha = hashlib.sha256(text).hexdigest()
    assert psha == W["provenance"]["lrat_sha256"], "proof digest does not match the witness file"
    lrat = scratch / "witness.lrat"
    lrat.write_bytes(text)

    print(f"{nv} points, {len(edges)} edges, n = {n}, k = {k}, width {w}, "
          f"packed literal {len(str(packed))} digits; CNF {len(cl)} clauses sha {sha[:12]}…", flush=True)

    edges_json = scratch / "edges.json"
    json.dump({"edges": [list(e) for e in edges]}, open(edges_json, "w"))
    subprocess.run([sys.executable, "tools/emit_mask.py", "--edges", str(edges_json), "--n", str(nv),
                    "--edges-name", f"{name}Edges", "--import", f"{module}.Edges",
                    "--pins", repr(pins), "--colours", str(k), "--lrat", str(lrat),
                    "--name", name, "--out", f"{outdir}/Cnf", "--module", f"{module}.Cnf",
                    "--segments", str(segments), "--table-modules", str(table_modules)],
                   cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
