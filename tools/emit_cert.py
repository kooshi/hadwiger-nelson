#!/usr/bin/env python3
"""Emit a `UDCert n` Lean module from a certificate JSON. Untrusted generator.

Nothing here is believed: Lean re-derives every unit-distance claim by kernel reduction of
`UDCert.Valid`. A bug in this file can only produce data Lean refuses to certify.

Input JSON: {"names": [...], "denom": int, "coords": [[[16 ints], [16 ints]], ...],
             "edges": [[i, j], ...], "primes": [3, 5, 7, 11]}

Coefficients are in mask order over {1, √3, √5, √7, √11, √15, ...}: bit0↔√3, bit1↔√5, bit2↔√7,
bit3↔√11. `Q4` nests √11 outermost, so the depth-first re-before-im flattening of the nested pair
literal is exactly mask order.

Usage:
    tools/emit_cert.py tools/spindle.json moserSpindle Proofs/HadwigerNelson/Instances/Spindle.lean
    tools/emit_cert.py ... --chunk 250          # split ValidOn into chunks of 250 edges
"""
import json
import sys


def q4lit(coeffs):
    """Nested-pair literal for a Q4 element, 16 coefficients in mask order."""
    def tree(lo, hi):
        if hi - lo == 1:
            v = coeffs[lo]
            return f"({v})" if v < 0 else str(v)
        mid = (lo + hi) // 2
        return "⟨" + tree(lo, mid) + "," + tree(mid, hi) + "⟩"
    return tree(0, len(coeffs))


def ptlit(coord):
    return "⟨" + q4lit(coord[0]) + "," + q4lit(coord[1]) + "⟩"


def emit(data, name, chunk=None):
    n = len(data["coords"])
    edges = [tuple(e) for e in data["edges"]]
    L = []
    add = L.append

    add("import Proofs.HadwigerNelson.Certificate")
    add("")
    add("/-!")
    add(f"# `{name}` — a unit-distance certificate on {n} vertices, {len(edges)} edges")
    add("")
    add("Generated by `tools/emit_cert.py`, which is **not trusted**: `Valid` below is decided by")
    add("kernel reduction, so wrong coordinates cannot pass. When it fails, `#eval` the `badEdges`")
    add("diagnostic — it names the offending edge and the squared distance actually found.")
    add("-/")
    add("")
    add("set_option maxRecDepth 100000")
    add("")
    add("namespace HadwigerNelson")
    add("")
    add(f"/-- The {n} vertices, coordinates exact in `ℚ(√3,√5,√7,√11)` and scaled by")
    add(f"`{data['denom']}` so every leaf is an integer. -/")
    add(f"def {name}Verts : Fin {n} → Pt :=")
    add("  ![" + ",\n    ".join(ptlit(c) for c in data["coords"]) + "]")
    add("")
    add(f"/-- The {len(edges)} claimed unit-distance pairs. -/")
    add(f"def {name}Edges : List (Fin {n} × Fin {n}) :=")
    add("  [" + ", ".join(f"({i},{j})" for i, j in edges) + "]")
    add("")
    add(f"/-- The certificate. -/")
    add(f"def {name} : UDCert {n} where")
    add(f"  verts := {name}Verts")
    add(f"  edges := {name}Edges")
    add(f"  denom := {data['denom']}")
    add("")

    if chunk is None or len(edges) <= chunk:
        add(f"/-- Every listed edge has exact squared distance `{data['denom']}²`. Kernel-checked. -/")
        add(f"theorem {name}_valid : {name}.Valid = true := by decide")
    else:
        slices = [edges[i:i + chunk] for i in range(0, len(edges), chunk)]
        for k, sl in enumerate(slices):
            add(f"/-- Edges {k * chunk}–{k * chunk + len(sl) - 1}. -/")
            add(f"def {name}Chunk{k} : List (Fin {n} × Fin {n}) :=")
            add("  [" + ", ".join(f"({i},{j})" for i, j in sl) + "]")
            add(f"theorem {name}Chunk{k}_valid : {name}.ValidOn {name}Chunk{k} = true := by decide")
            add("")
        add(f"/-- Every listed edge has exact squared distance `{data['denom']}²`, glued from the")
        add("chunks above. The chunk theorems are *cited*, never re-decided — `by decide` here would")
        add("redo every edge and double the cost. -/")
        add(f"theorem {name}_valid : {name}.Valid = true :=")
        add(f"  {name}.valid_of_chunks [" + ", ".join(f"{name}Chunk{k}" for k in range(len(slices))) + "]")
        add("    (by rfl) (by")
        add("      intro ch hch")
        add("      fin_cases hch")
        add("      exacts [" + ", ".join(f"{name}Chunk{k}_valid" for k in range(len(slices))) + "])")
    add("")
    add("end HadwigerNelson")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    src, name, dst = sys.argv[1], sys.argv[2], sys.argv[3]
    chunk = None
    if "--chunk" in sys.argv:
        chunk = int(sys.argv[sys.argv.index("--chunk") + 1])
    data = json.load(open(src))
    open(dst, "w").write(emit(data, name, chunk))
    print(f"{dst}: {len(data['coords'])} vertices, {len(data['edges'])} edges, "
          f"denom {data['denom']}", file=sys.stderr)
