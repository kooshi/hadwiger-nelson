#!/usr/bin/env python3
"""Emit a `UDCert n` from a certificate JSON, as one module or as a directory. Untrusted generator.

Nothing here is believed: Lean re-derives every unit-distance claim by kernel reduction of
`UDCert.Valid`. A bug in this file can only produce data Lean refuses to certify.

Input JSON: {"names": [...], "denom": int, "coords": [[[16 ints], [16 ints]], ...],
             "edges": [[i, j], ...], "primes": [3, 5, 7, 11]}

Coefficients are in mask order over {1, √3, √5, √7, √11, √15, ...}: bit0↔√3, bit1↔√5, bit2↔√7,
bit3↔√11. `Q4` nests √11 outermost, so the depth-first re-before-im flattening of the nested pair
literal is exactly mask order.

## Two output shapes, and why

A certificate small enough to elaborate in one go gets **one module** (`--out FILE`). De Grey's does
not: measured at v4.32.0 the geometry costs ~0.054 s and ~1.8 MB per edge, so 7877 edges want ~7
minutes of kernel time and more memory than one process should hold. Those get a **directory**
(`--dir DIR`), split so that the pieces build in parallel:

    Table.lean    the points, as a `PtTable` — one module, because defining it costs ~32 s and
                  ~3.8 GB, and that is paid per module that *defines* it, not per importer
    Edges.lean    the edge list, already cut into chunks; `edges := chunks.flatten`, so the
                  certificate and the chunking cannot drift and the join proof is `rfl`
    Geom00..NN    the geometry, `--per-module` chunks each, one `decide +kernel` per chunk
    Valid.lean    the glue: `valid_of_chunks`, citing the chunk theorems, never re-deciding

`--skeleton` emits `sorry` in place of every geometry proof — the specification without the eight
minutes, for validating the shape before spending them.

Usage:
    tools/emit_cert.py tools/spindle.json moserSpindle --out Proofs/.../Instances/Spindle.lean
    tools/emit_cert.py tools/degrey_cert.json deGrey --dir Proofs/.../Instances/DeGrey
    tools/emit_cert.py tools/degrey_cert.json deGrey --dir ... --skeleton
"""
import json
import os
import sys

CHUNK = 50          # edges per `ValidOn` theorem
PER_MODULE = 10     # chunks per geometry module


def q4lit(coeffs):
    """Nested-pair literal for a Q4 element, 16 coefficients in mask order."""
    def tree(lo, hi):
        if hi - lo == 1:
            v = coeffs[lo]
            return f"({v})" if v < 0 else str(v)
        mid = (lo + hi) // 2
        return "⟨" + tree(lo, mid) + "," + tree(mid, hi) + "⟩"
    return tree(0, len(coeffs))


def ptlit(coord):
    return "⟨" + q4lit(coord[0]) + "," + q4lit(coord[1]) + "⟩"


def tablelit(coords, lo, hi):
    """A `PtTable` covering indices [lo, hi), split at the midpoint. No padding: the tree is
    ragged when the count is not a power of two, which is why `PtTable` splits at a stored pivot
    rather than on the bits of the index."""
    if hi - lo == 1:
        return "(PtTable.leaf " + ptlit(coords[lo]) + ")"
    mid = (lo + hi) // 2
    return f"(PtTable.node {mid - lo} " + tablelit(coords, lo, mid) + " " + \
        tablelit(coords, mid, hi) + ")"


def edgelist(n, edges):
    return f"List (Fin {n} × Fin {n}) :=\n  [" + ", ".join(f"({i},{j})" for i, j in edges) + "]"


def chunk_name(name, k):
    return f"{name}Chunk{k:03d}"


# ---------------------------------------------------------------- single module

def emit_one(data, name):
    n, edges = len(data["coords"]), [tuple(e) for e in data["edges"]]
    L = [f"import Proofs.HadwigerNelson.Certificate", "",
         "/-!",
         f"# `{name}` — a unit-distance certificate on {n} vertices, {len(edges)} edges",
         "",
         "Generated by `tools/emit_cert.py`, which is **not trusted**: `Valid` below is decided by",
         "kernel reduction, so wrong coordinates cannot pass. When it fails, `#eval` the `badEdges`",
         "diagnostic — it names the offending edge and the squared distance actually found.",
         "-/", "",
         "namespace HadwigerNelson", "",
         f"/-- The {n} vertices, coordinates exact in `ℚ(√3,√5,√7,√11)` and scaled by",
         f"`{data['denom']}` so every leaf is an integer. -/",
         f"def {name}Table : PtTable :=", "  " + tablelit(data["coords"], 0, n), "",
         f"/-- The {len(edges)} claimed unit-distance pairs. -/",
         f"def {name}Edges : " + edgelist(n, edges), "",
         "/-- The certificate. -/",
         f"def {name} : UDCert {n} where",
         f"  verts := {name}Table.toVerts",
         f"  edges := {name}Edges",
         f"  denom := {data['denom']}", "",
         f"/-- Every listed edge has exact squared distance `{data['denom']}²`. Kernel-checked. -/",
         f"theorem {name}_valid : {name}.Valid = true := by decide +kernel", "",
         "end HadwigerNelson"]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------- directory

def emit_dir(data, name, mod, skeleton):
    """`mod` is the Lean module prefix of the output directory, e.g.
    `Proofs.HadwigerNelson.Instances.DeGrey`. Returns {filename: contents}."""
    n, edges = len(data["coords"]), [tuple(e) for e in data["edges"]]
    chunks = [edges[i:i + CHUNK] for i in range(0, len(edges), CHUNK)]
    groups = [range(i, min(i + PER_MODULE, len(chunks)))
              for i in range(0, len(chunks), PER_MODULE)]
    out = {}

    out["Table.lean"] = "\n".join([
        "import Proofs.HadwigerNelson.Certificate", "",
        "/-!",
        f"# `{name}` — the {n} vertices",
        "",
        f"Coordinates are exact in `ℚ(√3,√5,√7,√11)`, scaled by `{data['denom']}` so every leaf is",
        "an integer. Generated by `tools/emit_cert.py`; **not trusted** — see `Valid.lean`.",
        "",
        "This table gets a module to itself because *defining* it is the expensive part (~32 s,",
        "~3.8 GB at v4.32.0) and that cost is paid per module that defines it. Importing the",
        "compiled table is free, so every geometry module below imports rather than repeats it.",
        "-/", "",
        "set_option maxHeartbeats 2000000",
        "set_option maxRecDepth 100000", "",
        "namespace HadwigerNelson", "",
        f"/-- The {n} vertices. -/",
        f"def {name}Table : PtTable :=", "  " + tablelit(data["coords"], 0, n), "",
        "end HadwigerNelson"]) + "\n"

    E = [f"import {mod}.Table", "",
         "/-!",
         f"# `{name}` — the certificate, and the {len(edges)} claimed edges in {len(chunks)} chunks",
         "",
         f"The edge list is **defined as** the chunks flattened, not written twice. That keeps the",
         "certificate and the chunking from drifting, makes `valid_of_chunks`' join hypothesis",
         "`rfl`, and preserves the edge order — which later milestones' certificates index by",
         "position, so it must not change.",
         "-/", "",
         "namespace HadwigerNelson", ""]
    for k, ch in enumerate(chunks):
        E.append(f"/-- Edges {k * CHUNK}–{k * CHUNK + len(ch) - 1}. -/")
        E.append(f"def {chunk_name(name, k)} : " + edgelist(n, ch))
    E += ["", f"/-- The {len(chunks)} chunks, in edge order. -/",
          f"def {name}Chunks : List (List (Fin {n} × Fin {n})) :=",
          "  [" + ",\n   ".join(chunk_name(name, k) for k in range(len(chunks))) + "]", "",
          "/-- The certificate. -/",
          f"def {name} : UDCert {n} where",
          f"  verts := {name}Table.toVerts",
          f"  edges := {name}Chunks.flatten",
          f"  denom := {data['denom']}", "",
          "end HadwigerNelson"]
    out["Edges.lean"] = "\n".join(E) + "\n"

    tac = "sorry" if skeleton else "by decide +kernel"
    for g, ks in enumerate(groups):
        lo, hi = ks[0] * CHUNK, min((ks[-1] + 1) * CHUNK, len(edges))
        G = [f"import {mod}.Edges", "",
             "/-!",
             f"# `{name}` — geometry for edges {lo}–{hi - 1}",
             "",
             "One `decide +kernel` per chunk: the kernel evaluates the check once, where plain",
             "`decide` evaluates it twice (elaborator, then kernel) and exhausts the heartbeat",
             "budget past ~250 edges. Many small chunks rather than one large one — each",
             "reduction is transient, so the module's peak memory tracks the chunk, not the module.",
             "-/", "",
             "namespace HadwigerNelson", ""]
        for k in ks:
            G.append(f"theorem {chunk_name(name, k)}_valid : "
                     f"{name}.ValidOn {chunk_name(name, k)} = true := {tac}")
        G += ["", "end HadwigerNelson"]
        out[f"Geom{g:02d}.lean"] = "\n".join(G) + "\n"

    V = [f"import {mod}.Geom{g:02d}" for g in range(len(groups))]
    V += ["",
          "/-!",
          f"# `{name}` — the geometry, glued",
          "",
          f"The {len(chunks)} chunk theorems are **cited**, never re-decided: `by decide +kernel`",
          "here would redo every edge and double the cost of the milestone.",
          "-/", "",
          "namespace HadwigerNelson", "",
          f"/-- **Every one of the {len(edges)} listed edges has exact squared distance",
          f"`{data['denom']}²`** — so every one of them is a real unit distance in the plane.",
          "Kernel-checked, chunk by chunk. -/",
          f"theorem {name}_valid : {name}.Valid = true :=",
          f"  {name}.valid_of_chunks {name}Chunks rfl",
          "    (List.forall_iff_forall_mem.mp",
          "      ⟨" + ",\n       ".join(f"{chunk_name(name, k)}_valid" for k in range(len(chunks)))
          + "⟩)", "",
          "end HadwigerNelson"]
    out["Valid.lean"] = "\n".join(V) + "\n"
    return out


if __name__ == "__main__":
    src, name = sys.argv[1], sys.argv[2]
    data = json.load(open(src))
    skeleton = "--skeleton" in sys.argv
    if "--out" in sys.argv:
        dst = sys.argv[sys.argv.index("--out") + 1]
        open(dst, "w").write(emit_one(data, name))
        wrote = [dst]
    else:
        d = sys.argv[sys.argv.index("--dir") + 1]
        mod = d.rstrip("/").replace("/", ".")
        os.makedirs(d, exist_ok=True)
        wrote = []
        for fn, body in emit_dir(data, name, mod, skeleton).items():
            open(os.path.join(d, fn), "w").write(body)
            wrote.append(os.path.join(d, fn))
    print(f"{len(data['coords'])} vertices, {len(data['edges'])} edges, denom {data['denom']}"
          + ("  [skeleton: geometry sorried]" if skeleton else ""), file=sys.stderr)
    for w in wrote:
        print(f"  {w}", file=sys.stderr)
