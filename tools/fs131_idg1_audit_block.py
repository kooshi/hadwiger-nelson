#!/usr/bin/env python3
"""FS131-IDG1 (FS131-IN1L's `tools/fs131_in1l_audit_block.py`, for this job's modules) — the draft block for `scripts/Axioms.lean`'s CLEAN section: one `#print axioms` line per PUBLIC record
of this job's six modules whose axioms are a subset of the standard three, read from the output of
`data/fs131/idg1/lean/Axioms.lean` on the built tree (the one record resting on `sorryAx`, `exists_admissiblePair`,
lane A's leaf, is left out and listed in a comment; the `DOWNSTREAM` rows are not this job's and are skipped).  Generated names Lean
makes on demand (`.congr_simp`, `.eq_n`, `.induct`, …) are left out: no author declares them.

Usage: fs131_idg1_audit_block.py <axioms.txt> > <block.lean>
Exit 2 if the input holds no record (a block from a broken read is never written as an empty block).
"""
import sys

STANDARD = {"propext", "Classical.choice", "Quot.sound"}
GENERATED = (".congr_simp", ".eq_def", ".induct", ".splitter")
# what `structure` generates beside the fields (the fields themselves — `AdmissiblePair.u`, `.w`, `.injective`,
# `.generates` — are kept: the file declares them)
STRUCTURE_GENERATED = (".casesOn", ".ctorIdx", ".mk.inj", ".mk.injEq", ".mk.noConfusion", ".mk.sizeOf_spec",
                       ".noConfusion", ".noConfusionType", ".recOn")


def main():
    rows = []
    for ln in open(sys.argv[1]).read().splitlines():
        if not ln.startswith("AXIOMS ") or ln.startswith("AXIOMS-COUNT"):
            continue
        head, axs = ln.split(" : ", 1)
        _, mod, kind, name = head.split(" ")
        body = axs.strip()[1:-1].strip()
        ax = set() if not body else {x.strip() for x in body.split(",")}
        if mod == "PLANT" or mod.startswith("DOWNSTREAM-") or kind != "public":
            continue
        if any(g in name for g in GENERATED) or ".eq_" in name or name.endswith(STRUCTURE_GENERATED):
            continue
        rows.append((mod, name, ax))
    if not rows:
        print("no records read", file=sys.stderr)
        sys.exit(2)
    out = ["/-! ## FS131-IDG1 — the dual of a countable group (`Rigidity/DualGroup`), Pontryagin duality",
           "(`Rigidity/Annihilator`, `SubgroupHaar`, `Duality`, `DualConnected`) and the unit circle (`Rigidity/UnitCircle`);",
           "generated by `tools/fs131_idg1_audit_block.py` -/",
           "-- FS131-IDG1"]
    left = []
    cur = None
    for mod, name, ax in rows:
        if not ax <= STANDARD:
            left.append(f"--   {name} : {sorted(ax)}")
            continue
        if mod != cur:
            out.append(f"-- {mod.removeprefix('Proofs.HadwigerNelson.').replace('.', '/')}")
            cur = mod
        out.append(f"#print axioms {name}")
    if left:
        out.append("-- left out (it rests on `sorryAx`, its own: lane A's leaf, not this job's):")
        out.extend(left)
    print("\n".join(out))


if __name__ == "__main__":
    main()
