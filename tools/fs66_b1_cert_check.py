class Refusal(Exception):
    """the file is not a valid certificate; `code` is from the closed list, `detail` says what, where, next."""

    def __init__(self, code, detail):
        super().__init__(f'{code}: {detail}')
        self.code = code
        self.detail = detail


class CheckerError(Exception):
    """the checker could not do its job -- never the file's fault."""

    def __init__(self, code, detail):
        super().__init__(f'{code}: {detail}')
        self.code = code
        self.detail = detail


# ----------------------------------------------------------------------------- strict reading of integers

class NotAnInteger:
    """what the JSON parser returns where a float or a JSON constant stood, so the refusal can name the path."""

    def __init__(self, kind, text):
        self.kind = kind
        self.text = text

    def __repr__(self):
        return f'the {self.kind} {self.text}'


def describe(v):
    if isinstance(v, NotAnInteger):
        return repr(v)
    if isinstance(v, bool):
        return f'the boolean {"true" if v else "false"}'
    if isinstance(v, str):
        return f'the string "{v[:40]}"'
    if v is None:
        return 'null'
    if isinstance(v, list):
        return f'a list of {len(v)} entries'
    if isinstance(v, dict):
        return 'an object'
    return f'{v!r}'


def need_int(v, path):
    if isinstance(v, bool) or not isinstance(v, int):
        raise Refusal('NOT_AN_INTEGER', f'{path} is {describe(v)}, not a JSON integer. Every number in a '
                                        f'certificate is an exact integer over one scale; a float cannot be '
                                        f'read back exactly, so the producer must write integers only.')
    return v


def need_list(v, path):
    if not isinstance(v, list):
        raise Refusal('MALFORMED', f'{path} is {describe(v)}, not a list.')
    return v


def need_str(v, path, allowed=None):
    if not isinstance(v, str):
        raise Refusal('MALFORMED', f'{path} is {describe(v)}, not a string.')
    if allowed is not None and v not in allowed:
        raise Refusal('MALFORMED', f'{path} is "{v}"; the only values this format has are '
                                   f'{", ".join(repr(a) for a in allowed)}.')
    return v


def load_json_strict(path):
    """every float in the file becomes a sentinel, so that the refusal can say WHERE the float was."""
    try:
        with open(path, 'rb') as f:
            raw = f.read()
    except OSError as ex:
        hint = ''
        if not os.path.exists(path):
            near = sorted(f for f in os.listdir(CERT_DIR) if f.endswith('.json')) \
                if os.path.isdir(CERT_DIR) else []
            if near:
                hint = (f' The certificates in this repository are '
                        f'{", ".join(os.path.join(os.path.relpath(CERT_DIR, REPO), f) for f in near)}.')
        raise CheckerError('CANNOT_READ', f'{path}: {ex.strerror or ex}.{hint}')
    try:
        doc = json.loads(raw.decode('utf-8'),
                         parse_float=lambda s: NotAnInteger('float', s),
                         parse_constant=lambda s: NotAnInteger('JSON constant', s))
    except (ValueError, UnicodeDecodeError) as ex:
        raise CheckerError('CANNOT_READ', f'{path} is not JSON text: {ex}')
    return doc, hashlib.sha256(raw).hexdigest()


def is_prime(m):
    if m < 2:
        return False
    if m % 2 == 0:
        return m == 2
    d = 3
    while d * d <= m:
        if m % d == 0:
            return False
        d += 2
    return True


def least_factor(m):
    d = 2
    while d * d <= m:
        if m % d == 0:
            return d
        d += 1
    return m


def dec_str(num, den, places=6):
    """the exact rational num/den truncated toward zero, with an ellipsis when truncation lost something."""
    neg = (num < 0) != (den < 0)
    a, b = abs(num), abs(den)
    whole, rem = divmod(a, b)
    frac, rem2 = divmod(rem * 10 ** places, b)
    return f'{"-" if neg else ""}{whole}.{frac:0{places}d}' + ('' if rem2 == 0 else '…')


def short_int(v, digits=45):
    """exact up to `digits` digits, then an abbreviation WITH the digit count.

    The cut is 45 because every quantity a reader compares here -- a scale, a U_num, m*U_num, a row
    multiplier -- is under 40 digits and must print exactly: two numbers differing in their last place
    must never print as the same string. Only the elimination's minors (hundreds of digits) abbreviate,
    and there the sign is the whole content."""
    s = str(v)
    body = s.lstrip('-')
    if len(body) <= digits:
        return s
    return f'{"-" if v < 0 else ""}{body[0]}.{body[1:7]}e+{len(body) - 1} ({len(body)} digits)'


# ----------------------------------------------------------------------------- the plane, rebuilt from p

class Plane:
    """the n points of F_p^2, the unit circle, the 2(p+1) linear maps -- built from p and nothing else."""

    def __init__(self, p):
        self.p = p
        n = self.n = p * p
        self.ADD = [[0] * n for _ in range(n)]
        self.SUB = [[0] * n for _ in range(n)]
        for x in range(n):
            ax, bx = divmod(x, p)
            add, sub = self.ADD[x], self.SUB[x]
            for y in range(n):
                ay, by = divmod(y, p)
                add[y] = ((ax + ay) % p) * p + ((bx + by) % p)
                sub[y] = ((ay - ax) % p) * p + ((by - bx) % p)
        self.S = tuple(a * p + b for a in range(p) for b in range(p) if (a * a + b * b) % p == 1)
        maps = []
        for s in self.S:
            c, d = divmod(s, p)
            rot, ref = [], []
            for z in range(n):
                a, b = divmod(z, p)
                rot.append(((a * c - b * d) % p) * p + ((a * d + b * c) % p))       # z |-> s*z
                ref.append(((a * c + b * d) % p) * p + ((a * d - b * c) % p))       # z |-> s*conj(z)
            maps.append(tuple(rot))
            maps.append(tuple(ref))
        self.maps = tuple(maps)

    def verify_maps(self):
        """each map a bijection with h(x+s) - h(x) in S for every x and s -- the one property soundness uses.

        Failure is a bug in THIS program (the maps are rebuilt here from p), never the certificate's fault,
        so it raises ERROR SELF_CHECK_FAILED.  The check is generic: it never assumes the maps are linear."""
        n, S = self.n, self.S
        if len(S) != self.p + 1:
            raise CheckerError('SELF_CHECK_FAILED',
                               f'the unit circle of F_{self.p}^2 came out with {len(S)} points, not p + 1 = '
                               f'{self.p + 1}; the checker rebuilt it wrongly.')
        inS = [False] * n
        for s in S:
            inS[s] = True
        pairs = 0
        for idx, h in enumerate(self.maps):
            if sorted(h) != list(range(n)):
                raise CheckerError('SELF_CHECK_FAILED', f'rebuilt linear map {idx} is not a bijection of the '
                                                        f'{n} points.')
            for x in range(n):
                hx_row = self.SUB[h[x]]
                add_x = self.ADD[x]
                for s in S:
                    if not inS[hx_row[h[add_x[s]]]]:
                        raise CheckerError('SELF_CHECK_FAILED',
                                           f'rebuilt map {idx} moves the unit vector {divmod(s, self.p)} at '
                                           f'the point {divmod(x, self.p)} off the unit circle.')
                    pairs += 1
        return pairs

    def representatives(self, times):
        """reps("1") = phi_0, then phi_{-h} phi_h one per class {h,-h} by ascending smaller index;
           reps("q") = phi_0.  (Any list of monomials of degree <= 2 would be sound -- see the docstring --
           but the file does not carry one, so this list IS the specification.)"""
        if times == 'q':
            return [(0,)]
        p, n = self.p, self.n
        reps = [(0,)]
        seen = set()
        for h in range(n):
            if h in seen:
                continue
            mh = self.SUB[h][0]                       # -h
            seen.add(h)
            seen.add(mh)
            reps.append(tuple(sorted((mh, h))))
        return reps


class Canon:
    """canonical forms of monomials (sorted tuples of at most four point indices).

    Two memos.  The outer one normalises by TRANSLATION only -- canon is translation invariant because the
    translates of m are exactly the translates of any translate of m -- and the inner one runs the full
    minimisation over (origin in m) x (verified linear map).  The split matters because the products
    a * tau_t(a') and a' * tau_{-t}(a) are translates of one another, so the expensive half runs once for the
    two of them."""

    def __init__(self, plane):
        self.plane = plane
        self.tmemo = {}
        self.cmemo = {}
        self.index = {}
        self.list = []

    def canon(self, m):
        m = tuple(sorted(m))
        t = self.tmemo.get(m)
        if t is None:
            if m:
                SUB = self.plane.SUB
                best = None
                for x in set(m):
                    row = SUB[x]
                    c = sorted(row[y] for y in m)
                    if best is None or c < best:
                        best = c
                t = tuple(best)
            else:
                t = m
            self.tmemo[m] = t
        c = self.cmemo.get(t)
        if c is None:
            c = self._full(t)
            self.cmemo[t] = c
        return c

    def _full(self, t):
        if not t:
            return t
        SUB, maps = self.plane.SUB, self.plane.maps
        best = None
        for x in set(t):
            row = SUB[x]
            tr = [row[y] for y in t]
            for h in maps:
                c = sorted(map(h.__getitem__, tr))
                if best is None or c < best:
                    best = c
        return tuple(best)

    def idx(self, m):
        c = self.canon(m)
        i = self.index.get(c)
        if i is None:
            i = len(self.list)
            self.index[c] = i
            self.list.append(c)
        return i


# ----------------------------------------------------------------------------- the certificate, parsed

class Cert:
    def __init__(self, doc, path, sha):
        self.path = path
        self.sha256 = sha
        if not isinstance(doc, dict):
            raise Refusal('MALFORMED', f'the file is {describe(doc)}, not a JSON object.')
        for k in doc:
            if k not in TOP_KEYS and k not in TOP_OPTIONAL:
                near = [c for c in TOP_KEYS if sorted(c) == sorted(k)]
                hint = f' Did you mean "{near[0]}"?' if near else ''
                raise Refusal('MALFORMED', f'unknown top-level key "{k}". The keys of {FORMAT} are '
                                           f'{", ".join(TOP_KEYS)} (plus the ignored provenance keys '
                                           f'{", ".join(TOP_OPTIONAL)}).{hint} An unknown key is refused '
                                           f'rather than ignored, so that a misspelt field cannot be read '
                                           f'as an absent one.')
        for k in TOP_KEYS:
            if k not in doc:
                raise Refusal('MALFORMED', f'the file has no "{k}" key.')
        need_str(doc['format'], '"format"', (FORMAT,))
        self.has_provenance = [k for k in TOP_OPTIONAL if k in doc]

        p = need_int(doc['p'], '"p"')
        if p < 2 or not is_prime(p):
            f = least_factor(p) if p >= 2 else None
            why = f' ({p} = {f} x {p // f})' if f and f != p else ''
            raise Refusal('BAD_PRIME', f'"p" is {p}, which is not a prime{why}. This checker\'s group, its '
                                       f'counts and the statement it licenses were written and verified only '
                                       f'for a prime p = 3 (mod 4) -- the anisotropic case, where the unit '
                                       f'circle has p + 1 points. Nothing here was examined otherwise.')
        if p % 4 != 3:
            raise Refusal('BAD_PRIME', f'"p" is {p}, a prime congruent to {p % 4} modulo 4. This checker '
                                       f'handles only p = 3 (mod 4): for p = 1 (mod 4) the circle '
                                       f'x^2 + y^2 = 1 is a different object (it has p - 1 points and -1 is a '
                                       f'square), and nothing in this plan was examined for that case.')
        self.p = p
        self.n = n = p * p

        self.scale = need_int(doc['scale'], '"scale"')
        self.U_num = need_int(doc['U_num'], '"U_num"')

        self.weights = []
        for i, w in enumerate(need_list(doc['weights'], '"weights"')):
            w = need_list(w, f'weights[{i}]')
            if len(w) != n + 1:
                raise Refusal('MALFORMED', f'weights[{i}] has {len(w)} entries; a weight vector over '
                                           f'{{[]}} + V has 1 + n = {n + 1} (the constant, then one per '
                                           f'point index 0..{n - 1}). Is the file\'s "p" = {p} the prime it '
                                           f'was made for?')
            self.weights.append([need_int(v, f'weights[{i}][{j}]') for j, v in enumerate(w)])

        self.blocks = []
        for i, b in enumerate(need_list(doc['blocks'], '"blocks"')):
            if not isinstance(b, dict):
                raise Refusal('MALFORMED', f'blocks[{i}] is {describe(b)}, not an object.')
            for k in ('times', 'weights', 'R'):
                if k not in b:
                    raise Refusal('MALFORMED', f'blocks[{i}] has no "{k}" key.')
            times = need_str(b['times'], f'blocks[{i}]["times"]', ('1', 'q'))
            widx = []
            for j, v in enumerate(need_list(b['weights'], f'blocks[{i}]["weights"]')):
                v = need_int(v, f'blocks[{i}]["weights"][{j}]')
                if not 0 <= v < len(self.weights):
                    raise Refusal('MALFORMED', f'blocks[{i}]["weights"][{j}] is {v}, not an index into the '
                                               f'{len(self.weights)} weight vectors.')
                widx.append(v)
            R = need_list(b['R'], f'blocks[{i}]["R"]')
            size = len(R)
            M = []
            for r, row in enumerate(R):
                row = need_list(row, f'blocks[{i}]["R"][{r}]')
                if len(row) != size:
                    raise Refusal('MALFORMED', f'blocks[{i}]["R"] is {size} x {len(row)} at row {r}; a block '
                                               f'matrix is square.')
                M.append([need_int(v, f'blocks[{i}]["R"][{r}][{c}]') for c, v in enumerate(row)])
            for r in range(size):
                for c in range(r + 1, size):
                    if M[r][c] != M[c][r]:
                        raise Refusal('MALFORMED', f'blocks[{i}]["R"] is not symmetric: entry [{r}][{c}] is '
                                                   f'{short_int(M[r][c])} and [{c}][{r}] is '
                                                   f'{short_int(M[c][r])}. Only a symmetric matrix is '
                                                   f'tested for positive definiteness here, so a '
                                                   f'non-symmetric one is refused rather than symmetrised.')
            # The block is indexed by the constant and the representative monomials, whose number depends
            # only on p: 1 + (n+1)/2 of degree <= 2 for times "1", and 1 (phi_0) for times "q".
            want = 2 if times == 'q' else 2 + (n + 1) // 2
            if size != want:
                raise Refusal('MALFORMED', f'blocks[{i}]["R"] is {size} x {size}; a block with times '
                                           f'"{times}" is indexed by the constant and the '
                                           f'{want - 1} representative monomials at p = {p}, so it must be '
                                           f'{want} x {want}.')
            self.blocks.append({'times': times, 'weights': widx, 'R': M, 'size': size})

        self.rows = []
        for i, r in enumerate(need_list(doc['rows'], '"rows"')):
            r = need_list(r, f'rows[{i}]')
            if len(r) != 3:
                raise Refusal('MALFORMED', f'rows[{i}] has {len(r)} entries; a row is [A, B, lam].')
            A = [need_int(v, f'rows[{i}][0][{j}]') for j, v in enumerate(need_list(r[0], f'rows[{i}][0]'))]
            B = [need_int(v, f'rows[{i}][1][{j}]') for j, v in enumerate(need_list(r[1], f'rows[{i}][1]'))]
            lam = need_int(r[2], f'rows[{i}][2]')
            self.rows.append((A, B, lam))


def check_rows_shape(cert):
    n = cert.n
    worst = 0
    for i, (A, B, lam) in enumerate(cert.rows):
        if len(A) + len(B) > 4:
            raise Refusal('MALFORMED', f'rows[{i}] is a box product of degree {len(A) + len(B)}; the moment '
                                       f'variables of this certificate are monomials of degree at most 4, so '
                                       f'a row with more than four points names no variable.')
        worst = max(worst, len(A) + len(B))
        for which, lst in (('0', A), ('1', B)):
            for j, x in enumerate(lst):
                if not 0 <= x < n:
                    raise Refusal('MALFORMED', f'rows[{i}][{which}][{j}] is {x}, not a point index in '
                                               f'[0, {n}) of the plane over F_{cert.p}.')
    return worst


# ----------------------------------------------------------------------------- positive definiteness

def first_nonpositive_minor(R):
    """Bareiss fraction-free elimination.  Its k-th pivot IS the k-th leading principal minor of R, and
    every division is exact.  Returns (0, None) when every leading principal minor is positive -- which by
    Sylvester's criterion is exactly positive definiteness -- else (k, minor_k) for the first bad one."""
    size = len(R)
    M = [row[:] for row in R]
    prev = 1
    for k in range(size):
        piv = M[k][k]
        if piv <= 0:
            return k + 1, piv
        for i in range(k + 1, size):
            Mi, Mk = M[i], M[k]
            a = Mi[k]
            for j in range(k + 1, size):
                num = Mi[j] * piv - a * Mk[j]
                qt, rem = divmod(num, prev)
                if rem:
                    raise CheckerError('SELF_CHECK_FAILED',
                                       f'the fraction-free elimination divided {num} by {prev} with a '
                                       f'remainder at step {k}, entry ({i},{j}); Bareiss says it cannot, so '
                                       f'this program is wrong.')
                Mi[j] = qt
        prev = piv
    return 0, None


def ldl_exact(R):
    """R = L D L^T over the rationals, L unit lower triangular.  Returns (L, D) or (None, k) at a zero pivot
    (a zero leading minor: not positive definite).  The caller re-multiplies and compares, so the
    elimination code itself is off the trust surface."""
    size = len(R)
    L = [[Fraction(1) if i == j else Fraction(0) for j in range(size)] for i in range(size)]
    D = [Fraction(0)] * size
    for j in range(size):
        D[j] = Fraction(R[j][j]) - sum(L[j][k] * L[j][k] * D[k] for k in range(j))
        if D[j] == 0:
            return None, j + 1
        for i in range(j + 1, size):
            L[i][j] = (Fraction(R[i][j]) - sum(L[i][k] * L[j][k] * D[k] for k in range(j))) / D[j]
    return L, D


def ldl_verdict(R):
    """(0, None) if positive definite, else (k, D_k).  Verifies L D L^T = R entry by entry first."""
    L, D = ldl_exact(R)
    if L is None:
        return D, Fraction(0)
    size = len(R)
    for i in range(size):
        for j in range(size):
            s = sum(L[i][k] * D[k] * L[j][k] for k in range(size))
            if s != R[i][j]:
                raise CheckerError('SELF_CHECK_FAILED',
                                   f'the exact L*D*L^T does not reproduce the block at entry ({i},{j}): '
                                   f'{s} against {R[i][j]}.')
    for k in range(size):
        if D[k] <= 0:
            return k + 1, D[k]
    return 0, None


# ----------------------------------------------------------------------------- the identity

def box_terms(A, B):
    """prod_A phi * prod_B (1 - phi) expanded: one (monomial, sign) per subset of the POSITIONS of B."""
    out = []
    k = len(B)
    A = tuple(A)
    for mask in range(1 << k):
        sub = tuple(B[i] for i in range(k) if (mask >> i) & 1)
        out.append((A + sub, -1 if bin(mask).count('1') & 1 else 1))
    return out


class Forms:
    """the linear forms the identity needs, as dictionaries {canonical monomial index: integer}."""

    def __init__(self, plane, canon):
        self.plane = plane
        self.canon = canon
        self._q = {}

    def y(self, m):
        return {self.canon.idx(m): 1}

    def q(self, m):
        """Q(m) = the moment of q * m, with the hand-proved constant c = 2 built in:
             2 * sum_x y(m + x)  -  2 * sum_x y(m + x + x)  -  sum_x sum_{s in S} y(m + x + (x+s)).
        Memoised on canon(m): for a group element gamma, substituting x -> gamma(x) and using the verified
        property that s -> gamma(x+s) - gamma(x) permutes S shows Q(gamma m) and Q(m) are the same form."""
        key = self.canon.canon(m)
        got = self._q.get(key)
        if got is not None:
            return got
        base = tuple(key)
        n, S, ADD, idx = self.plane.n, self.plane.S, self.plane.ADD, self.canon.idx
        d = {}
        for x in range(n):
            i = idx(base + (x,))
            d[i] = d.get(i, 0) + 2
            i = idx(base + (x, x))
            d[i] = d.get(i, 0) - 2
            row = ADD[x]
            for s in S:
                i = idx(base + (x, row[s]))
                d[i] = d.get(i, 0) - 1
        d = {k: v for k, v in d.items() if v}
        self._q[key] = d
        return d

    def value(self, times, m):
        return self.y(m) if times == '1' else self.q(m)


def accumulate_identity(cert, plane, canon, narrate):
    """the right-hand side of the identity as a dict {canonical monomial index: integer}."""
    forms = Forms(plane, canon)
    n = plane.n
    acc = {}

    def add(form, c):
        if not c:
            return
        for k, v in form.items():
            acc[k] = acc.get(k, 0) + c * v

    # the table F(a, a', t) = canon(a * tau_t(a')), shared by every block with times "1".
    reps1 = plane.representatives('1')
    need_table = any(b['times'] == '1' for b in cert.blocks)
    F = None
    if need_table:
        t0 = time.monotonic()
        nr = len(reps1)
        narrate(f'  products a * tau_t(a\'): {nr} x {nr} representative pairs x {n} shifts = '
                f'{nr * nr * n} canonical forms')
        F = []
        for i, a in enumerate(reps1):
            rowi = []
            for a2 in reps1:
                rowi.append([canon.idx(a + tuple(plane.ADD[t][y] for y in a2)) for t in range(n)])
            F.append(rowi)
            if nr > 8 and (i + 1) % max(1, nr // 6) == 0:
                narrate(f'    representative {i + 1}/{nr} ... [{time.monotonic() - t0:.1f} s]')
        narrate(f'  products table built: {len(canon.list)} canonical monomials so far '
                f'[{time.monotonic() - t0:.1f} s]')

    for bi, b in enumerate(cert.blocks):
        t0 = time.monotonic()
        times, R, size = b['times'], b['R'], b['size']
        reps = reps1 if times == '1' else plane.representatives('q')
        if size != 1 + len(reps):
            raise Refusal('MALFORMED', f'blocks[{bi}]["R"] is {size} x {size}; a block with times "{times}" '
                                       f'is indexed by the constant and the {len(reps)} representative '
                                       f'monomials, so it must be {1 + len(reps)} x {1 + len(reps)}. '
                                       f'(At p = {cert.p} there are {len(reps1)} representatives of degree '
                                       f'<= 2 and 1 of degree <= 1.)')
        before = len(acc)
        for wi in b['weights']:
            w = cert.weights[wi]
            c0 = w[0]
            wx = w[1:]
            sigma = sum(wx)
            kap = [0] * n
            for x in range(n):
                row = plane.ADD[x]
                wxx = wx[x]
                if wxx:
                    for t in range(n):
                        kap[t] += wxx * wx[row[t]]
            add(forms.value(times, ()), R[0][0] * c0 * c0)
            for j, a in enumerate(reps):
                add(forms.value(times, a), 2 * R[0][1 + j] * c0 * sigma)
            if times == '1':
                for i in range(len(reps)):
                    Rrow = R[1 + i]
                    for j in range(len(reps)):
                        c = Rrow[1 + j]
                        if not c:
                            continue
                        Fij = F[i][j]
                        for t in range(n):
                            k = kap[t]
                            if k:
                                key = Fij[t]
                                acc[key] = acc.get(key, 0) + c * k
            else:
                for i, a in enumerate(reps):
                    Rrow = R[1 + i]
                    for j, a2 in enumerate(reps):
                        c = Rrow[1 + j]
                        if not c:
                            continue
                        for t in range(n):
                            k = kap[t]
                            if k:
                                add(forms.q(a + tuple(plane.ADD[t][y] for y in a2)), c * k)
        narrate(f'  block {bi + 1}/{len(cert.blocks)}: times {times}, {len(b["weights"])} weight vector(s), '
                f'{size} x {size}; {len(acc) - before} new canonical monomials '
                f'[{time.monotonic() - t0:.1f} s]')

    for (A, B, lam) in cert.rows:
        if not lam:
            continue
        for m, sign in box_terms(A, B):
            k = canon.idx(m)
            acc[k] = acc.get(k, 0) + sign * lam
    return acc


