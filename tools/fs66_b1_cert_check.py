def check(path, m=None, use_ldl=False, narrate=lambda s: None):
    t_start = time.monotonic()
    doc, sha = load_json_strict(path)
    narrate(f'certificate sha256 {sha}  ({path})')
    narrate(f'checker     sha256 {self_sha256()}  (this file)')

    cert = Cert(doc, path, sha)
    n, p = cert.n, cert.p
    narrate(f'format {FORMAT}, p = {p} (prime, = 3 mod 4), n = p^2 = {n} points')
    narrate(f'scale = {short_int(cert.scale)}, U_num = {short_int(cert.U_num)}')
    if cert.has_provenance:
        narrate(f'note: {" and ".join(chr(34) + k + chr(34) for k in cert.has_provenance)} '
                f'{"are" if len(cert.has_provenance) > 1 else "is"} provenance, not checked')
    narrate(f'step 1/7: parsed {len(cert.weights)} weight vectors of {n + 1} integers, {len(cert.blocks)} '
            f'blocks, {len(cert.rows)} rows; every number a JSON integer')

    if cert.scale <= 0:
        raise Refusal('NONPOSITIVE_SCALE',
                      f'"scale" is {short_int(cert.scale)}. The bound claimed is U = U_num/scale, and the '
                      f'argument divides the identity by the scale: with scale <= 0 that division flips the '
                      f'inequality, so a file with every sign negated would "prove" the opposite. The '
                      f'producer must emit a positive scale.')
    neg = [i for i, (_, _, lam) in enumerate(cert.rows) if lam < 0]
    if neg:
        i = neg[0]
        raise Refusal('NEGATIVE_MULTIPLIER',
                      f'rows[{i}] has multiplier {short_int(cert.rows[i][2])} < 0 ({len(neg)} rows do). A '
                      f'row is a product of numbers in [0,1] and of numbers 1 - phi_x in [0,1], so its '
                      f'moment is >= 0; only a NONNEGATIVE multiple of it may be added. Next: the producer '
                      f'clips negative row multipliers to zero before the cascade.')
    narrate(f'step 2/7: signs: scale > 0; all {len(cert.rows)} row multipliers >= 0')

    plane = Plane(p)
    pairs = plane.verify_maps()
    narrate(f'step 3/7: rebuilt from p alone: {n} points, unit circle S of {len(plane.S)} points, '
            f'{len(plane.maps)} linear maps, each a bijection with h(x+s) - h(x) in S on all {pairs} '
            f'(point, unit vector) pairs')

    worst = check_rows_shape(cert)
    narrate(f'step 4/7: rows: every point index in [0, {n}); largest box-product degree {worst} (<= 4)')

    route = ('an exact rational L*D*L^T, re-multiplied and compared with R: every D_k positive' if use_ldl
             else 'fraction-free (Bareiss) elimination: every leading principal minor positive')
    for bi, b in enumerate(cert.blocks):
        k, minor = (ldl_verdict(b['R']) if use_ldl else first_nonpositive_minor(b['R']))
        if k:
            name = 'D_%d' % k if use_ldl else 'leading principal minor %d' % k
            raise Refusal('BLOCK_NOT_POSITIVE_DEFINITE',
                          f'blocks[{bi}] (times "{b["times"]}", weight vectors {b["weights"]}, '
                          f'{b["size"]} x {b["size"]}) has {name} = {short_int(minor)}, which is not '
                          f'positive, so the block is not positive definite and its term is not a sum of '
                          f'squares. Next: the producer raises its diagonal shift (x10) and rounds again '
                          f'(the file scores by the U it proves, so a larger shift costs only a weaker U).')
    narrate(f'step 5/7: positive definiteness of {len(cert.blocks)} blocks '
            f'(sizes {min(b["size"] for b in cert.blocks)}..{max(b["size"] for b in cert.blocks)}) by '
            f'{route}')

    canon = Canon(plane)
    rhs = accumulate_identity(cert, plane, canon, narrate)
    lhs = {canon.idx(()): cert.U_num, canon.idx((0,)): -cert.scale * n}
    keys = set(rhs) | set(lhs)
    bad = [k for k in keys if rhs.get(k, 0) != lhs.get(k, 0)]
    if bad:
        bad.sort(key=lambda k: (len(canon.list[k]), canon.list[k]))
        shown = '; '.join(f'y({list(canon.list[k])}): left {short_int(lhs.get(k, 0))}, right '
                          f'{short_int(rhs.get(k, 0))}, left - right = '
                          f'{short_int(lhs.get(k, 0) - rhs.get(k, 0))}' for k in bad[:3])
        extra = ''
        const = canon.idx(())
        if bad == [const]:
            supported = rhs.get(const, 0)
            extra = (f' The blocks and rows of this file support U_num = {supported} '
                     f'(U = {dec_str(supported, cert.scale)}) and no smaller value; the file claims '
                     f'U_num = {cert.U_num} (U = {dec_str(cert.U_num, cert.scale)}).')
        raise Refusal('IDENTITY_MISMATCH',
                      f'the two sides of the identity differ at {len(bad)} of {len(keys)} canonical '
                      f'monomials, the first by degree being {shown}.{extra} Next: the producer recomputes '
                      f'the cascade, which by construction makes the identity exact.')
    narrate(f'step 6/7: identity (*) holds on {len(canon.list)} canonical monomials ({len(cert.blocks)} '
            f'blocks, {len(cert.rows)} rows), coefficient by coefficient in exact integers')

    res = {'p': p, 'n': n, 'scale': cert.scale, 'U_num': cert.U_num, 'sha256': sha,
           'canonical_monomials': len(canon.list), 'blocks': len(cert.blocks), 'rows': len(cert.rows),
           'U_dec': dec_str(cert.U_num, cert.scale), 'ldl': use_ldl,
           'wall_s': round(time.monotonic() - t_start, 3)}
    if m is None:
        res['verdict'] = 'CERTIFIED'
        narrate('step 7/7: no --m given, so no colour count is asked of the bound')
    elif m * cert.U_num < n * cert.scale:
        res['verdict'] = 'CERTIFIED'
        res['m'] = m
        narrate(f'step 7/7: {m} * U_num = {short_int(m * cert.U_num)} < {n} * scale = '
                f'{short_int(n * cert.scale)}')
    else:
        res['verdict'] = 'BOUND ONLY'
        res['m'] = m
        narrate(f'step 7/7: {m} * U_num = {short_int(m * cert.U_num)} >= {n} * scale = '
                f'{short_int(n * cert.scale)}')
    res['wall_s'] = round(time.monotonic() - t_start, 3)
    return res


def last_line(res, m):
    U = res['U_dec']
    head = (f'every phi in [0,1]^{res["n"]} with q(phi) >= 0 has sum(phi) <= U = {U} (exactly U_num/scale of '
            f'the file, sha256 {res["sha256"][:12]}…)')
    if m is None:
        return f'CERTIFIED: {head}. Standard-library checker, NOT the Lean kernel.'
    mU = dec_str(m * res['U_num'], res['scale'])
    if res['verdict'] == 'CERTIFIED':
        return (f'CERTIFIED: {head}; {m}*U = {mU} < {res["n"]}, so BY THE HAND-PROVED LINKS L1, L2, L6 '
                f'({os.path.relpath(SOUNDNESS, REPO)}) no UD(Z/{res["p"]}^k, 2), k >= 1, is {m}-colourable. '
                f'Standard-library checker, NOT the Lean kernel.')
    return (f'BOUND ONLY: {head}; but {m}*U = {mU} >= {res["n"]}, so this file does not refuse {m} colours '
            f'-- which says nothing about whether {m} colours suffice.')


def self_sha256():
    with open(os.path.abspath(__file__), 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def write_record(path, cert_path, m, use_ldl, res, verdict, code, line, argv):
    rec = {'kind': 'fs66-b1-check', 'record_version': 1,
           'utc': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
           'command': ' '.join(argv), 'checker_sha256': self_sha256(), 'cert': cert_path,
           'cert_sha256': (res or {}).get('sha256'), 'p': (res or {}).get('p'), 'm': m,
           'verdict': verdict, 'code': code,
           'U_num': (res or {}).get('U_num'), 'scale': (res or {}).get('scale'),
           'U_float': float((res or {}).get('U_dec', '0').rstrip('…')) if res else None,
           'canonical_monomials': (res or {}).get('canonical_monomials'),
           'blocks': (res or {}).get('blocks'), 'rows': (res or {}).get('rows'), 'ldl': use_ldl,
           'wall_s': (res or {}).get('wall_s'), 'python': platform.python_version(),
           'machine': f'{platform.node()} {platform.machine()}', 'last_line': line}
    with open(path, 'a') as f:
        f.write(json.dumps(rec) + '\n')


def main_check(cert_path, m, use_ldl, record, argv):
    res = None
    try:
        res = check(cert_path, m, use_ldl, narrate=lambda s: print(s, flush=True))
        line = last_line(res, m)
        rc = 0 if res['verdict'] == 'CERTIFIED' else 3
        verdict, code = res['verdict'], None
    except Refusal as ex:
        line = f'REFUSED {ex.code}: {ex.detail}'
        rc, verdict, code = 1, 'REFUSED', ex.code
    except CheckerError as ex:
        line = f'ERROR {ex.code}: {ex.detail}'
        rc, verdict, code = 2, 'ERROR', ex.code
    print(line, flush=True)
    if record:
        write_record(record, cert_path, m, use_ldl, res, verdict, code, line, argv)
    return rc


