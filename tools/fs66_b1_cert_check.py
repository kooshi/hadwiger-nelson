#!/usr/bin/env python3
"""fs66_b1_cert_check -- checks, in exact integer arithmetic, a certificate that every point of the
"fibre-density" region is small; through six hand-proved links that bounds the independence number of EVERY
level of the unit-distance tower over Z/p^k at once, and so refuses a colour count at every level at once.

STANDARD LIBRARY ONLY. It imports nothing from tools/ and shares no code with the producer or with the
prototype that emitted the files in data/fs66/b1/: the whole point of this program is that a second,
independently written bookkeeping agrees with theirs. It reads no floating-point number -- a float where an
integer belongs is refused by name. (The only float it ever CREATES is the `U_float` of an optional --record
line, formatted from the exact rational; nothing is ever read as a float.)

THE OBJECT.  Fix a prime p = 3 (mod 4).  V = F_p^2 is the plane over the field with p elements; the point
(a, b) is the integer a*p + b and n = p^2.  S is the unit circle {(a,b) : a^2 + b^2 = 1}, which has p + 1
points.  For a vector phi in [0,1]^V write

    q(phi) = 2 * sum_x phi_x (1 - phi_x)  -  sum_x sum_{s in S} phi_x phi_{x+s},

    B1(p)  = max { sum_x phi_x  :  phi in [0,1]^V ,  q(phi) >= 0 }.

A CERTIFICATE (format "fs66-b1-cert-v2") is a rational number U = U_num/scale together with an explicit
algebraic identity exhibiting  U - sum(phi)  as a nonnegative combination:

    U_num * y([])  -  scale * n * y([0])  =  sum over blocks T_block(y)  +  sum over rows lam * box(A,B)(y)

as integer linear forms in the variables y(k), one per canonical monomial k of degree <= 4.  A block is a
symmetric POSITIVE DEFINITE integer matrix R together with integer weight vectors; it contributes a sum of
squares (times 1, or times q).  A row is a box product  prod_{x in A} phi_x * prod_{x in B} (1 - phi_x)  with
a nonnegative integer multiplier.  Evaluated at the symmetrised moments of any feasible phi, every term on
the right is >= 0, so sum(phi) <= U.  Why that is so -- and the six links L1-L6 that carry it from this
polynomial statement to the tower -- is data/fs66/b1/SOUNDNESS.md, which this program does NOT check.

WHAT IS CHECKED, in order (cheap and decisive first).
  1. Parsing.  The format string; every number a JSON integer (never a float, a string or a boolean);
     the shape of every list; every index in range; p prime and = 3 (mod 4).
  2. Signs.  scale > 0 -- without it the final division flips the inequality -- and every row multiplier >= 0.
  3. The symmetries, rebuilt from p ALONE.  The n points, the circle S, and the 2(p+1) linear maps; each map
     is verified to be a bijection h with h(x+s) - h(x) in S for every point x and every s in S.  That single
     property is what the soundness page's averaging argument uses, and it is closed under composition, so
     the group generated by the verified maps and the translations is verified wholesale.
  4. Rows.  A and B are lists of valid point indices with len(A) + len(B) <= 4.
  5. Positive definiteness of every R, exactly: fraction-free (Bareiss) elimination, whose k-th pivot IS the
     k-th leading principal minor, all of which must be positive (Sylvester).  --ldl runs the slower route
     instead: an exact rational R = L*D*L^T, re-multiplied and compared with R, with every D_k > 0.
  6. The identity, coefficient by coefficient over the canonical monomials, in big integers.
  7. The colour arithmetic, if --m M was given: M * U_num < p^2 * scale.

WHY THE CANONICAL FORM CANNOT MAKE A FALSE CERTIFICATE PASS.  canon(m) is computed as an explicit image of m
under a translation followed by one of the VERIFIED maps of step 3, so two monomials are merged only when
they really are equivalent under the group the soundness argument averages over.  Failing to merge two
equivalent monomials would only make the identity stricter.  A wrong-merging canonicaliser is therefore
impossible by construction, and an incomplete one is safe.

WHAT IS NOT ON THE TRUST SURFACE.  The weight vectors, the number of blocks, which character the producer had
in mind, the order of the rows: a block contributes  sum_w <E_w R E_w^T, M>  for a moment matrix M, which is
>= 0 for ANY integers in the weights as long as R is positive definite.  Wrong weights can only make U
larger.  So can a wrong block structure, a clipped multiplier, or a bad rounding.  The producer's whole job
is to make U small; it cannot make a false certificate.

THE CLOSED LIST OF REFUSAL CODES (nothing is accepted and ignored):
  NOT_AN_INTEGER               a float, a string or a boolean where an integer belongs
  MALFORMED                    shape, an index out of range, a row of degree > 4, an unknown top-level key
  BAD_PRIME                    p is not a prime congruent to 3 modulo 4
  NONPOSITIVE_SCALE            scale <= 0: the final division by it would flip the inequality
  NEGATIVE_MULTIPLIER          a box-product multiplier is negative
  BLOCK_NOT_POSITIVE_DEFINITE  some leading principal minor of a block is not positive
  IDENTITY_MISMATCH            the two sides of the identity differ at some canonical monomial
and the error codes, which say the CHECKER could not do its job rather than that the file is bad:
  CANNOT_READ, USAGE, SELF_CHECK_FAILED (a rebuilt map is not a symmetry -- a bug here, never the file's
  fault), INTERNAL.

USAGE
  fs66_b1_cert_check.py CERT.json [--m M] [--ldl] [--record FILE]
  fs66_b1_cert_check.py --self-test [--cert CERT.json]
  fs66_b1_cert_check.py --help
The last line always begins with CERTIFIED (exit 0), BOUND ONLY (exit 3), REFUSED <CODE> (exit 1) or
ERROR <CODE> (exit 2).  CERTIFIED is this checker's word, NOT the Lean kernel's, and it asserts only the
polynomial bound: the sentence about the tower is carried by the hand-proved links of SOUNDNESS.md.
"""
