def run_self(args):
    r = subprocess.run([sys.executable, os.path.abspath(__file__)] + args, capture_output=True, text=True)
    out = [l for l in r.stdout.strip().splitlines() if l.strip()]
    return r.returncode, (out[-1] if out else (r.stderr.strip()[-300:] or '(no output at all)'))


def digest_of(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


class SelfTest:
    def __init__(self, cert_path):
        self.cert_path = cert_path
        self.rows = []
        self.first_bad = None

    def row(self, ok, label, expected, observed):
        self.rows.append(ok)
        if not ok and self.first_bad is None:
            self.first_bad = (label, expected, observed)
        print(f'  [{"ok  " if ok else "FAIL"}] {label}\n         expected {expected}\n'
              f'         observed {observed}', flush=True)

    def expect(self, label, args, path, twin_digest, expect_word, expect_code=None, expect_rc=None):
        """a plant must (a) really differ from the faithful twin and (b) end on the named WORD and CODE.

        Matching the code and not merely the exit status is what keeps a wrong-reason red from passing: a
        checker that crashed on a malformed plant would exit 1 like a refusal."""
        rc, line = run_self(args)
        changed = (path is None) or (digest_of(path) != twin_digest)
        want = expect_word if expect_code is None else f'{expect_word} {expect_code}'
        hit = line.startswith(want + ':')
        if expect_rc is None:
            expect_rc = {'CERTIFIED': 0, 'BOUND ONLY': 3, 'REFUSED': 1, 'ERROR': 2}[expect_word]
        ok = changed and rc == expect_rc and hit
        self.row(ok, label, f'exit {expect_rc}, last line starting "{want}"',
                 (f'exit {rc}: {line[:190]}' if changed
                  else f'[THE PLANT CHANGED NOTHING] exit {rc}: {line[:150]}'))


