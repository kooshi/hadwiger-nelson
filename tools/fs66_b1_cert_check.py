        use_ldl = False
        record = None
        positional = []
        i = 0
        while i < len(argv):
            a = argv[i]
            if a == '--m':
                if i + 1 >= len(argv):
                    print(USAGE)
                    print('ERROR USAGE: --m needs a colour count, e.g. --m 4')
