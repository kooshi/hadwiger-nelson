#!/usr/bin/env python3
"""fs131_ikc3_ktab -- FS131-IKC3: a probe of F2's first new checker part, the K table as a literal checked map range by
map range (plans/FS131-KC13-certificates.md section 3.2, item 1), against the library's unchanged `FibreCert.ktable`.

Writes one Lean file: a minimal `Cert` holding only what `ktable` reads (p, w, wf, the weights, the times-1 blocks'
weight indices; every other field empty), the literal `kt` (per map of `gList p`, its (c, d, e) and per times-1 block
the packed rows t |-> max(+-K_b(g t), 0) at width w, exactly `FibreCert.krow`), the check `ktabChk` and one theorem
`ktabChk mini kt K R = true` (or `= false` with --corrupt: one slot of one row of the first checked map moved by one).

UNTRUSTED: the kernel compares the literal with its own computation of `ktable`.

Usage: fs131_ikc3_ktab.py CERT.json OUT.lean --w W --maps K --range R [--corrupt]
  W is the slot width the converter chose for this certificate (`w :=` in its output).
"""
import argparse, importlib.util, json, pathlib

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("gen", HERE / "fs131_ikc1_gen.py")
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)

CHECK = r'''
/-- Bool equality of two lists of packed row pairs. -/
def rowsEq : List (Nat × Nat) → List (Nat × Nat) → Bool
  | [], [] => true
  | a :: l, b :: l' => Nat.beq a.1 b.1 && Nat.beq a.2 b.2 && rowsEq l l'
  | _, _ => false

/-- Bool equality of two K-table entries. -/
def entEq (a b : (Nat × Nat × Nat) × List (Nat × Nat)) : Bool :=
  Nat.beq a.1.1 b.1.1 && Nat.beq a.1.2.1 b.1.2.1 && Nat.beq a.1.2.2 b.1.2.2 && rowsEq a.2 b.2

/-- F2's K-table check, piece `r`: maps `[r·k, r·k + k)` of `ktable C` agree with the literal `kt`. -/
def ktabChk (C : Cert) (kt : List ((Nat × Nat × Nat) × List (Nat × Nat))) (k r : Nat) : Bool :=
  let a := ((ktable C).drop (Nat.mul r k)).take k
  let b := (kt.drop (Nat.mul r k)).take k
  Nat.beq a.length b.length && (a.zip b).all fun x => entEq x.1 x.2
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cert'); ap.add_argument('out')
    ap.add_argument('--w', type=int, required=True); ap.add_argument('--maps', type=int, default=5)
    ap.add_argument('--range', type=int, default=0); ap.add_argument('--corrupt', action='store_true')
    a = ap.parse_args()
    C = json.load(open(a.cert))
    P = C['p']; n = P * P; pl = gen.Plane(P)
    W = []
    for w in C['weights']:
        pw = gen.plane_wave(P, w[1:]); W.append((w[0], pw[0], pw[1]))
    wc = 8; wf = max(abs(v) for (c0, u, f) in W for v in f).bit_length() + 2
    weights = [(c0 + (1 << (wc - 1)), u, sum((v + (1 << (wf - 1))) << (wf * r) for r, v in enumerate(f))) for (c0, u, f) in W]
    t1 = [b for b in C['blocks'] if b['times'] == '1']

    def Kb(b, t):
        return sum(gen.kappa_pw(P, W[wi][1], W[wi][2], t) for wi in b['weights'])
    w = a.w
    kt = []
    for gi, (c, d, e) in enumerate(pl.maps):
        rows = []
        for b in t1:
            vs = [Kb(b, pl.gmap(c, d, e, t)) for t in range(n)]
            Pp = sum(max(v, 0) << (w * t) for t, v in enumerate(vs))
            Nn = sum(max(-v, 0) << (w * t) for t, v in enumerate(vs))
            assert all(abs(v) < (1 << w) for v in vs)
            rows.append((Pp, Nn))
        kt.append(((c, d, e), rows))
    if a.corrupt:
        gi = a.range * a.maps
        (g, rows) = kt[gi]
        rows = list(rows); rows[0] = (rows[0][0] + (1 << (w * 5)), rows[0][1]); kt[gi] = (g, rows)
    blks = ', '.join('{ wts := [' + ', '.join(str(x) for x in b['weights']) + '], m := 0, wr := 0, per := 0, sb := 0, '
                     'wm := 0, wB := 0, mrows := [], row0 := [], rest := [] }' for b in t1)
    ktl = gen.lean_list(['((%d, %d, %d), [%s])' % (g + (', '.join('(%s, %s)' % (hex(x), hex(y)) for (x, y) in rows),))
                         for (g, rows) in kt], '    ')
    want = 'false' if a.corrupt else 'true'
    text = ('import Proofs.HadwigerNelson.Arith.FibreCert\n'
            f'-- GENERATED by tools/fs131_ikc3_ktab.py from {a.cert}: F2 K-table probe, maps {a.maps}, range {a.range}, '
            f'corrupt={a.corrupt}. A probe, not a library module.\n'
            'namespace FS131IKC3KT\nopen HadwigerNelson.FibreCert\n' + CHECK +
            f'\n/-- What `ktable` reads of FS-66\'s p = {P} certificate. -/\n'
            f'def mini : Cert where\n  p := {P}\n  scale := 1\n  unum := 0\n  w := {w}\n  lb := 0\n  ds := 0\n  nseg := 0\n'
            f'  kb := 0\n  keys := []\n  reps := []\n  wc := {wc}\n  wf := {wf}\n'
            '  weights := [' + ', '.join(f'({c}, {u}, {hex(fp)})' for (c, u, fp) in weights) + ']\n'
            f'  blocks1 := [{blks}]\n  blocksq := []\n  orbits := []\n  orows := []\n  k1 := 0\n  per1 := 0\n  p1 := []\n'
            '  tnu := []\n  kq := 0\n  perq := 0\n  qt := []\n  kp := 0\n  kr := 0\n  perr := 0\n  nrows := 0\n  rows := []\n'
            '  kw := 0\n  ko := 0\n  pero := 0\n  ops := []\n'
            f'/-- The K table, as the certificate would carry it. -/\ndef kt : List ((Nat × Nat × Nat) × List (Nat × Nat)) :=\n  {ktl}\n'
            f'theorem ok : ktabChk mini kt {a.maps} {a.range} = {want} := by decide +kernel\n'
            'end FS131IKC3KT\n')
    pathlib.Path(a.out).write_text(text)
    print(f'wrote {a.out}: maps={len(kt)} blocks1={len(t1)} w={w} bytes={len(text)}')


if __name__ == '__main__':
    main()
