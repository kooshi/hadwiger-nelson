#!/usr/bin/env python3
"""FS131-L10A — the audit records wave 10's first pass still lacks, from the kernel's own list of theorems.

  tools/fs131_l10a_register.py MAIN_COUNT LANDING_COUNT            list
  tools/fs131_l10a_register.py MAIN_COUNT LANDING_COUNT --write    append one block "FS131-L10A" above the PURCHASED banner
  tools/fs131_l10a_register.py MAIN_COUNT LANDING_COUNT --self-test

MAIN_COUNT, LANDING_COUNT: the two outputs of `data/fs131/l5/count-modules.lean` (`DECL <kind> <module> <name>` lines), taken on
`main`'s library and on the landing's. The wave's theorems are the `DECL THM` names of the landing that `main` does not hold.
A name Lean generates (`f.eq_1`, `congr_simp`, `mk.inj`, …: the pattern of `tools/fs131_l5_records.py`, whose check this
registration is made for) is counted and asked no record. Listed: the hand-written wave theorems with no `#print axioms` line in
`scripts/Axioms.lean` (MISSING), and the `#print axioms` lines of `scripts/Axioms.lean` in the wave's four namespaces that name no
declaration of the landing library (STALE: a record of a deleted declaration, which would not elaborate).
--self-test: on the lists as read, a wave theorem's record removed in memory must read MISSING, and a record naming nothing must
read STALE.
"""
import collections
import re
import sys

AX = "scripts/Axioms.lean"
BANNER = '#eval IO.println "=== PURCHASED ==="'
WAVE_NS = tuple(f"HadwigerNelson.{m}." for m in ("CharacterColouring", "SpectralInputs", "StationaryRatio", "StandingFive"))
GENERATED = re.compile(r"\.(eq_\d+|eq_def|congr_simp|brecOn|binductionOn)$|\.mk\.(inj|injEq|sizeOf_spec)$")


def decls(path):
    thm, every = {}, set()
    for ln in open(path, encoding="utf-8"):
        p = ln.split()
        if ln.startswith("DECL ") and len(p) >= 4:
            every.add(p[3])
            if p[1] == "THM":
                thm[p[3]] = p[2]
    return thm, every


def survey(main_thm, land_thm, land_all, ax_text):
    have = collections.Counter(re.findall(r"^#print axioms (\S+)", ax_text, re.M))
    wave = {n: m for n, m in land_thm.items() if n not in main_thm}
    gen = sorted(n for n in wave if GENERATED.search(n))
    hand = {n: m for n, m in wave.items() if not GENERATED.search(n)}
    missing = sorted((m, n) for n, m in hand.items() if have[n] == 0)
    # older blocks print short names under an `open`; the wave's records are written in full, so the test is scoped to them
    stale = sorted(n for n in have if n.startswith(WAVE_NS) and n not in land_all)
    return wave, gen, hand, missing, stale


def main(argv):
    flags = {a for a in argv if a.startswith("--")}
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 2:
        print(__doc__)
        return 2
    main_thm, _ = decls(args[0])
    land_thm, land_all = decls(args[1])
    if not main_thm or not land_thm:
        print("a count file holds no DECL THM line")
        return 2
    src = open(AX, encoding="utf-8").read()
    wave, gen, hand, missing, stale = survey(main_thm, land_thm, land_all, src)
    bymod = collections.Counter(m.split(".")[-1] for m in wave.values())
    print(f"kernel: main {len(main_thm)} theorems, landing {len(land_thm)}; the wave adds {len(wave)} "
          f"({', '.join(f'{k} {v}' for k, v in sorted(bymod.items()))}); generated by Lean {len(gen)} {gen}; "
          f"hand-written {len(hand)}; with a record {len(hand) - len(missing)}; MISSING {len(missing)}; STALE {len(stale)} {stale}")
    if "--self-test" in flags:
        victim = next(n for n in sorted(hand) if re.search(r"^#print axioms " + re.escape(n) + r"$", src, re.M))
        s1 = re.sub(r"^#print axioms " + re.escape(victim) + r"\n", "", src, count=1, flags=re.M)
        m1 = survey(main_thm, land_thm, land_all, s1)[3]
        f1 = any(n == victim for _, n in m1)
        s2 = src.replace(BANNER, "#print axioms HadwigerNelson.StationaryRatio.zz_planted_nothing\n" + BANNER, 1)
        st2 = survey(main_thm, land_thm, land_all, s2)[4]
        f2 = "HadwigerNelson.StationaryRatio.zz_planted_nothing" in st2
        print(f"plant (the record of {victim} removed): {'MISSING fired' if f1 else 'DID NOT FIRE'}")
        print(f"plant (a record naming no declaration): {'STALE fired' if f2 else 'DID NOT FIRE'}")
        print("self-test: PASS" if f1 and f2 else "self-test: FAIL")
        return 0 if f1 and f2 else 1
    if "--write" in flags and missing:
        assert src.count(BANNER) == 1
        blk = ["/-! ## FS-131 wave 10's first pass (job FS131-L10A) — the landing: the theorems of `Arith/{CharacterColouring, SpectralInputs,",
               "StationaryRatio, StandingFive}` that the planner's and the three implementers' blocks did not list. Read from the kernel's own",
               "list of the library's theorems (`data/fs131/l5/count-modules.lean`), by `tools/fs131_l10a_register.py`; checked by",
               "`tools/fs131_l5_records.py`. -/"]
        last = None
        for m, n in missing:
            if m != last:
                blk.append(f"-- {m[len('Proofs.HadwigerNelson.'):].replace('.', '/')}")
                last = m
            blk.append(f"#print axioms {n}")
        src = src.replace(BANNER, "\n".join(blk) + "\n\n" + BANNER)
        open(AX, "w", encoding="utf-8").write(src)
        print(f"wrote {len(missing)} records")
    else:
        for m, n in missing[:400]:
            print(f"  MISSING {m.split('.')[-1]} {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
