#!/usr/bin/env python3
"""FS131-IN1L — the draft block for `scripts/Axioms.lean`'s CLEAN section: one `#print axioms` line per PUBLIC record
of this job's four modules whose axioms are a subset of the standard three, read from the output of
`data/fs131/in1l/lean/Axioms.lean` on the built tree (the records resting on `sorryAx` — the three leaves this job
does not hold and the two theorems that read them — are left out and listed in a comment).  Generated names Lean
makes on demand (`.congr_simp`, `.eq_n`, `.induct`, …) are left out: no author declares them.

Usage: fs131_in1l_audit_block.py <axioms.txt> > <block.lean>
Exit 2 if the input holds no record (a block from a broken read is never written as an empty block).
"""
import sys

STANDARD = {"propext", "Classical.choice", "Quot.sound"}
GENERATED = (".congr_simp", ".eq_def", ".induct", ".splitter")


def main():
    rows = []
    for ln in open(sys.argv[1]).read().splitlines():
        if not ln.startswith("AXIOMS ") or ln.startswith("AXIOMS-COUNT"):
            continue
        head, axs = ln.split(" : ", 1)
        _, mod, kind, name = head.split(" ")
        body = axs.strip()[1:-1].strip()
        ax = set() if not body else {x.strip() for x in body.split(",")}
        if mod == "PLANT" or kind != "public":
            continue
        if any(g in name for g in GENERATED) or ".eq_" in name:
            continue
        rows.append((mod, name, ax))
    if not rows:
        print("no records read", file=sys.stderr)
        sys.exit(2)
    out = ["/-! ## FS131-IN1L — the largest Haar multiple (`Rigidity/HaarMultiple`), the names at entropy zero",
           "(`Rigidity/ZeroEntropyNames`), the ergodicity bridge (`Rigidity/SolenoidErgodic`) and the smaller set's leaves",
           "with every record of `Rigidity/ChainAtTA` now clean; generated by `tools/fs131_in1l_audit_block.py` -/",
           "-- FS131-IN1L"]
    left = []
    cur = None
    for mod, name, ax in rows:
        if not ax <= STANDARD:
            left.append(f"--   {name} : {sorted(ax)}")
            continue
        if mod != cur:
            out.append(f"-- {mod.removeprefix('Proofs.HadwigerNelson.').replace('.', '/')}")
            cur = mod
        out.append(f"#print axioms {name}")
    if left:
        out.append("-- left out (they rest on `sorryAx` from leaves this job does not hold):")
        out.extend(left)
    print("\n".join(out))


if __name__ == "__main__":
    main()
