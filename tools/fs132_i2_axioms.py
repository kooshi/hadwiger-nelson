#!/usr/bin/env python3
"""FS132-I2 — the ported declarations' axioms, printed from the built modules and checked as sets.

  fs132_i2_axioms.py emit            write data/fs132/i2/axioms/Print.lean: one `#print axioms` per ported declaration
                                     (the records of this job's block in scripts/Axioms.lean, read from the generator),
                                     then three CONTROLS: a theorem of this library that rests on the first declared
                                     outside theorem, one that rests on the second, and a `sorry` stated in the file
  fs132_i2_axioms.py check OUT       every record's axioms must be a subset of the standard three — in particular
                                     neither declared outside theorem, no `sorryAx`, no native axiom — and every
                                     record of the block must be printed; each control must show the axiom it was
                                     planted for (a control that prints clean means the print cannot see that axiom)
  fs132_i2_axioms.py --self-test OUT plant faults in copies of OUT (an outside axiom in a target's list, `sorryAx` in a
                                     record, a record missing, a control gone clean) and require each refused

Run the print with `lake env lean data/fs132/i2/axioms/Print.lean` from the worktree, after the build.
"""
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data/fs132/i2/axioms"
STANDARD = {"propext", "Classical.choice", "Quot.sound"}
NS = "HadwigerNelson.Outside.OAI158."
H, T = NS + "no_proper_five_coloring", NS + "proper_to_borel_weak"
TARGETS = ["palette_transfer_pair", "palette_sixty_disjoint", "two_state_impossible", "mem_spatialSupport_ae"]
CONTROLS = {
    NS + "not_colorable_five": H,
    NS + "chromaticNumber_plane_eq_chiM0": T,
    "FS132I2Control.planted_sorry": "sorryAx",
}


def records():
    spec = importlib.util.spec_from_file_location("port", ROOT / "tools/fs132_i2_port.py")
    port = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(port)
    _, p = port.generate()
    return [NS + sh for name, _, _, _ in port.FILES for (_, _, sh, _) in p[name]["copied"]]


def emit() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    recs = records()
    lines = ["import Proofs.HadwigerNelson.Outside.OAI158States",
             "import Proofs.HadwigerNelson.Outside.OAI158AngularBoundary",
             "-- FS132-I2 (generated by tools/fs132_i2_axioms.py emit): the ported declarations' axioms, and three controls.",
             "set_option pp.fullNames true",
             "namespace FS132I2Control",
             "/-- A control: a statement left as `sorry`; its print must show `sorryAx`. -/",
             "theorem planted_sorry : (1 : Nat) = 1 := by sorry",
             "end FS132I2Control"]
    lines += [f"#print axioms {r}" for r in recs]
    lines += [f"#print axioms {c}" for c in CONTROLS]
    (OUT / "Print.lean").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}/Print.lean: {len(recs)} records, {len(CONTROLS)} controls")
    return 0


def parse(text: str):
    """name -> set of axioms.  `'X' depends on axioms: [a, b]` (possibly over several lines) or `does not depend`."""
    got = {}
    flat = re.sub(r"\s+", " ", text)
    for m in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", flat):
        got[m.group(1)] = {a.strip() for a in m.group(2).split(",") if a.strip()}
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", flat):
        got[m.group(1)] = set()
    return got


def check(text: str, quiet=False):
    got, recs, bad = parse(text), records(), []
    for r in recs:
        if r not in got:
            bad.append(f"{r}: not printed")
        elif not got[r] <= STANDARD:
            bad.append(f"{r}: rests on {sorted(got[r] - STANDARD)}")
    for c, ax in CONTROLS.items():
        if c not in got:
            bad.append(f"control {c}: not printed")
        elif ax not in got[c]:
            bad.append(f"control {c}: its print does not show {ax} — the print cannot see that axiom")
    if not quiet:
        full = sum(1 for r in recs if got.get(r) == STANDARD)
        none = sum(1 for r in recs if r in got and not got[r])
        print(f"records: {len(recs)}  printed: {sum(1 for r in recs if r in got)}  on the standard three exactly: {full}  "
              f"on a proper subset: {sum(1 for r in recs if r in got and got[r] < STANDARD) - none}  on no axiom: {none}")
        for t in TARGETS:
            print(f"  {t}: {sorted(got.get(NS + t, {'NOT PRINTED'}))}")
        for c, ax in CONTROLS.items():
            print(f"  control {c}: {sorted(got.get(c, {'NOT PRINTED'}))}  (planted for {ax})")
        for b in bad:
            print(f"FAIL: {b}")
        print("AXIOMS " + ("OK: every record on the standard three or fewer, neither outside theorem under any; "
                           "the three controls fire" if not bad else "FAILED"))
    return bad


def self_test(text: str) -> int:
    if check(text, quiet=True):
        print("SELF-TEST FAILED: the unplanted print does not pass")
        return 1
    print("unplanted: PASS (as it must)")
    ok = True
    t0 = NS + TARGETS[0]

    def expect(label, planted):
        nonlocal ok
        assert planted != text, label
        b = check(planted, quiet=True)
        print(f"plant '{label}': {'REFUSED' if b else 'SILENT'}" + (f" ({b[0][:120]})" if b else ""))
        ok = ok and bool(b)

    flat = re.sub(r"\s+", " ", text)
    m = re.search(r"'" + re.escape(t0) + r"' depends on axioms: \[", flat)
    expect("an outside theorem under a target", flat[:m.end()] + H + ", " + flat[m.end():])
    expect("sorryAx under a target", flat[:m.end()] + "sorryAx, " + flat[m.end():])
    expect("a native axiom under a target", flat[:m.end()] + t0 + "._native.native_decide.ax_1_1, " + flat[m.end():])
    expect("a record not printed", flat.replace(f"'{t0}' depends on axioms", "'gone' depends on axioms"))
    c = NS + "not_colorable_five"
    expect("a control gone clean", re.sub(r"'" + re.escape(c) + r"' depends on axioms: \[[^\]]*\]",
                                          f"'{c}' depends on axioms: [propext]", flat))
    print("SELF-TEST " + ("OK: 5 plants refused" if ok else "FAILED"))
    return 0 if ok else 1


def main(argv) -> int:
    if len(argv) >= 2 and argv[1] == "emit":
        return emit()
    if len(argv) >= 3 and argv[1] == "check":
        return 1 if check(Path(argv[2]).read_text()) else 0
    if len(argv) >= 3 and argv[1] == "--self-test":
        return self_test(Path(argv[2]).read_text())
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
