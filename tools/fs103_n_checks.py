#!/usr/bin/env python3
"""FS103-N: exact checks behind the controls of plans/FS103-N-verification.md (stages 1-2).

Each check returns (ok, detail).  `--plant NAME` swaps one input for a faulty one; the named check must then
FAIL, and for its own reason (the detail line says which inequality broke).  Exit status 0 iff every check
passes (unplanted) or iff the planted check fails and every other check passes (planted).

Checks:
  hex      C1: hexagon side a = 2/5 gives a colouring proper at every unit edge:
           2a < 1 (a cell's diameter) and (sqrt(21) - 2) a > 1 (same-coloured cells), exactly.
  circ     A-E3' upper / C2: f(x) = floor(3 {alpha x}) with alpha = 2/5 is proper on Cay(R, {+-1, +-sqrt2}):
           alpha*d mod 1 in [1/3, 2/3] for d = 1, sqrt2, exactly; and the 'thirds' lemma on a rational grid.
  cosets   A-E3' lower / C2, C2': both cosets of Lam = {m + n sqrt2 : m = n mod 2} in Z + Z sqrt2 contain
           nonzero elements of absolute value < 10^-3 (dense), while for {1, 3} Lam = 2Z has least
           positive element 2 (the argument must stop there).
  nonraj   C2 / C4: sigma = atoms at +-1, +-sqrt2 is not Rajchman: sigma^(q) -> 1 along Pell denominators q;
           the circle measure is: |J0(2 pi r)| < 0.01 at r = 1000 (mpmath, 50 digits).
"""
from __future__ import annotations

import sys
from fractions import Fraction as Fr

import mpmath

mpmath.mp.dps = 50

PLANT = None
if len(sys.argv) >= 3 and sys.argv[1] == "--plant":
    PLANT = sys.argv[2]


def check_hex():
    a = Fr(3, 8) if PLANT == "hex" else Fr(2, 5)
    diam_ok = 2 * a < 1
    # (sqrt21 - 2) a > 1  <=>  sqrt21 * a > 1 + 2a  <=>  21 a^2 > (1 + 2a)^2   (both sides positive)
    sep_ok = 21 * a * a > (1 + 2 * a) ** 2
    return diam_ok and sep_ok, f"a={a}: 2a<1 {diam_ok}; 21a^2={21*a*a} > (1+2a)^2={(1+2*a)**2} {sep_ok}"


def in_middle_third_sqrt(num: Fr) -> bool:
    """Is sqrt(num) mod 1 in [1/3, 2/3]?  num >= 0 rational; decided exactly via squares."""
    # integer part of sqrt(num)
    k = 0
    while (k + 1) ** 2 <= num:
        k += 1
    lo, hi = (k + Fr(1, 3)) ** 2, (k + Fr(2, 3)) ** 2
    return lo <= num <= hi


def check_circ():
    alpha = Fr(1, 2) if PLANT == "circ" else Fr(2, 5)
    frac = alpha - (alpha.numerator // alpha.denominator)
    ok1 = Fr(1, 3) <= frac <= Fr(2, 3)
    ok2 = in_middle_third_sqrt(2 * alpha * alpha)  # alpha*sqrt2 = sqrt(2 alpha^2)
    # thirds lemma: for s in [1/3, 2/3], t and t+s mod 1 never share a third [0,1/3),[1/3,2/3),[2/3,1)
    N = 60
    lemma = True
    for i in range(N):
        for j in range(N + 1):
            t = Fr(i, N)
            s = Fr(1, 3) + Fr(j, 3 * N)
            u = (t + s) % 1
            if int(3 * t) == int(3 * u):
                lemma = False
    return ok1 and ok2 and lemma, f"alpha={alpha}: alpha mod 1 mid-third {ok1}; alpha*sqrt2 mid-third {ok2}; thirds lemma {lemma}"


def check_cosets():
    # Pell units (3 + 2 sqrt2)^j have m odd, n even: m + n sqrt2 with (3 - 2 sqrt2)^j small, in the ODD coset;
    # twice them lie in Lam (the even coset).
    s2 = mpmath.sqrt(2)
    m, n = 1, 0
    small_odd = small_even = None
    for _ in range(12):
        m, n = 3 * m - 4 * n, -2 * m + 3 * n  # multiply by (3 - 2 sqrt2)
        v = m + n * s2
        if abs(v) < mpmath.mpf("1e-3"):
            if (m - n) % 2 == 1 and small_odd is None:
                small_odd = (m, n, v)
            if small_even is None:
                small_even = (2 * m, 2 * n, 2 * v)
    dense_ok = small_odd is not None and small_even is not None and (small_even[0] - small_even[1]) % 2 == 0
    # {1, 3}: Lam generated by 1+3 and 1-3 -> 2Z; least positive element 2 (the stopping control C2')
    d2 = 2 if PLANT == "cosets" else 3  # plant: replace 3 by 2, which makes the lattice Z (1+2=3, 1-2=-1)
    a, b = 1 + d2, 1 - d2
    from math import gcd
    g = gcd(abs(a), abs(b))
    stop_ok = g == 2
    return dense_ok and stop_ok, (f"odd coset small element {small_odd[:2] if small_odd else None}; even coset "
                                  f"{small_even[:2] if small_even else None}; for {{1,{d2}}} Lam = {g}Z (must be 2Z) {stop_ok}")


def check_nonraj():
    s2 = mpmath.sqrt(2)
    qs = [12, 70, 408, 2378, 13860] if PLANT != "nonraj" else [11, 71, 409, 2377, 13861]
    vals = [(mpmath.cos(2 * mpmath.pi * q) + mpmath.cos(2 * mpmath.pi * s2 * q)) / 2 for q in qs]
    atoms_ok = vals[-1] > mpmath.mpf("0.9999")
    j = mpmath.besselj(0, 2 * mpmath.pi * 1000)
    circle_ok = abs(j) < mpmath.mpf("0.01")
    return atoms_ok and circle_ok, (f"atomic sigma^ at q={qs}: {[mpmath.nstr(v, 8) for v in vals]} (last > 0.9999: {atoms_ok}); "
                                    f"J0(2 pi 1000) = {mpmath.nstr(j, 6)} (|.| < 0.01: {circle_ok})")


CHECKS = {"hex": check_hex, "circ": check_circ, "cosets": check_cosets, "nonraj": check_nonraj}


def main() -> int:
    if PLANT is not None and PLANT not in CHECKS:
        print(f"unknown plant {PLANT!r}; choose one of {sorted(CHECKS)}")
        return 2
    failed = []
    for name, fn in CHECKS.items():
        ok, detail = fn()
        print(f"{'PASS' if ok else 'FAIL'} {name}: {detail}")
        if not ok:
            failed.append(name)
    if PLANT is None:
        print("ALL PASS" if not failed else f"FAILED: {failed}")
        return 0 if not failed else 1
    good = failed == [PLANT]
    print(f"plant {PLANT}: {'fired alone, as it must' if good else 'DID NOT FIRE ALONE: ' + str(failed)}")
    return 0 if good else 1


if __name__ == "__main__":
    sys.exit(main())
