#!/usr/bin/env python3
"""fs73_classify -- FS-73 P1: every proper four-colouring of Cay(Lambda/8Lambda, U mod 8) on de Grey's lattice, classified up to the
lattice's symmetry, and G70's test.

  classify [--out data/fs73/census/K-8Lambda-classes.json]

(1) Enumeration: the quotient's colouring CNF with the finder's pins (origin 0, least neighbour 1, a quotient triangle 2 -- a triangle
    pinned to three colours fixes the colour permutation completely, so each colouring is counted once per S4-orbit), at-most-one
    clauses, and incremental CaDiCaL 1.5.3 (pysat) with a blocking clause per model, to exhaustion.  Every model is re-verified
    proper on the quotient.
(2) Classification: the group generated by the four translations e_1..e_4 (mod 8), the lattice's point group (fs73_lattice's
    point_group: rotations by the unit multipliers, complex conjugation, the Galois flips preserving Lambda; order 24) and the colour
    permutations acts on the pinned colourings (act, then relabel so the pins hold again); orbits by union-find over the generators.
    Per orbit: its size, the period group of its members (exactly, PColour.per), and whether its members are sqrt3-clean.
(3) G70: a colouring is sqrt3-clean when no two points at distance sqrt3 share a colour (the sqrt3-vectors of Lambda enumerated
    exactly: D in O_E with D conj(D) = 243, i.e. |D/9|^2 = 3).  Prediction (G70, MASCOT-T6 carried to Lambda = (1/9) O_E, 2 split
    in E with Lambda/2Lambda = O_E/2 = F4 x F4): the sqrt3-clean colourings are exactly Theorem B's two residue colourings (the
    two primes above 2: sqrt33 -> S and sqrt33 -> -S 2-adically), each pinned once.  Both outcomes reachable: a sqrt3-clean colouring
    that is not residue refutes G70's transfer to this lattice; a residue colouring that is not sqrt3-clean refutes the hexagon
    reading (it would be a defect).
"""
import json
import os
import sys
import time
from fractions import Fraction as Fr

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import fs73_lattice as FL                                                     # noqa: E402
import fs73_screen as S                                                       # noqa: E402
import fs73_certify as CE                                                     # noqa: E402


def enumerate_colourings(Q, U):
    from pysat.solvers import Cadical153
    (cls, E, extra), nvars, pins, note = S.build_cnf(Q, U, 'plain')
    n = Q.n
    x = lambda v, c: 4 * v + c + 1
    amo = [[-x(v, a), -x(v, b)] for v in range(n) for a in range(4) for b in range(a + 1, 4)]
    edges = [[-x(i, c), -x(j, c)] for i, j in E.tolist() for c in range(4)]
    sv = Cadical153(bootstrap_with=cls + edges + extra + amo)
    out = []
    t0 = time.time()
    while sv.solve():
        m = sv.get_model()
        X = np.array([m[x(v, c) - 1] > 0 for v in range(n) for c in range(4)]).reshape(n, 4)
        assert (X.sum(axis=1) == 1).all()
        col = np.argmax(X, axis=1).astype(np.int8)
        assert not np.any(col[E[:, 0]] == col[E[:, 1]]), 'improper model'
        out.append(col)
        sv.add_clause([-x(v, int(col[v])) for v in range(n)])
    sv.delete()
    return out, pins, note, time.time() - t0, E


def relabel(col, pins):
    """the unique colour permutation putting the pins back (the pins are a triangle plus... three distinct colours)"""
    perm = np.full(4, -1, dtype=np.int8)
    for v, c in pins:
        perm[col[v]] = c
    rest = [c for c in range(4) if c not in perm]
    perm[perm == -1] = rest[0]
    return perm[col]


def sqrt3_vectors(lat):
    pts = S.minkowski_ball(lat, 1.75)
    out = []
    for p in pts:
        if any(p):
            z = CE.to_oe(p)
            if CE.oe_mul(z, CE.oe_conj(z)) == (243, 0, 0, 0):
                out.append(p)
    return out


def residue_colouring_values(lat, sign):
    import residue_colouring as RC
    Sq = RC.sqrt33_2adic(17)
    if sign < 0:
        Sq = RC.MOD - Sq
    vals = []
    for b in lat.H:
        x = tuple(Fr(t, lat.M) for t in b[:4])
        y = tuple(Fr(t, lat.M) for t in b[4:])
        pq = RC.residue_of_coords(x, y, Sq)
        assert pq is not None
        vals.append(pq[0] + 2 * pq[1])
    return vals


def cmd_classify(out_path):
    lat, r, T = S.degrey_setup()
    U = lat.U
    Q = S.Quot(S.NW(8, r), r)
    cols, pins, note, secs, E = enumerate_colourings(Q, U)
    print(f'enumerated {len(cols)} pinned colourings of Cay(Lambda/8Lambda, U mod 8) ({Q.n} classes, {len(E)} edges) in {secs:.1f} s; '
          f'pins {pins} ({note})', flush=True)
    key = {c.tobytes(): i for i, c in enumerate(cols)}
    assert len(key) == len(cols)
    reps = Q.rep(np.arange(Q.n))
    G, gens = FL.point_group(lat)
    perms = []
    for i in range(r):                                           # translations by the basis vectors
        e = [0] * r
        e[i] = 1
        perms.append(('translate e%d' % (i + 1), Q.shift_by_point(e)))
    for A, (nm, u) in gens.items():                              # the point group's generators
        perms.append((nm, Q.cls(reps @ np.array(A, dtype=np.int64))))
    for nm, p in perms:
        assert sorted(p.tolist()) == list(range(Q.n)), f'{nm} is not a permutation of the classes'
    parent = list(range(len(cols)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    for i, c in enumerate(cols):
        for nm, p in perms:
            img = relabel(c[p], pins)
            j = key.get(img.tobytes())
            assert j is not None, f'the image of colouring {i} under {nm} is not among the enumerated colourings (enumeration incomplete?)'
            a, b = find(i), find(j)
            if a != b:
                parent[a] = b
    orbits = {}
    for i in range(len(cols)):
        orbits.setdefault(find(i), []).append(i)
    s3 = sqrt3_vectors(lat)
    s3cls = [Q.shift_by_point(v) for v in s3]
    clean = [not any(np.any(c[t] == c) for t in s3cls) for c in cols]
    per = []
    for i, c in enumerate(cols):
        H, nper = S.PColour(U, Q, c, f'c{i}').per()
        per.append(S.describe(H, r)['Lambda_mod'])
    res_idx = {}
    for sg in (1, -1):
        ph = np.array(residue_colouring_values(lat, sg), dtype=np.int64)
        colr = (np.mod(reps @ (ph & 1), 2) + 2 * np.mod(reps @ (ph >> 1), 2)).astype(np.int8)
        assert not np.any(colr[E[:, 0]] == colr[E[:, 1]]), 'residue colouring improper'
        res_idx['+S' if sg > 0 else '-S'] = key.get(relabel(colr, pins).tobytes())
    table = []
    for rt, mem in sorted(orbits.items(), key=lambda kv: -len(kv[1])):
        pers = sorted({json.dumps(per[i], sort_keys=True) for i in mem})
        table.append({'size': len(mem), 'members': mem, 'period_groups': [json.loads(p) for p in pers],
                      'sqrt3_clean': sorted({clean[i] for i in mem}),
                      'residue': [k for k, v in res_idx.items() if v in mem]})
    clean_set = sorted(i for i in range(len(cols)) if clean[i])
    g70 = {'sqrt3_vectors': len(s3), 'sqrt3_clean_colourings': clean_set, 'residue_colourings': res_idx,
           'holds': sorted(clean_set) == sorted(v for v in res_idx.values() if v is not None) and None not in res_idx.values()}
    print(f'{len(orbits)} orbits under translations, the point group (order {len(G)}) and colour permutations:', flush=True)
    for t in table:
        print(f"  size {t['size']:4d}  period groups {t['period_groups']}  sqrt3-clean {t['sqrt3_clean']}  residue {t['residue']}",
              flush=True)
    print(f"G70: {len(s3)} sqrt3-vectors; sqrt3-clean colourings {clean_set}; residue colourings {res_idx}; holds: {g70['holds']}",
          flush=True)
    out = {'what': "every proper 4-colouring of Cay(Lambda/8Lambda, U mod 8), de Grey's lattice, pinned (origin 0, least neighbour 1, "
                   'triangle 2), classified under translations, the point group and colour permutations; G70 tested',
           'classes': Q.n, 'edges': int(len(E)), 'pins': [[int(v), c] for v, c in pins], 'enumerated': len(cols),
           'enumeration': {'solver': 'pysat Cadical153, blocking clauses, at-most-one clauses', 'seconds': round(secs, 1),
                           'machine': S.MACHINE},
           'generators': [nm for nm, _ in perms], 'point_group_order': len(G), 'orbits': table, 'G70': g70,
           'period_group_counts': {k: sum(1 for p in per if json.dumps(p, sort_keys=True) == k)
                                   for k in sorted({json.dumps(p, sort_keys=True) for p in per})},
           'colouring_format': 'a string of 4096 digits 0-3: the colour of class index i, i = big-endian mixed radix of the lattice '
                               'coordinates mod 8 (fs73_screen.Quot with W = 8 Lambda, C = I)',
           'orbit_representatives': {str(t['members'][0]): bytes(cols[t['members'][0]].astype(np.uint8) + 48).decode() for t in table},
           'all_colourings': os.path.basename(out_path).replace('.json', '-all.json.gz')}
    import gzip
    with gzip.open(out_path.replace('.json', '-all.json.gz'), 'wt') as f:
        json.dump([bytes(c.astype(np.uint8) + 48).decode() for c in cols], f)
    json.dump(out, open(out_path, 'w'), indent=1)
    print(f'wrote {out_path}', flush=True)
    return 0


def main():
    a = sys.argv[1:]
    if a and a[0] == 'classify':
        op = a[a.index('--out') + 1] if '--out' in a else os.path.join(S.CENSUS, 'K-8Lambda-classes.json')
        return cmd_classify(op)
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main())
