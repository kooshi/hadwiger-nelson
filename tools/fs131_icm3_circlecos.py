#!/usr/bin/env python3
"""FS131-ICM3: the exact arithmetic of `circleCos_bound` (Rigidity/ClassRatio), mirroring the Lean route term for term.

For Q in {23, 31}, with j' = min(j, Q - j), r_j = 2 * PI_LO * j' / Q (a rational) and N Taylor terms:

  cosLow(Q, j) = sum_{m < N} r^m / m! * re(i^m)  -  r^N / N! * 2  -  2 * j' / Q * PI_ERR

(`Complex.exp_bound'` at x = r i, valid since r / (N + 1) <= 1/2; cos 1-Lipschitz; PI_LO < pi < PI_LO + PI_ERR, from
`Real.pi_gt_d20`, `Real.pi_lt_d20`). The table is C_j = floor(D * cosLow(Q, j)), so C_j <= D * cosLow(Q, j) exactly. The
bound is M = -min over (alpha, beta) != 0 of S(alpha, beta), S = sum over the circle {(a, b) : (a^2 + b^2) % Q = 1} of
C_{(alpha a + beta b) % Q}; kappa = M / (D (Q + 1)). The leaf needs, in exact arithmetic:

  3 M < D (Q + 1)        (kappa < 1/3)
  2 D <= M               (2 / (Q + 1) <= kappa)

Also printed, as a reading (mpmath at 60 digits, not part of the proof): the true least sum, cosLow's worst gap below the
true cosine, and the margins.

--plant: the same at Q = 11 and 19, where Hoffman fails; both must read FAILS (exit 0 then, 1 if either holds).
--emit DIR: write the Lean literals (the circle, the table, M) for each Q to DIR/circle<Q>.lean.txt.
"""
import sys
from fractions import Fraction as Fr
from math import factorial, floor

import mpmath

mpmath.mp.dps = 60

PI_LO = Fr(31415926535, 10 ** 10)
PI_ERR = Fr(1, 10 ** 10)
N = 26
D = 10 ** 9


def re_i_pow(m):
    return {0: 1, 1: 0, 2: -1, 3: 0}[m % 4]


def cos_low(Q, j):
    jp = min(j, Q - j)
    r = 2 * PI_LO * jp / Q
    assert r / (N + 1) <= Fr(1, 2)
    t = sum(r ** m / factorial(m) * re_i_pow(m) for m in range(N))
    return t - r ** N / factorial(N) * 2 - Fr(2 * jp, Q) * PI_ERR


def circle(Q):
    return [(a, b) for a in range(Q) for b in range(Q) if (a * a + b * b) % Q == 1]


def run(Q):
    pts = circle(Q)
    assert len(pts) == Q + 1
    low = [cos_low(Q, j) for j in range(Q)]
    C = [floor(D * x) for x in low]
    assert all(Fr(c) <= D * x for c, x in zip(C, low))
    gap = max(mpmath.cos(2 * mpmath.pi * j / Q) - mpmath.mpf(low[j].numerator) / low[j].denominator for j in range(Q))
    assert gap >= 0, "cosLow above the cosine: the route is unsound"
    worst, at = None, None
    true_worst = None
    for al in range(Q):
        for be in range(Q):
            if al == 0 and be == 0:
                continue
            s = sum(C[(al * a + be * b) % Q] for a, b in pts)
            if worst is None or s < worst:
                worst, at = s, (al, be)
            ts = sum(mpmath.cos(2 * mpmath.pi * ((al * a + be * b) % Q) / Q) for a, b in pts)
            if true_worst is None or ts < true_worst:
                true_worst = ts
    M = -worst
    k3 = 3 * M < D * (Q + 1)
    k2 = 2 * D <= M
    holds = k3 and k2
    margin = Fr(D * (Q + 1) - 3 * M, 3 * D)  # (Q+1)/3 - M/D, exact
    print(f"Q={Q} circle={len(pts)} N={N} D={D} PI_LO={PI_LO} PI_ERR={PI_ERR}")
    print(f"  table: worst gap cos - cosLow = {mpmath.nstr(gap, 6)} (>= 0); C_0 = {C[0]}")
    print(f"  least table sum = {worst} at (alpha,beta)={at}; M = {M}; kappa = M/(D(Q+1)) = {Fr(M, D * (Q + 1))}")
    print(f"  true least sum = {mpmath.nstr(true_worst, 15)}; (Q+1)/3 = {mpmath.nstr(mpmath.mpf(Q + 1) / 3, 15)}")
    print(f"  exact: 3M < D(Q+1): {k3}  [(Q+1)/3 - M/D = {margin} = {float(margin):.6e}]; 2D <= M: {k2}")
    print(f"  -> {'HOLDS' if holds else 'FAILS'}")
    return holds, pts, C, M


def emit(Q, pts, C, M, out):
    with open(out, "w") as f:
        f.write(f"-- generated by tools/fs131_icm3_circlecos.py at Q = {Q}\n")
        f.write("circle: [" + ", ".join(f"({a}, {b})" for a, b in pts) + "]\n")
        f.write("table: [" + ", ".join(str(c) for c in C) + "]\n")
        f.write(f"M: {M}\n")


def main(argv):
    plant = "--plant" in argv
    qs = [11, 19] if plant else [23, 31]
    res = []
    for Q in qs:
        holds, pts, C, M = run(Q)
        res.append(holds)
        if "--emit" in argv and not plant:
            d = argv[argv.index("--emit") + 1]
            emit(Q, pts, C, M, f"{d}/circle{Q}.lean.txt")
    if plant:
        ok = not any(res)
        print("plant: " + ("both FAIL, as they must" if ok else "SILENT"))
        return 0 if ok else 1
    return 0 if all(res) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
