class Plane:
    """UD(F_q, 2): vertex index v = x*q + y; two points adjacent iff their difference has quadrance 1.

    G0 is the group generated by the rotations (x, y) -> (ax - by, bx + ay) for (a, b) on the unit circle, the
    reflection (x, y) -> (x, -y) and the Frobenius (x, y) -> (x^p, y^p).  Each GENERATOR is verified here, as a
    permutation of the points, to fix 0, be additive and preserve the unit circle; the group is then their
    closure under composition, so every element is an additive automorphism of the plane, and every map
    z -> g(z - t) is an affine one.  `drop` and `extra` exist only for the self-test's plants."""

    def __init__(self, F: Field, drop: str | None = None, extra=None, log=None):
        t0 = time.time()
        q = F.q
        n = q * q
        self.F, self.q, self.n = F, q, n
        X = [v // q for v in range(n)]
        Yc = [v % q for v in range(n)]
        subq = [[F.sub(a, b) for b in range(q)] for a in range(q)]
        SUB = [0] * (n * n)                       # SUB[a*n + b] = a - b
        for a in range(n):
            rx, ry, base = subq[X[a]], subq[Yc[a]], a * n
            for b in range(n):
                SUB[base + b] = rx[X[b]] * q + ry[Yc[b]]
        self.SUB = SUB
        self.NEG = [F.neg(X[v]) * q + F.neg(Yc[v]) for v in range(n)]
        self.unit = [F.add(F.mul(X[v], X[v]), F.mul(Yc[v], Yc[v])) == F.one for v in range(n)]
        if self.unit[0]:
            raise Refusal("the origin has quadrance 1: the field arithmetic is broken")
        self.circle = [v for v in range(n) if self.unit[v]]
        gens = []
        for c in self.circle:
            a, b = X[c], Yc[c]
            gens.append(("rotation by " + str((a, b)),
                         [F.add(F.mul(a, X[v]), F.neg(F.mul(b, Yc[v]))) * q + F.add(F.mul(b, X[v]), F.mul(a, Yc[v]))
                          for v in range(n)]))
        gens.append(("reflection (x,y)->(x,-y)", [X[v] * q + F.neg(Yc[v]) for v in range(n)]))

        def frob(x):
            r = x
            for _ in range(F.p - 1):
                r = F.mul(r, x)
            return r

        fr = [frob(x) for x in range(q)]
        gens.append((f"Frobenius (x,y)->(x^{F.p},y^{F.p})", [fr[X[v]] * q + fr[Yc[v]] for v in range(n)]))
        if drop is not None:
            gens = [g for g in gens if not g[0].startswith(drop)]
        if extra is not None:
            gens.append(extra)
        axes = [x * q for x in range(q)] + list(range(q))       # the points (x, 0) and (0, y): they generate V
        for name, g in gens:
            self._verify_generator(g, name, axes)
        self.generators = [name for name, _ in gens]
        ident = tuple(range(n))
        G = {ident}
        frontier = [ident]
        gt = [tuple(g) for _, g in gens]
        while frontier:
            nxt = []
            for g in frontier:
                for h in gt:
                    c = tuple(h[g[v]] for v in range(n))
                    if c not in G:
                        G.add(c)
                        nxt.append(c)
            frontier = nxt
        self.G0 = sorted(G)
        for g in self.G0:            # defence in depth: composition preserves both, and it costs n per element
            if g[0] != 0 or any(self.unit[g[v]] != self.unit[v] for v in range(n)):
                raise Refusal("a composite of verified generators moved 0 or the unit circle: the closure is broken")
        self.rep = [min(g[z] for g in self.G0) for z in range(n)]
        self.torep = [[g for g in self.G0 if g[z] == self.rep[z]] for z in range(n)]
        self.seconds = time.time() - t0

    def _verify_generator(self, g, name, axes):
        n, SUB, NEG, unit = self.n, self.SUB, self.NEG, self.unit
        if len(g) != n or sorted(g) != list(range(n)):
            raise Refusal(f"generator {name}: not a permutation of the {n} points")
        if g[0] != 0:
            raise Refusal(f"generator {name}: moves the origin")
        for a in axes:          # g(a + b) = g(a) + g(b) for a on the axes and every b; a + b = a - (-b)
            ga, an = g[a], a * n
            for b in range(n):
                if g[SUB[an + NEG[b]]] != SUB[ga * n + NEG[g[b]]]:
                    raise Refusal(f"generator {name}: not additive at a = {a}, b = {b}")
        for v in range(n):
            if unit[g[v]] != unit[v]:
                raise Refusal(f"generator {name}: does not preserve the unit circle at the point {v}")

    def adjacent(self, a: int, b: int) -> bool:
        return self.unit[self.SUB[a * self.n + b]]

    def key(self, T, want_mult: bool = False):
        """The canonical form of a set T of at least two DISTINCT points: the least, as a sorted tuple, of the
        nonzero points of g(T - t) over t in T and g in G0 -- an image of T under the affine automorphism
        z -> g(z - t).  Only candidates with some g(x - t) equal to the least orbit representative b* among the
        differences can attain the least tuple (its first entry is b*), so only those are formed.  With
        `want_mult`, also the number of (t, g) attaining it, which is |Stab(T)| in V x| G0."""
        n, SUB, rep, torep = self.n, self.SUB, self.rep, self.torep
        best = n
        for t in T:
            for x in T:
                if x != t:
                    r = rep[SUB[x * n + t]]
                    if r < best:
                        best = r
        kb = None
        mult = 0
        for t in T:
            tn = None
            for x in T:
                if x != t:
                    z = SUB[x * n + t]
                    if rep[z] == best:
                        if tn is None:
                            tn = [SUB[w * n + t] for w in T if w != t]
                        for g in torep[z]:
                            img = sorted([g[w] for w in tn])
                            if kb is None or img < kb:
                                kb = img
                                mult = 1
                            elif img == kb:
                                mult += 1
        return (tuple(kb), mult) if want_mult else tuple(kb)

    def key_brute(self, T):
        """The same least image, over EVERY (t, g): the self-test's reference."""
        n, SUB = self.n, self.SUB
        best = None
        for t in T:
            D = [SUB[w * n + t] for w in T if w != t]
            for g in self.G0:
                img = sorted(g[w] for w in D)
                if best is None or img < best:
                    best = img
        return tuple(best)


