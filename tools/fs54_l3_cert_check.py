def y_from_set(P: Plane, S, index: dict, K: int, plant_no_stabiliser: bool = False):
    """y_K = (1/(s |G0|)) * sum over subsets T of S in the orbit K of |Stab(T)|: the average over V x| G0 of
    N(T)/s.  Exact Fractions; returns (y, s)."""
    S = sorted(set(S))
    s = len(S)
    for a, b in itertools.combinations(S, 2):
        if P.adjacent(a, b):
            raise Refusal(f"the set is not independent: {a} and {b} are adjacent")
    num = [0] * K
    for r in (2, 3, 4):
        for T in itertools.combinations(S, r):
            k, mult = P.key(T, want_mult=True)
            v = index.get(k)
            if v is None:
                raise Refusal(f"a subset {T} of the set has the canonical form {(0,) + k}, not a listed variable")
            num[v] += 1 if plant_no_stabiliser else mult
    den = s * len(P.G0)
    return [Fraction(x, den) for x in num], s


def against(cert: dict, S, jobs: int = 1, out=sys.stdout, plant_no_stabiliser: bool = False):
    """(*) evaluated at the averaged counts of a genuine independent set S, every term exact: the objective must be
    |S|, the pairing <Z, A(y_S)> and both multiplier terms must be >= 0, and N - |S| must be their sum.  A check of the
    derivation at a real set, not of the certificate (the identity already implies the last equation)."""
    def log(s):
        print(s, file=out, flush=True)
    F = field_of_cert(cert)
    P = Plane(F)
    index, K = read_variables(cert, P.n)
    mden, lower, upper = read_multipliers(cert, K)
    lf = compute_linear_form(P, cert, index, K, jobs=jobs, log=lambda s: None)
    y, s = y_from_set(P, S, index, K, plant_no_stabiliser)
    L = lf["L"]
    obj = lf["o0"] + sum(t * yy for t, yy in zip(lf["t_obj"], y) if t)
    pairing = Fraction(lf["c0"], L) + sum(Fraction(a, L) * yy for a, yy in zip(lf["acc"], y) if a and yy)
    lam = sum(Fraction(l_, mden) * yy for l_, yy in zip(lower, y) if l_ and yy)
    mu = sum(Fraction(u_, mden) * (1 - yy) for u_, yy in zip(upper, y) if u_)
    N = as_frac(cert["N"], "N")
    ok = obj == s and pairing >= 0 and lam >= 0 and mu >= 0 and N - s == pairing + lam + mu
    log(f"[against] |S| = {s}: sum_u y{{0,u}} = {obj} ({'= |S|' if obj == s else 'NOT |S|'}); <Z, A(y_S)> = {float(pairing):.9f}, "
        f"lambda.y = {float(lam):.9f}, mu.(1-y) = {float(mu):.9f}; N - |S| = {float(N - s):.9f} "
        f"{'= the sum, every term >= 0' if ok else '-- MISMATCH'}")
    return ok


