#!/usr/bin/env python3
"""fs54_l3_cert_check -- the independent checker for an exact upper bound on the independence number of a
finite Euclidean plane UD(F_q, 2), from the LEVEL-3 semidefinite programme (moment matrices localised at a
point or a pair of points, every sign pattern; Gvozdenovic-Laurent-Vallentin's L_3 in Schrijver's
normalisation).

WHAT THIS PROGRAM IS FOR.  A certificate file says: "every set of points of F_q^2 with no two at quadrance 1
has at most N points".  This program decides, in exact arithmetic, whether the file proves that.  It runs no
solver, reads no float, and imports nothing outside the Python standard library (plus, for the field's
arithmetic, the rational reader and the exact LDL^T, the FS-50 checker `fplane_cert_check.py`, which is itself
standard library only).  `plans/FS54-L3-certificate-soundness.md` is the derivation of why the checks below
imply the claim; read it first if you are the stranger this file was written for.

WHAT IT TRUSTS.  Python's integers, `fractions.Fraction`, the JSON parser's reading of integers and strings,
and `fplane_cert_check.Field` (the field F_q named by its modulus; its irreducibility is proved there).
NOTHING in the certificate file is trusted: the plane, its symmetry group, the canonical form of every set of
at most four points, and every coefficient of every matrix entry are rebuilt here from `q` and `modulus`, and
the file's own list of variables is compared against the rebuild.  What the file genuinely supplies is the
matrices' block presentation (any integer column vectors and any rational Gram factor are sound), the
multipliers, and N.

WHAT IT CHECKS, printed in order (silence is never a pass):
  1. the field, the plane (its edge hash against the file's), the symmetry group G0 generated by the
     rotations, the reflection and the Frobenius -- EVERY generator verified to fix 0, be a bijection, be
     additive and preserve the unit circle (so every element of the group generated with the translations is
     an affine automorphism of the plane);
  2. every multiplier is >= 0;
  3. every block is positive semidefinite: a Gram factor G gives Z = G^T G, which is PSD for ANY rational G;
     a dense block is tested by exact LDL^T;
  4. the canonical form (least image under the group) of every set {anchors} + {u, w} that a matrix entry
     touches, the file's variable list against the keys actually met, and the affine identity, coefficient by
     coefficient over the variables and in the constant term:

        N - sum_u y{0,u}  =  sum_matrices <Z, A(y)>  +  sum_K lambda_K y_K  +  sum_K mu_K (1 - y_K)      (*)

     where A(y)[u,w] is the anchored moment matrix entry, expanded by [x not in S] = 1 - [x in S]; a set with
     one point contributes 1, a set with two adjacent points 0, and any other set its variable.  Every term on
     the right is >= 0 at the averaged counts of a genuine independent set S, and the left is N - |S|; so
     |S| <= N.  That implication is the derivation, and it is the only step this program does not perform.

USAGE
  python3 tools/fs54_l3_cert_check.py CERT.json [--k 5] [--jobs 8] [--against SET.json]
  python3 tools/fs54_l3_cert_check.py --self-test

`--k K` adds the colouring sentence when K * floor(N) < q^2.  `--jobs J` spreads the per-anchor work over J
forked processes (standard library `multiprocessing`); the verdict does not depend on it.  `--against` also
evaluates (*) at a verified independent set, term by term (exact, from the set's own subsets).  `--self-test`
checks the canonical form against a brute-force least image, checks the anchored-matrix expansion against its
definition at genuine independent sets, and plants faults in small certificates, watching each refuse.
"""

