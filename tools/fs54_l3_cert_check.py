def field_of_cert(cert: dict) -> Field:
    q = as_int(need(cert, "q", "certificate"), "certificate.q")
    pf = is_prime_power(q)
    if pf is None:
        raise Refusal(f"certificate.q: {q} is neither a prime nor a prime power")
    if "p" in cert and as_int(cert["p"], "certificate.p") != pf[0]:
        raise Refusal(f"certificate.p: the file says {cert['p']}, but q = {q} has characteristic {pf[0]}")
    if "f" in cert and as_int(cert["f"], "certificate.f") != pf[1]:
        raise Refusal(f"certificate.f: the file says {cert['f']}, but {q} = {pf[0]}^{pf[1]}")
    F = Field(q, cert.get("modulus"))
    if q % 4 != 3:
        raise Refusal(f"certificate.q: {q} is not 3 mod 4 -- this checker has only been exercised on such planes")
    return F


def parse_anchors(obj, n: int, where: str):
    """[[point, "+"|"-"], ...]: at most two distinct points.  The matrix is
    A[u, w] = (1/s) sum_z prod_a [z + a in S]^(sign a) [z + u in S][z + w in S], expanded by [.]^- = 1 - [.]
    into sum over subsets B of the negative anchors of (-1)^|B| N(positive anchors + B + {u, w}) / s.
    Returned: the expansion as a list of (coefficient, tuple of anchor points)."""
    if not isinstance(obj, list) or len(obj) > 2:
        raise Refusal(f"{where}: expected a list of at most two [point, sign] anchors (more would touch sets of five "
                      f"points, which are not variables of this programme)")
    pts, signs = [], []
    for i, a in enumerate(obj):
        if not (isinstance(a, list) and len(a) == 2):
            raise Refusal(f"{where}[{i}]: expected [point, sign]")
        p = as_int(a[0], f"{where}[{i}][0]")
        if not 0 <= p < n:
            raise Refusal(f"{where}[{i}][0]: point {p} is not in 0..{n - 1}")
        if a[1] not in ("+", "-"):
            raise Refusal(f"{where}[{i}][1]: sign {a[1]!r} is neither '+' nor '-'")
        pts.append(p)
        signs.append(a[1])
    if len(set(pts)) != len(pts):
        raise Refusal(f"{where}: the anchors are not distinct points")
    pos = [p for p, s in zip(pts, signs) if s == "+"]
    neg = [p for p, s in zip(pts, signs) if s == "-"]
    terms = []
    for r in range(len(neg) + 1):
        for B in itertools.combinations(neg, r):
            chosen = [p for p in pts if p in pos or p in B]          # keep the file's anchor order
            terms.append(((-1) ** r, tuple(chosen)))
    return terms


def parse_columns(obj, n: int, where: str):
    """A block's columns: each a flat list [point, integer coefficient, point, coefficient, ...] -- the integer
    vector U e_i.  Any integer matrix U is sound (U Z U^T is PSD whenever Z is)."""
    if not isinstance(obj, list):
        raise Refusal(f"{where}: expected a list of columns")
    cols = []
    for i, c in enumerate(obj):
        if not isinstance(c, list) or len(c) % 2 or not c:
            raise Refusal(f"{where}[{i}]: expected a nonempty flat list [point, coefficient, ...]")
        col, seenp = [], set()
        for j in range(0, len(c), 2):
            p = as_int(c[j], f"{where}[{i}][{j}]")
            v = as_int(c[j + 1], f"{where}[{i}][{j + 1}]")
            if not 0 <= p < n:
                raise Refusal(f"{where}[{i}][{j}]: point {p} is not in 0..{n - 1}")
            if p in seenp:
                raise Refusal(f"{where}[{i}]: the point {p} appears twice")
            seenp.add(p)
            col.append((p, v))
        cols.append(col)
    return cols


def parse_block(blk, n: int, where: str, force_ldl: bool = False):
    """Returns (columns, kind, rows, m, flat numerators, denominator of Z's numerators, note).  kind 'gram': Z =
    G^T G / den^2 with G r x m; kind 'dense': Z = num / den, tested by exact LDL^T here."""
    cols = parse_columns(need(blk, "columns", where), n, f"{where}.columns")
    m = len(cols)
    if "gram" in blk and "Z" in blk:
        raise Refusal(f"{where}: give either a Gram factor or a dense Z, not both")
    if "gram" in blk:
        g = blk["gram"]
        if isinstance(g, dict) and g.get("num") == []:
            return cols, "gram", 0, m, [], 1, "rank 0"
        r, c, flat, den = parse_int_matrix(g, f"{where}.gram")
        if c != m:
            raise Refusal(f"{where}.gram: {c} columns but the block has {m}")
        note = f"Gram factor {r}x{m} (Z = G^T G: positive semidefinite for any rational G)"
        if force_ldl:
            zflat = gram_dense(flat, r, m)
            ok, why = ldl_psd(zflat, den * den, m)
            if not ok:
                raise Refusal(f"{where}: the Gram block fails the exact LDL test -- {why}")
            note += "; LDL^T re-run and clean"
        return cols, "gram", r, m, flat, den * den, note
    if "Z" in blk:
        r, c, flat, den = parse_int_matrix(blk["Z"], f"{where}.Z")
        if r != m or c != m:
            raise Refusal(f"{where}.Z: shape {r}x{c}, but the block has {m} columns")
        ok, why = ldl_psd(flat, den, m)
        if not ok:
            raise Refusal(f"{where}: the block is NOT positive semidefinite -- {why}")
        return cols, "dense", m, m, flat, den, f"dense {m}x{m}, PSD by exact LDL^T"
    raise Refusal(f"{where}: neither a 'gram' factor nor a dense 'Z'")


def gram_dense(flat, r, m):
    colsG = [[flat[k * m + i] for k in range(r)] for i in range(m)]
    out = [0] * (m * m)
    for i in range(m):
        gi = colsG[i]
        for j in range(i, m):
            s = sum(map(int.__mul__, gi, colsG[j]))
            out[i * m + j] = s
            out[j * m + i] = s
    return out


