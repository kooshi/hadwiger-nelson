class Tables:
    """Variable codes of the sets the entries touch, translated so that one anchor is the origin:
    key2[z] for {0, z}; key3[u*n + w] for {0, u, w}; key4[d][u*n + w] for {0, d, u, w}.  A code is a variable
    index (from the file's list, compared here), KILLED or CONST.  `seen` records which variables were met."""

    def __init__(self, plane: Plane, index: dict, K: int):
        self.P, self.index, self.K = plane, index, K
        self.seen = bytearray(K)
        self.key2 = None
        self.key3 = None
        self.key4 = {}

    def code(self, pts):
        P = self.P
        S = []
        for x in pts:
            if x not in S:
                S.append(x)
        if len(S) == 1:
            return CONST
        n, SUB, unit = P.n, P.SUB, P.unit
        for i in range(len(S)):
            for j in range(i + 1, len(S)):
                if unit[SUB[S[i] * n + S[j]]]:
                    return KILLED
        k = P.key(S)
        v = self.index.get(k)
        if v is None:
            raise Refusal(f"the set {sorted(S)} has the canonical form {list((0,) + k)}, which is not in the file's "
                          f"variable list -- the file's variables are not this plane's orbits")
        self.seen[v] = 1
        return v

    def build2(self):
        n = self.P.n
        self.key2 = [CONST] + [self.code((0, z)) for z in range(1, n)]

    def build3(self):
        n = self.P.n
        T = [0] * (n * n)
        for u in range(n):
            for w in range(u, n):
                c = self.code((0, u, w))
                T[u * n + w] = c
                T[w * n + u] = c
        self.key3 = T

    def build4(self, d):
        n = self.P.n
        T = [0] * (n * n)
        for u in range(n):
            for w in range(u, n):
                c = self.code((0, d, u, w))
                T[u * n + w] = c
                T[w * n + u] = c
        self.key4[d] = T


def matrix_E(plane: Plane, blocks, L: int):
    """E[u*n + w] = the numerator (over L) of sum_b (U_b Z_b U_b^T)[u, w], folded so that only u <= w carries
    weight: <sum U Z U^T, A> = sum_{u<=w} E'[u,w] A[u,w] with A symmetric as a linear form."""
    n = plane.n
    E = [0] * (n * n)
    for (cols, kind, r, m, flat, zden) in blocks:
        if kind == "gram" and r == 0:
            continue
        scale = L // zden
        if kind == "gram":
            G = [[flat[k * m + i] for k in range(r)] for i in range(m)]
        for i in range(m):
            ci = cols[i]
            gi = G[i] if kind == "gram" else None
            for j in range(i, m):
                z = sum(map(int.__mul__, gi, G[j])) if kind == "gram" else flat[i * m + j]
                if not z:
                    continue
                z *= scale if i == j else 2 * scale
                cj = cols[j]
                for (u, a) in ci:
                    za = z * a
                    un = u * n
                    for (w, b) in cj:
                        if u <= w:
                            E[un + w] += za * b
                        else:
                            E[w * n + u] += za * b
    return E


def pair_matrix(plane: Plane, tabs: Tables, terms, E, acc, where: str):
    """Adds <Z, A(y)> for one matrix into acc (variable coefficients); returns the constant part.  Each term is
    (coefficient, anchor points); the set anchors + {u, w} is looked up translated by its first anchor."""
    n, SUB = plane.n, plane.SUB
    c0 = 0
    plan = []
    zero_term = None
    for coef, pts in terms:
        if len(pts) == 0:
            zero_term = coef
        elif len(pts) == 1:
            a = pts[0]
            plan.append((coef, tabs.key3, [SUB[x * n + a] for x in range(n)]))
        else:
            a1, a2 = pts
            d = SUB[a2 * n + a1]
            if d not in tabs.key4:
                raise Refusal(f"{where}: internal -- the table for d = {d} was not built")
            plan.append((coef, tabs.key4[d], [SUB[x * n + a1] for x in range(n)]))
    key2 = tabs.key2
    for u in range(n):
        un = u * n
        rows = [(coef, tab, Sa[u] * n, Sa) for (coef, tab, Sa) in plan]
        for w in range(u, n):
            e = E[un + w]
            if not e:
                continue
            for coef, tab, base, Sa in rows:
                v = tab[base + Sa[w]]
                if v >= 0:
                    acc[v] += coef * e
                elif v == CONST:
                    c0 += coef * e
            if zero_term is not None:
                if u == w:
                    c0 += zero_term * e
                else:
                    v = key2[SUB[w * n + u]]
                    if v >= 0:
                        acc[v] += zero_term * e
    return c0


def needed_tables(matrices_terms, plane: Plane):
    need3, need4 = False, set()
    n, SUB = plane.n, plane.SUB
    for terms in matrices_terms:
        for _c, pts in terms:
            if len(pts) == 1:
                need3 = True
            elif len(pts) == 2:
                need4.add(SUB[pts[1] * n + pts[0]])
    return need3, need4


_W = {}          # the forked workers' inherited state


def _work(task):
    """One task: build the key4 table for d (if any) and pair every matrix that needs it."""
    d, mids = task
    P, tabs, parsed, L, K = _W["P"], _W["tabs"], _W["parsed"], _W["L"], _W["K"]
    tabs.seen = bytearray(K)
    t0 = time.time()
    if d is not None:
        tabs.build4(d)
    tb = time.time() - t0
    acc = [0] * K
    c0 = 0
    for mi in mids:
        terms, blocks = parsed[mi]
        E = matrix_E(P, blocks, L)
        c0 += pair_matrix(P, tabs, terms, E, acc, f"certificate.matrices[{mi}]")
        del E
    return d, mids, acc, c0, bytes(tabs.seen), tb, time.time() - t0


def compute_linear_form(P: Plane, cert: dict, index: dict, K: int, jobs: int = 1, log=print, force_ldl=False):
    """The file's matrices, parsed and PSD-checked, then sum <Z, A(y)> as (constant numerator, coefficient
    numerators over the variables, common denominator L), plus the objective and the variables met."""
    mats = need(cert, "matrices", "certificate")
    if not isinstance(mats, list) or not mats:
        raise Refusal("certificate.matrices: expected a nonempty list")
    parsed = []
    nblocks = ngram = ndense = 0
    rank_m = 0
    dens = set()
    for mi, mo in enumerate(mats):
        where = f"certificate.matrices[{mi}]"
        terms = parse_anchors(need(mo, "anchors", where), P.n, f"{where}.anchors")
        blist = need(mo, "blocks", where)
        if not isinstance(blist, list):
            raise Refusal(f"{where}.blocks: expected a list")
        blocks = []
        for bi, blk in enumerate(blist):
            cols, kind, r, m, flat, zden, _note = parse_block(blk, P.n, f"{where}.blocks[{bi}]", force_ldl)
            blocks.append((cols, kind, r, m, flat, zden))
            dens.add(zden)
            nblocks += 1
            ngram += kind == "gram"
            ndense += kind == "dense"
            rank_m += r * m
        parsed.append((terms, blocks))
    L = 1
    for dd in dens:
        L = L * dd // math.gcd(L, dd)
    log(f"check 3/5  positive semidefiniteness: {nblocks} blocks over {len(mats)} matrices -- {ngram} by a rational Gram "
        f"factor G (Z = G^T G, PSD for any rational G; {rank_m} Gram entries), {ndense} dense and PSD by exact LDL^T; "
        f"common denominator of the Z numerators {L if L < 10**30 else f'~10^{len(str(L)) - 1}'}")

    tabs = Tables(P, index, K)
    t0 = time.time()
    tabs.build2()
    need3, need4 = needed_tables([t for t, _ in parsed], P)
    if need3:
        tabs.build3()
    log(f"check 4/5  canonical forms: {'pairs and triples' if need3 else 'pairs'} tabulated in {time.time() - t0:.1f} s; "
        f"{len(need4)} pair-anchor table(s) of quadruples to build (d = {sorted(need4)})")
    base_seen = bytearray(tabs.seen)
    # the objective: sum_u y{0,u}
    t_obj = [0] * K
    o0 = 1
    for z in range(1, P.n):
        v = tabs.key2[z]
        if v >= 0:
            t_obj[v] += 1
    # tasks: one per d, plus one for the matrices with at most one anchor point in every term
    groups = {}
    for mi, (terms, _b) in enumerate(parsed):
        ds = {P.SUB[pts[1] * P.n + pts[0]] for _c, pts in terms if len(pts) == 2}
        d = next(iter(ds)) if ds else None
        groups.setdefault(d, []).append(mi)
    tasks = sorted(groups.items(), key=lambda kv: (kv[0] is None, kv[0] if kv[0] is not None else 0))
    acc = [0] * K
    c0 = 0
    seen = bytearray(base_seen)
    _W.update(P=P, tabs=tabs, parsed=parsed, L=L, K=K)
    t1 = time.time()
    if jobs > 1 and len(tasks) > 1:
        import multiprocessing as mp
        ctx = mp.get_context("fork")
        with ctx.Pool(min(jobs, len(tasks))) as pool:
            results = pool.imap_unordered(_work, tasks)
            results = list(_drain(results, log))
    else:
        results = list(_drain(map(_work, tasks), log))
    for d, mids, a, c, sn, tb, tt in results:
        for i, x in enumerate(a):
            if x:
                acc[i] += x
        c0 += c
        for i, x in enumerate(sn):
            if x:
                seen[i] = 1
    log(f"           the pairing over {len(parsed)} matrices in {len(tasks)} task(s), {jobs} job(s): {time.time() - t1:.1f} s")
    return dict(c0=c0, acc=acc, L=L, t_obj=t_obj, o0=o0, seen=seen, matrices=len(parsed), blocks=nblocks)


def _drain(it, log):
    for res in it:
        d, mids, _a, _c, _sn, tb, tt = res
        log(f"           task d = {d}: matrices {mids}, table {tb:.1f} s, total {tt:.1f} s")
        yield res


def read_variables(cert: dict, n: int):
    vs = need(cert, "variables", "certificate")
    if not isinstance(vs, list) or not vs:
        raise Refusal("certificate.variables: expected a nonempty list of canonical sets")
    index = {}
    prev = None
    for i, v in enumerate(vs):
        where = f"certificate.variables[{i}]"
        if not isinstance(v, list) or not 2 <= len(v) <= 4:
            raise Refusal(f"{where}: expected a list of 2 to 4 points")
        pts = [as_int(x, f"{where}[{j}]") for j, x in enumerate(v)]
        if pts[0] != 0 or any(not (pts[j] < pts[j + 1]) for j in range(len(pts) - 1)) or pts[-1] >= n:
            raise Refusal(f"{where}: {pts} is not a strictly increasing list of points starting at 0")
        k = (len(pts), tuple(pts))
        if prev is not None and not prev < k:
            raise Refusal(f"{where}: the list is not sorted by (size, points)")
        prev = k
        index[tuple(pts[1:])] = i
    return index, len(vs)


def read_multipliers(cert: dict, K: int):
    mo = need(cert, "multipliers", "certificate")
    den = as_int(need(mo, "den", "certificate.multipliers"), "certificate.multipliers.den")
    if den <= 0:
        raise Refusal(f"certificate.multipliers.den: {den} is not positive")
    out = {}
    for name in ("lower", "upper"):
        lst = need(mo, name, "certificate.multipliers")
        if not isinstance(lst, list) or len(lst) != K:
            raise Refusal(f"certificate.multipliers.{name}: expected {K} integers, one per variable")
        vals = [as_int(x, f"certificate.multipliers.{name}[{i}]") for i, x in enumerate(lst)]
        for i, x in enumerate(vals):
            if x < 0:
                row = "y_K >= 0" if name == "lower" else "1 - y_K >= 0"
                raise Refusal(f"multiplier {name}[{i}] (on the valid inequality {row} of variable {i}) is negative: "
                              f"{Fraction(x, den)}")
        out[name] = vals
    return den, out["lower"], out["upper"]


def check(cert: dict, k: int | None = None, jobs: int = 1, force_ldl: bool = False, out=sys.stdout) -> str:
    """Run every check and return the final sentence.  Raises `Refusal` at the first failure."""
    def log(s):
        print(s, file=out, flush=True)

    t_all = time.time()
    kind = need(cert, "kind", "certificate")
    if kind != KIND:
        raise Refusal(f"the file's kind is {kind!r}, not {KIND!r}")
    F = field_of_cert(cert)
    N = as_frac(need(cert, "N", "certificate"), "certificate.N")
    alpha = as_int(need(cert, "alpha_bound", "certificate"), "certificate.alpha_bound")
    if N < 1:
        raise Refusal(f"certificate.N: {N} < 1, but a one-point set is independent")
    if alpha != math.floor(N):
        raise Refusal(f"certificate.alpha_bound: {alpha}, but floor(N) = {math.floor(N)}")

    # ---- 1. field, plane, group
    P = Plane(F)
    n = P.n
    got = graph_sha256(F)
    want = need(cert, "edges_sha256", "certificate")
    if want != got:
        raise Refusal(f"certificate.edges_sha256: the file says {want!r}, but the plane rebuilt from {F.source} hashes "
                      f"to {got!r} -- the certificate is about a different graph")
    log(f"check 1/5  plane rebuilt from {F.source}: {n} points, degree {len(P.circle)}, edges_sha256 {got[:16]}... "
        f"agrees with the file; G0 generated by {len(P.generators)} verified generators (each fixes 0, is a bijection, "
        f"additive, preserves the unit circle) has {len(P.G0)} elements; {P.seconds:.1f} s")

    # ---- 2. variables and multipliers
    index, K = read_variables(cert, n)
    mden, lower, upper = read_multipliers(cert, K)
    nz_l = sum(1 for x in lower if x)
    nz_u = sum(1 for x in upper if x)
    log(f"check 2/5  {K} variables listed; multipliers over the denominator {mden if mden < 10**30 else '~10^' + str(len(str(mden)) - 1)}: "
        f"{nz_l} nonzero on y_K >= 0 and {nz_u} on 1 - y_K >= 0, every one >= 0")

    # ---- 3 and 4. blocks, canonical forms, pairing
    lf = compute_linear_form(P, cert, index, K, jobs=jobs, log=log, force_ldl=force_ldl)
    missing = [i for i in range(K) if not lf["seen"][i]]
    if missing:
        i = missing[0]
        raise Refusal(f"certificate.variables[{i}] = {cert['variables'][i]}: no matrix entry touches it ({len(missing)} "
                      f"such) -- the file's variables are not the sets its matrices use")
    log(f"           the file's {K} variables are exactly the canonical forms the entries met")

    # ---- 5. the identity (*), coefficient by coefficient, and N
    L, acc, c0, t_obj, o0 = lf["L"], lf["acc"], lf["c0"], lf["t_obj"], lf["o0"]
    LM = L * mden
    for i in range(K):
        if -t_obj[i] * LM != acc[i] * mden + (lower[i] - upper[i]) * L:
            lhs = Fraction(-t_obj[i])
            rhs = Fraction(acc[i], L) + Fraction(lower[i] - upper[i], mden)
            raise Refusal(f"the identity fails at variable {i} (the set {cert['variables'][i]}): the left side's "
                          f"coefficient is {lhs}, the right side's {rhs} (difference {float(lhs - rhs):.3e})")
    sum_mu = Fraction(sum(upper), mden)
    Nrec = Fraction(o0) + Fraction(c0, L) + sum_mu
    if Nrec != N:
        raise Refusal(f"the identity's constant term fails: the file's N = {N} (~{float(N):.9f}), but o0 + <Z, A>'s "
                      f"constant + sum mu = {Nrec} (~{float(Nrec):.9f}); the file claims {'LESS' if N < Nrec else 'more'} "
                      f"than its own multipliers prove")
    log(f"check 5/5  the identity N - sum_u y{{0,u}} = sum <Z, A(y)> + sum lambda y + sum mu (1 - y): all {K} coefficients "
        f"and the constant term agree exactly; N recomputed = {float(Nrec):.9f} (sum mu = {float(sum_mu):.6f})")
    sentence = (f"CERTIFIED: every independent set of UD(F_{F.q}, 2){'' if F.f == 1 else ' [' + F.modulus + ']'} has at most "
                f"{N} points, hence at most {alpha} -- exact arithmetic, no solver trusted ({time.time() - t_all:.0f} s)")
    log(sentence)
    if k is not None:
        if k * alpha < n:
            log(f"hence UD(F_{F.q}, 2) is not {k}-colourable ({k} * {alpha} = {k * alpha} < {n}) and its chromatic number "
                f"is at least {k + 1}")
        else:
            log(f"this says nothing about {k}-colourability: {k} * {alpha} = {k * alpha} >= {n}")
    return sentence


