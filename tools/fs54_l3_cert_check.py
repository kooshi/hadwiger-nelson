def definitional_matrix(P: Plane, S, anchors):
    """The G0-average of (1/s) sum_z prod_a [z + a in S']^(sign) xi xi^T over S' = gS, straight from the
    definition, as a dict {(u, w): Fraction} (zero entries omitted).  Translations need no averaging: the
    matrix of S + c equals the matrix of S (substitute z -> z - c)."""
    n, SUB, NEG = P.n, P.SUB, P.NEG
    s = len(S)
    acc = {}
    for g in P.G0:
        gS = set(g[x] for x in S)
        for z in range(n):
            wgt = 1
            for a, sg in anchors:
                inside = SUB[z * n + NEG[a]] in gS            # z + a = z - (-a)
                wgt *= inside if sg == "+" else (not inside)
                if not wgt:
                    break
            if not wgt:
                continue
            xs = [u for u in range(n) if SUB[z * n + NEG[u]] in gS]
            for u in xs:
                for w in xs:
                    acc[(u, w)] = acc.get((u, w), 0) + 1
    den = s * len(P.G0)
    return {k: Fraction(v, den) for k, v in acc.items()}


def y_definitional(P: Plane, S, T):
    """y(T) = #{(g, c) : g T + c inside S} / (s |G0|) -- the definition, with no canonical form involved.  (The
    average of N_{gS + c}(T)/s over the group V x| G0 is (1/(n |G0| s)) #{(g, c, z) : z + T inside g'S + c'}, which
    reindexes to n #{(g, c) : gT + c inside S} / (n |G0| s).)  Only c = s0 - g(T[0]) with s0 in S can work."""
    n, SUB, NEG = P.n, P.SUB, P.NEG
    Sset = set(S)
    cnt = 0
    for g in P.G0:
        gT = [g[t] for t in T]
        g0 = gT[0]
        for s0 in S:
            c = SUB[s0 * n + g0]                          # c = s0 - g(T[0])
            if all(SUB[x * n + NEG[c]] in Sset for x in gT):
                cnt += 1
    return Fraction(cnt, len(S) * len(P.G0))


def definitional_entry(P: Plane, gsets, s: int, anchors, u: int, w: int):
    """A[u, w] of the anchored matrix, from its definition: the G0-average of (1/s) sum_z prod_a [z + a in gS]^sign
    [z + u in gS][z + w in gS].  Only z in gS - u can contribute, so z runs over those."""
    n, SUB, NEG = P.n, P.SUB, P.NEG
    total = 0
    nu = NEG[u]
    for gS in gsets:
        for x in gS:
            z = SUB[x * n + u]                            # z = x - u, so z + u = x is in gS
            if SUB[z * n + NEG[w]] not in gS:
                continue
            ok = True
            for a, sg in anchors:
                inside = SUB[z * n + NEG[a]] in gS
                if inside != (sg == "+"):
                    ok = False
                    break
            if ok:
                total += 1
    return Fraction(total, s * len(gsets))


def expansion_check(cert: dict, S, samples: int, seed: int = 1, out=sys.stdout, plant: str | None = None):
    """For every matrix the certificate carries, `samples` random entries (u, w): the checker's keyed expansion
    evaluated at the definitional averaged counts of the genuine set S, against the entry computed from its
    definition.  A check of the programme's semantics on THIS plane (the self-test does all entries at q = 7, where
    the Frobenius is trivial).  Returns (mismatches, checked, nonzero)."""
    def log(x):
        print(x, file=out, flush=True)
    F = field_of_cert(cert)
    P = Plane(F)
    n = P.n
    S = sorted(set(S))
    for a, b in itertools.combinations(S, 2):
        if P.adjacent(a, b):
            raise Refusal(f"the set is not independent: {a} and {b} are adjacent")
    gsets = [set(g[x] for x in S) for g in P.G0]
    rng = random.Random(seed)
    cache = {}
    mism = checked = nonzero = 0
    t0 = time.time()
    for mi, mo in enumerate(need(cert, "matrices", "certificate")):
        anchors = [(int(a), sg) for a, sg in mo["anchors"]]
        terms = parse_anchors(mo["anchors"], n, f"matrices[{mi}].anchors")
        if plant == "sign":
            terms = [(abs(c), pts) for c, pts in terms]
        for _ in range(samples):
            u, w = rng.randrange(n), rng.randrange(n)
            val = Fraction(0)
            for c, pts in terms:
                Tset = []
                for x in list(pts) + [u, w]:
                    if x not in Tset:
                        Tset.append(x)
                if len(Tset) == 1:
                    yv = Fraction(1)
                elif any(P.adjacent(a, b) for a, b in itertools.combinations(Tset, 2)):
                    yv = Fraction(0)
                else:
                    kk = P.key(Tset)
                    if kk not in cache:
                        cache[kk] = y_definitional(P, S, (0,) + kk)
                    yv = cache[kk]
                val += c * yv
            d = definitional_entry(P, gsets, len(S), anchors, u, w)
            checked += 1
            nonzero += d != 0
            if val != d:
                mism += 1
    log(f"[expansion] q = {F.q}, |S| = {len(S)}: {checked} sampled entries of {len(cert['matrices'])} matrices "
        f"({nonzero} nonzero), keyed expansion vs definition: {mism} mismatches{' [PLANT: every sign +]' if plant else ''}; "
        f"{len(cache)} canonical forms evaluated from the definition; {time.time() - t0:.0f} s")
    return mism, checked, nonzero


def random_maximal_set(P: Plane, rng):
    order = list(range(P.n))
    rng.shuffle(order)
    S = []
    for v in order:
        if all(not P.adjacent(v, x) for x in S):
            S.append(v)
    return S


def synthetic_certificate(q: int, modulus=None, dense: bool = False, seed: int = 7):
    """A small, genuinely valid certificate at q built with no solver: the standard 3 + 3|classes| matrices, each
    with one block whose columns are single points and whose Gram factor is a small integer matrix; the
    multipliers and N are then DETERMINED (mu = max(0, a), lambda = max(0, -a)).  Weak, but exact and sound: it is
    the fixture the plants are made from."""
    F = Field(q, modulus)
    P = Plane(F)
    n = P.n
    rng = random.Random(seed)
    classes = sorted(set(P.rep[1:]))
    mats = [[[0, "+"]], [[0, "-"]]]
    for d in classes:
        if not P.unit[d]:
            mats += [[[0, "+"], [d, "+"]], [[0, "+"], [d, "-"]]]
        mats.append([[0, "-"], [d, "-"]])
    matrices = []
    den = 5
    for anchors in mats:
        pts = rng.sample(range(n), 3)
        cols = [[p, 1] for p in pts]
        G = [[rng.randint(-2, 2) for _ in range(3)] for _ in range(2)]
        if dense:
            Z = [[sum(G[k][i] * G[k][j] for k in range(2)) for j in range(3)] for i in range(3)]
            matrices.append({"anchors": anchors, "blocks": [{"columns": cols, "Z": {"den": den * den, "num": Z}}]})
        else:
            matrices.append({"anchors": anchors, "blocks": [{"columns": cols, "gram": {"den": den, "num": G}}]})
    # the variables: every canonical form the tables meet, found by building with an open index
    index_all = {}

    class OpenIndex(dict):
        def get(self, k, default=None):
            if k not in self:
                self[k] = len(self)
            return dict.get(self, k)

    oi = OpenIndex()
    tabs = Tables(P, oi, 10 ** 7)
    tabs.build2()
    need3, need4 = needed_tables([parse_anchors(a, n, "a") for a in mats], P)
    if need3:
        tabs.build3()
    for d in sorted(need4):
        tabs.build4(d)
    keys = sorted(oi.keys(), key=lambda k: (len(k), k))
    variables = [[0] + list(k) for k in keys]
    index_all = {k: i for i, k in enumerate(keys)}
    cert = {"kind": KIND, "q": q, "p": F.p, "f": F.f, "modulus": modulus, "edges_sha256": graph_sha256(F),
            "N": "0", "alpha_bound": 0, "variables": variables, "matrices": matrices,
            "multipliers": {"den": 1, "lower": [0] * len(keys), "upper": [0] * len(keys)}}
    fill_multipliers(cert, P, index_all, len(keys))
    return cert


def fill_multipliers(cert: dict, P: Plane, index: dict, K: int, jobs: int = 1, log=lambda s: None):
    """Given the matrices, set lambda, mu and N to the values the identity DETERMINES (the producer's rule):
    a_K = t_K + c_K; mu_K = max(0, a_K); lambda_K = max(0, -a_K); N = o0 + c0 + sum mu.  Uses this checker's own
    pairing, so the numbers are exactly what `check` will verify."""
    lf = compute_linear_form(P, cert, index, K, jobs=jobs, log=log)
    L = lf["L"]
    lower, upper = [], []
    for i in range(K):
        a = lf["t_obj"][i] * L + lf["acc"][i]       # numerator over L
        upper.append(a if a > 0 else 0)
        lower.append(-a if a < 0 else 0)
    N = Fraction(lf["o0"]) + Fraction(lf["c0"], L) + Fraction(sum(upper), L)
    cert["multipliers"] = {"den": L, "lower": lower, "upper": upper}
    cert["N"] = f"{N.numerator}/{N.denominator}"
    cert["alpha_bound"] = math.floor(N)
    return lf


def self_test(out=sys.stdout) -> bool:
    def log(s):
        print(s, file=out, flush=True)

    quiet = open(os.devnull, "w")
    failures = []

    def red(name, fn, fragment):
        try:
            fn()
        except Refusal as e:
            msg = str(e)
            if fragment.lower() in msg.lower():
                log(f"  RED (as designed)   {name}\n                      -> {msg[:200]}")
                return
            failures.append(f"{name}: refused for the wrong reason: {msg}")
            log(f"  RED, WRONG REASON   {name} -> {msg[:200]}")
            return
        except Exception as e:        # noqa: BLE001
            failures.append(f"{name}: raised {type(e).__name__}: {e}")
            log(f"  BROKE               {name} -> {type(e).__name__}: {e}")
            return
        failures.append(f"{name}: ACCEPTED a planted fault")
        log(f"  GREEN -- NOT OK     {name}")

    def green(name, fn):
        try:
            r = fn()
            log(f"  GREEN (as designed) {name}" + (f"\n                      -> {str(r)[:200]}" if r else ""))
        except Exception as e:        # noqa: BLE001
            failures.append(f"{name}: the faithful case failed: {e}")
            log(f"  RED -- NOT OK       {name} -> {e}")

    log("=== 1. the group: generators verified, and a plant of each kind refused ===")
    for q, mod, want in ((7, None, 16), (11, None, 24), (27, "t^3-t-1", 168), (27, "t^3-t-2", 168)):
        P = Plane(Field(q, mod))
        ok = len(P.G0) == want
        log(f"  q = {q}{'' if mod is None else ' [' + mod + ']'}: |G0| = {len(P.G0)} (expected {want}) "
            f"{'ok' if ok else 'WRONG'}")
        if not ok:
            failures.append(f"|G0| at q = {q}: {len(P.G0)}")
    F7 = Field(7)
    swap = list(range(49))
    swap[1], swap[2] = swap[2], swap[1]
    red("a planted non-additive generator (swap two points)", lambda: Plane(F7, extra=("planted swap", swap)), "not additive")
    dbl = [(2 * (v // 7) % 7) * 7 + (2 * (v % 7)) % 7 for v in range(49)]
    red("a planted additive map that does not preserve the circle (z -> 2z)",
        lambda: Plane(F7, extra=("planted doubling", dbl)), "does not preserve the unit circle")

    log("=== 2. the canonical form against the brute-force least image ===")
    for q, mod, trials in ((7, None, 4000), (11, None, 1500), (27, "t^3-t-1", 300)):
        P = Plane(Field(q, mod))
        rng = random.Random(q)
        bad = 0
        for _ in range(trials):
            T = rng.sample(range(P.n), rng.choice((2, 3, 4)))
            if P.key(T) != P.key_brute(T):
                bad += 1
        log(f"  q = {q}: {trials} random sets of 2-4 points, {bad} disagreements")
        if bad:
            failures.append(f"canonical form disagrees at q = {q} on {bad} sets")
    P27 = Plane(Field(27, "t^3-t-1"))
    Pdrop = Plane(Field(27, "t^3-t-1"), drop="Frobenius")
    rng = random.Random(5)
    diff = 0
    for _ in range(300):
        T = rng.sample(range(729), 4)
        diff += Pdrop.key(T) != P27.key_brute(T)
    log(f"  plant: the key computed WITHOUT the Frobenius against the full group's brute force at 27: {diff} of 300 "
        f"disagree {'(RED as designed: the comparison can fire)' if diff else '(NOT OK: the comparison is blind)'}")
    if not diff:
        failures.append("dropping the Frobenius was not detected by the brute-force comparison")

    log("=== 3. the expansion against the definition, at genuine independent sets (q = 7) ===")
    P = Plane(F7)
    rng = random.Random(11)
    classes = sorted(set(P.rep[1:]))
    anchor_list = [[[0, "+"]], [[0, "-"]], []]
    for d in classes:
        anchor_list += [[[0, "+"], [d, "+"]], [[0, "+"], [d, "-"]], [[0, "-"], [d, "+"]], [[0, "-"], [d, "-"]]]

    def expansion_matches(S, plant=None):
        s = len(S)
        mism = 0
        cache = {}
        for anchors in anchor_list:
            terms = parse_anchors(anchors, P.n, "a")
            if plant == "sign":
                terms = [(abs(c), pts) for c, pts in terms]
            D = definitional_matrix(P, S, [(a, sg) for a, sg in anchors])
            for u in range(P.n):
                for w in range(P.n):
                    val = Fraction(0)
                    for c, pts in terms:
                        if plant == "untranslated" and len(pts) == 1:
                            T = [0, u, w]
                        else:
                            T = list(pts) + [u, w]
                        Tset = []
                        for x in T:
                            if x not in Tset:
                                Tset.append(x)
                        if len(Tset) == 1:
                            yv = Fraction(1)
                        elif any(P.adjacent(a, b) for a, b in itertools.combinations(Tset, 2)):
                            yv = Fraction(0)
                        else:
                            kk = P.key(Tset)
                            if kk not in cache:
                                cache[kk] = y_definitional(P, S, (0,) + kk)
                            yv = cache[kk]
                        val += c * yv
                    if val != D.get((u, w), 0):
                        mism += 1
        return mism

    for trial in range(3):
        S = random_maximal_set(P, rng)
        mm = expansion_matches(S)
        log(f"  |S| = {len(S)}: {len(anchor_list)} anchored matrices x 49^2 entries, keyed expansion vs the definitional "
            f"G0-average: {mm} mismatches")
        if mm:
            failures.append(f"expansion mismatches at a genuine set of size {len(S)}: {mm}")
        if trial == 0:
            for plant in ("sign", "untranslated"):
                pm = expansion_matches(S, plant)
                log(f"  plant '{plant}' (the expansion {'with every sign +' if plant == 'sign' else 'looking {a,u,w} up as {0,u,w}'}): "
                    f"{pm} mismatches {'(RED as designed)' if pm else '(NOT OK: the comparison is blind)'}")
                if not pm:
                    failures.append(f"plant {plant} was not detected")

    log("=== 4. certificates at q = 7: faithful ones pass, planted ones are refused ===")
    good = synthetic_certificate(7)
    dense = synthetic_certificate(7, dense=True)
    green("a synthetic Gram-form certificate", lambda: check(good, out=quiet))
    green("the same with dense blocks (the exact LDL path)", lambda: check(dense, out=quiet))

    def mutated(c, f):
        c2 = json.loads(json.dumps(c))
        f(c2)
        return c2

    def flip_sign(c):
        m = c["multipliers"]
        i = next(i for i, x in enumerate(m["lower"]) if x)
        m["lower"][i] = -m["lower"][i]

    red("(a) a flipped multiplier sign", lambda: check(mutated(good, flip_sign), out=quiet), "is negative")

    def indefinite(c):
        blk = c["matrices"][0]["blocks"][0]["Z"]
        blk["num"][0][1] += 50
        blk["num"][1][0] += 50

    red("(b) a dense block perturbed to be indefinite", lambda: check(mutated(dense, indefinite), out=quiet),
        "NOT positive semidefinite")

    def gram_perturb(c):
        c["matrices"][0]["blocks"][0]["gram"]["num"][0][0] += 1

    red("(b') a Gram entry perturbed (PSD by construction, so the IDENTITY must refuse it)",
        lambda: check(mutated(good, gram_perturb), out=quiet), "identity")

    def smaller_N(c):
        N = Fraction(c["N"]) - Fraction(1, 10 ** 6)
        c["N"] = f"{N.numerator}/{N.denominator}"

    red("(d) a claimed N smaller than the identity allows", lambda: check(mutated(good, smaller_N), out=quiet),
        "constant term")
    red("a float where a rational belongs", lambda: check(mutated(good, lambda c: c.__setitem__("N", 3.5)), out=quiet),
        "float")
    red("a certificate filed against q = 11", lambda: check(mutated(good, lambda c: c.update(q=11, p=11)), out=quiet),
        "edges_sha256")

    def drop_var(c):
        i = len(c["variables"]) // 2
        del c["variables"][i]
        del c["multipliers"]["lower"][i]
        del c["multipliers"]["upper"][i]

    red("a variable missing from the file's list", lambda: check(mutated(good, drop_var), out=quiet), "not in the file")
    red("the wrong kind", lambda: check(mutated(good, lambda c: c.__setitem__("kind", "fs54-d4")), out=quiet), "kind")
    green("the faithful certificate again, after the mutations", lambda: check(good, out=quiet))

    log("=== 5. the identity at genuine independent sets, exactly (q = 7) ===")
    P7 = Plane(F7)
    rng = random.Random(3)
    for _ in range(3):
        S = random_maximal_set(P7, rng)
        if not against(good, S, out=quiet):
            failures.append(f"the identity at a genuine set of size {len(S)} did not hold term by term")
            log(f"  NOT OK  |S| = {len(S)}")
        else:
            log(f"  GREEN (as designed) |S| = {len(S)}: objective = |S|, every term >= 0, N - |S| = their sum")
    S = random_maximal_set(P7, rng)
    if against(good, S, out=quiet, plant_no_stabiliser=True):
        failures.append("counting each subset once (no stabiliser weight) left the objective at |S|: the evaluation is blind")
        log("  GREEN -- NOT OK     plant: subsets counted without their stabiliser weight")
    else:
        log("  RED (as designed)   plant: subsets counted without their stabiliser weight -- the objective is no longer |S|")
    red("a set that is not independent", lambda: against(good, [0, 1] + S, out=quiet), "not independent")
    log("=== verdict ===")
    if failures:
        for f in failures:
            log(f"  FAILURE: {f}")
        log(f"SELF-TEST FAILED ({len(failures)})")
        return False
    log("SELF-TEST PASSED: every faithful case accepted, every plant refused for its own reason")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("certificate", nargs="?")
    ap.add_argument("--k", type=int, help="also say whether floor(N) refutes a k-colouring")
    ap.add_argument("--jobs", type=int, default=1, help="forked worker processes for the per-anchor work")
    ap.add_argument("--ldl", action="store_true", help="also run exact LDL^T on Gram blocks (redundant, slow)")
    ap.add_argument("--against", metavar="SETFILE", help="also evaluate (*) at a verified independent set")
    ap.add_argument("--set-path", default="set", help="where the set sits in SETFILE (dotted path)")
    ap.add_argument("--expansion-check", metavar="SETFILE",
                    help="instead of checking: sample entries of every matrix and compare the keyed expansion at the set's "
                         "definitional averaged counts with the entry's definition (with a sign plant that must fire)")
    ap.add_argument("--samples", type=int, default=20)
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return 0 if self_test() else 1
    if not a.certificate:
        ap.error("give a certificate file, or --self-test")
    print(f"[cert] file: {a.certificate}", flush=True)
    raw = Path(a.certificate).read_bytes()
    print(f"[cert] sha256 {hashlib.sha256(raw).hexdigest()}", flush=True)
    try:
        cert = json.loads(raw)
    except json.JSONDecodeError as e:
        print(f"NOT A CERTIFICATE: not valid JSON ({e})")
        return 1
    if not isinstance(cert, dict):
        print("NOT A CERTIFICATE: the top level is not an object")
        return 1
    print(f"[cert] kind {cert.get('kind')!r}, q = {cert.get('q')}, modulus {cert.get('modulus')!r}, "
          f"N = {str(cert.get('N'))[:60]}..., alpha_bound = {cert.get('alpha_bound')}; derivation "
          f"{cert.get('derivation')}", flush=True)
    if a.expansion_check:
        rec = json.loads(Path(a.expansion_check).read_text())
        S = rec
        for part in a.set_path.split("."):
            S = S[int(part)] if isinstance(S, list) else S[part]
        S = [int(x) for x in S]
        mm, ch, nz = expansion_check(cert, S, a.samples)
        pm, _, _ = expansion_check(cert, S, max(3, a.samples // 4), plant="sign")
        print(f"[expansion] faithful: {mm} mismatches of {ch} -> {'PASS' if mm == 0 else 'FAIL'}; plant: {pm} mismatches -> "
              f"{'FIRED (as designed)' if pm else 'DID NOT FIRE (the comparison is blind)'}")
        return 0 if (mm == 0 and pm > 0) else 1
    try:
        check(cert, k=a.k, jobs=a.jobs, force_ldl=a.ldl)
    except Refusal as e:
        print(f"NOT A CERTIFICATE: {e}")
        return 1
    if a.against:
        rec = json.loads(Path(a.against).read_text())
        S = rec
        for part in a.set_path.split("."):
            S = S[int(part)] if isinstance(S, list) else S[part]
        try:
            ok = against(cert, [int(x) for x in S], jobs=a.jobs)
        except Refusal as e:
            print(f"[against] the set was refused: {e}")
            return 2
        return 0 if ok else 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
