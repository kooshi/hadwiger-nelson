_LAT_CACHE = {}


def fabric_lattice(spec, saturate=True):
    """CACHED.  Sound to cache across this file's plants because every plant here lives inside
    PeriodicColouring/component and none touches the lattice; fs70_fabric's own plants have disjoint names and
    are parsed at ITS import, before any call here."""
    key = (spec, saturate)
    if key not in _LAT_CACHE:
        _LAT_CACHE[key] = _fabric_lattice_uncached(spec, saturate)
    return _LAT_CACHE[key]


def _fabric_lattice_uncached(spec, saturate=True):
    lat = FB.Lattice(FB.generators(spec), spec)
    if saturate:
        lat.saturate('b')
        U = [tuple(lat.coords(z)) for z in lat.units]
        sat = True
    else:
        U = [tuple(FB.coords_in_basis(lat.H, lat.vec8(z))) for z in lat.S]
        sat = False
    assert all(u is not None for u in U), 'a unit vector is outside the lattice'
    return lat, U, sat


def fabric_target(lat, name):
    z = FB.target_element(name)
    c = lat.coords(z)
