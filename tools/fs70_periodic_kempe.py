def selftest(plants=False):
    fails = []

    def check(name, ok, detail=''):
        print(f'  [{"ok " if ok else "FAIL"}] {name}  {detail}')
        if not ok:
            fails.append(name)

    print('fs70_periodic_kempe self-test')

    # -- 0. the algebra: hnf_insert / member / det_of on a known lattice
    B = _echelon([[2, 0], [0, 3]], 2)
    check('member/det on 2Z x 3Z', member(B, [4, 6], 2) and not member(B, [1, 0], 2) and det_of(B, 2) == 6)

    # -- 1. a hand case: the triangular lattice, N = 3, the additive 3-colouring is not 4-valued, so use N = 2
    lat, U = _toy()
    n, edges, _ = quotient_edges(U, 2, 2)
    cls = _cnf(n, edges, [1], [])
    v, secs, model, _ = solve_cnf(cls, 4 * n, 60)
    check('triangular lattice, N = 2: the quotient four-colours', v == 'SAT', f'{n} classes, {v}')
    if v == 'SAT':
        pc = PeriodicColouring(U, 2, 2, model, label='zeta6')
        check('  and its proper-ness assertion passed', pc.monochromatic == 0)

    # -- 1b. the independent-rebuild control: this file's quotient must reproduce fs70_quotient.py's committed
    #    row.  It is what caught the class-index convention (big- vs little-endian), which is otherwise silent.
    latL1, UL1, _ = fabric_lattice('group6:u3:2')
    colL1, _m = load_colouring(os.path.join(ROOT, 'data', 'fs70', 'quotient',
                                            'group6_u3_2-N5.colouring.json'))
    try:
        pcL1 = PeriodicColouring(UL1, 5, latL1.rank, colL1, label='L1-N5')
        gapsL1 = pcL1.gapped_vertices()
        ok = (pcL1.monochromatic == 0 and len(gapsL1) == 50)     # phase 1d's committed number for L1 at N = 5
        check('independent rebuild: L1 at N = 5 is proper and has 50 gapped vertices (phase 1d\'s row)',
              ok, f'{pcL1.monochromatic} monochromatic, {len(gapsL1)} gapped')
    except AssertionError as e:
        pcL1, gapsL1 = None, []
        check('independent rebuild: L1 at N = 5 is proper', False, str(e)[:70])

    # -- 2. control (ii) (the brief's): L1's gapped N = 5 colouring must read ESCAPE at every target, for
    #    b = the gap colour, because a gap makes K0 = {0}.  Asserted on a population that must be NONEMPTY.
    if pcL1 is not None and gapsL1:
        tr = translate(pcL1, gapsL1[0])
        gcol = tr.gap_at(0)[0]
        p, V, edg, qi = tr.component(int(tr.colv[0]), gcol)
        check('control (ii): a gap at the origin gives the trivial component K0 = {0}',
              len(p) == 1, f'|Q0| = {len(p)}')
        # the sharp form: EVERY nonzero class of the origin's own colour must escape at LEVEL 1 by the gap
        # colour.  A level-0 escape would prove nothing about the Kempe machinery, so level 1 is asserted.
        lvl1 = [j for j in range(tr.n) if j and tr.colv[j] == tr.colv[0]]
        outs = []
        for j in lvl1[:120]:
            dd = class_digits(j, tr.N, tr.rank)     # the digit vector is a lattice point of that class
            r = tr.screen(dd, f'class{j}')
            # the GAP colour must be one of the escaping b's (several b's may escape; `escape_colour` reports
            # only the first, so asserting on it would be asserting on an ordering, not on the theorem)
            outs.append((r['level'], r['verdict'], not r['per_b'][gcol]['delta_in_K0']))
        check('control (ii): under a gap at the origin every same-coloured class escapes at level 1, and the '
              'gap colour is one of the escaping b', bool(outs) and all(o == (1, 'escape', True) for o in outs),
              f'{len(outs)} classes (of {len(lvl1)}), readings {sorted(set(outs))}')

    # -- 3. control (iii) in miniature: an additive colouring's screen equals the closed form
    lat4, U4, _ = fabric_lattice('zeta12+u3')
    rank4 = lat4.rank
    ok_all = True
    tried = 0
    for phi in itertools.product(range(4), repeat=rank4):
        vals = [sum(c * p for c, p in zip(u, phi)) % 4 for u in U4]
        if any(x == 0 for x in vals):
            continue
        tried += 1
        if tried > 6:
            break
        col = [sum(c * p for c, p in zip(class_digits(i, 4, rank4), phi)) % 4
               for i in range(4 ** rank4)]
        pc4 = PeriodicColouring(U4, 4, rank4, col, label='zeta12+u3')
        for t in ('4/3', '8/3', '4', '2'):
            d = fabric_target(lat4, t)
            if d is None:
                continue
            r = pc4.screen(d, t)
            if r['verdict'] != _additive_reach_verdict(U4, rank4, phi, d, 'zk'):
                ok_all = False
    check('control (iii) miniature: the periodic screen = the additive closed form on zeta12+u3',
          ok_all and tried > 0, f'{min(tried,6)} colourings x 4 targets')

    if plants:
        print(f'  -- plants on the bed {BED_SPEC} at N = {BED_N}, targets {BED_TARGETS} '
              '(each must move the reading)')
        base = _plant_bed()
        print(f'     unplanted: {base}')
        lvl = {r[2] for r in base if len(r) > 2}
        check('the bed reaches level 1 (so the plants have something to break)', lvl == {1}, f'levels {lvl}')
        for nm in VALID_PLANTS:
            got = _plant_bed(nm)
            check(f'plant {nm} fires', got != base, f'-> {got}')

    print(('SELF-TEST PASSED' if not fails else 'SELF-TEST FAILED: ' + ', '.join(fails)))
    return 1 if fails else 0


BED_SPEC, BED_N, BED_TARGETS = 'group6:u3:2+zeta6:w4', 4, ('4/3', '8/3', '4')


def _plant_bed(plant=None):
    """One fixed (lattice, N, colouring, targets) whose reading the plants must move.

    L3 at N = 4: gap-free (phase 1d), so the component is large and `V` carries the whole verdict -- which is
    exactly what the plants attack.  A gapped bed would be useless: there `K0 = {0}` whatever the voltages are,
    so `voltage_off` and `dedup_steps` could not fire (CLAUDE.md: a plant whose failure mode is unreachable has
    not been tested by passing)."""
    global PLANT
    old = PLANT
    PLANT = plant
    try:
        lat, U, _ = fabric_lattice(BED_SPEC)
        tag = BED_SPEC.replace(':', '_').replace('+', '_')
        col, _m = load_colouring(os.path.join(ROOT, 'data', 'fs70', 'quotient',
                                              f'{tag}-N{BED_N}.colouring.json'))
        try:
            pc = PeriodicColouring(U, BED_N, lat.rank, col, label='bed')
        except (AssertionError, InvariantError) as e:
            return (('RAISED', type(e).__name__, str(e)[:60]),)
        out = []
        for t in BED_TARGETS:
            d = fabric_target(lat, t)
            if d is None:
                out.append((t, 'absent'))
                continue
            try:
                r = pc.screen(d, t)
            except (AssertionError, InvariantError) as e:
                out.append((t, 'RAISED', type(e).__name__, str(e)[:60]))
                continue
            out.append((t, r['verdict'], r['level'],
                        tuple(sorted((b, v['V_index_in_NLambda'], v['component_classes'],
                                      v['delta_class_in_Q0'], v['delta_in_K0'])
                                     for b, v in r.get('per_b', {}).items()))))
        return tuple(out)
    finally:
        PLANT = old


def main():
    argv = sys.argv[1:]
    if PLANT is not None and PLANT not in VALID_PLANTS:
        raise SystemExit(f'unknown plant {PLANT!r}; known: {", ".join(VALID_PLANTS)}')
    if not argv:
        print(__doc__)
        return 0
    cmd = argv[0]
    if cmd == 'selftest':
        return selftest('--plants' in argv)
    if cmd == 'screen':
        cmd_screen(argv)
        return 0
    if cmd == 'verify-escape':
        rows = cmd_verify_escape(argv)
        return 0 if all(r.get('verified', True) for r in rows) else 1
    if cmd == 'screen-additive':
        a, d = cmd_screen_additive(argv)
        return 1 if d else 0
    if cmd == 'find':
        cmd_find(argv)
        return 0
    if cmd == 'degrey':
        rows, bad = cmd_degrey(argv)
        return 1 if bad else 0
    print(__doc__)
    return 0


if __name__ == '__main__':
    sys.exit(main())
