#!/usr/bin/env python3
"""fs70_periodic_kempe -- the Kempe screen for PERIODIC four-colourings, and the two finders that aim at one.
UNTRUSTED (tools/).

WHY.  Phase 1d's fan-gap screen (row 56 + row 66) closes `Forces` on a whole lattice from ONE gapped periodic
four-colouring.  It is the degenerate case of a general instrument, and that is what this file is.  The question
the milestone actually asks on a lattice that four-colours is not *can it be coloured* but *is the colouring space
RIGID at the target* -- and rigidity is decidable on the quotient, before any ball is built.

THE THEOREM (elementary; the only kernel input is row 56's homomorphism).  Let `Lambda` have unit-vector set `U`
(`-U = U`), let `N` be admissible (no `u` in `U` lies in `N*Lambda`), and let `c` be a proper four-colouring of
`Cay(Lambda/N Lambda, U mod N)`.  Its pull-back `C(x) = c(x mod N)` is a proper four-colouring of the whole
unit-distance graph on `Lambda` (row 56).  Fix `delta` in `Lambda` with `C(delta) = C(0) = a`, and `b != a`.

  * `Q` := the two-colour subgraph of the quotient: the classes with `c` in `{a, b}`, with ONE EDGE PER PAIR
    `(ybar, s)` for `s` in `U` with `c(ybar + sbar)` in `{a, b}`, carrying the VOLTAGE `s` in `Z^rank`.  Two unit
    vectors with the same residue are TWO EDGES -- dropping that is the plant `dedup_steps`, and it is the single
    easiest way to get this wrong.
  * `Q0` := the component of `0bar`; `p(xbar)` := the voltage of a spanning-tree walk `0bar -> xbar` (an actual
    lattice point of the class `xbar`); `V` := the Z-span of the closed-walk voltages, generated by the
    fundamental cycles `p(ybar) + s - p(ybar + sbar)`, one per edge (tree edges give 0).

  Then the `(a, b)`-Kempe component of the origin in the INFINITE lattice graph meets the class `xbar` in exactly
  `p(xbar) + V`, so

        delta in K0   <=>   deltabar in Q0  AND  delta - p(deltabar) in V.

  `V` is contained in `N*Lambda` always (a closed walk's steps sum to `0` mod `N`), so `V = N*Lambda` is the top
  and there the test collapses to `deltabar in Q0`.  The index `[N*Lambda : V]` is reported in every row: it is
  the quantity that decides, and it is what an escape needs to be large.

  ESCAPE (`delta not in K0` for some `b`): swapping `a <-> b` on `K0` is again a proper four-colouring of every
  graph on `Lambda` -- inside `K0` an edge keeps two distinct colours, and an edge out of `K0` has its far end
  coloured outside `{a, b}` -- and it gives `0` and `delta` different colours.  So NO graph on `Lambda` forces the
  pair, at any radius, and by translation no pair at difference `delta` is forced.  `Forces` at `delta` is dead.
  RIGID (`delta in K0` for every `b`, over every colouring tried): nothing is proved; the target is worth a solver.

  LEVEL 0.  If `c(deltabar) != c(0bar)` the periodic colouring ALREADY separates the pair and the target is dead
  with no Kempe argument at all.  That is the cheapest kill in the milestone and it is what the `sep` finder aims
  at.

  THE DEGENERATE CASE.  If `c` has a fan gap at the origin with gap colour `b` -- `b` absent from `{c(0bar)} u
  c(N(0bar))` -- then `Q0 = {0bar}`, `K0 = {0}`, and every `delta != 0` escapes.  That is phase 1d's screen, and
  this file must reproduce it (control (ii)).

  THE ADDITIVE CASE.  A proper additive `phi: Lambda -> Z/4` is a periodic colouring of period 4, and there
  `K0 = span{z + w : phi(z) = b, phi(w) = -b}` -- the phase-1 additive Kempe screen.  This file must agree with it
  at every target (control (iii)).

GENERATORS, NOT SATURATION.  On a lattice whose complete unit-vector set is unaffordable (the rich 2-unit
lattices, denominator 16,380 and beyond) `U` is the GENERATOR set.  Then the quotient colouring is proper only for
graphs whose edges are differences in `U`, and so is the swap: every ESCAPE is sound for U-fabric only.  A RIGID
verdict proves nothing either way and is a decision about where to spend a solver.  Every row carries
`saturated: true|false`.

THE FINDERS.  A screen that waits for whatever colouring a solver happens to return measures the solver
(phase 1d's own §8 item 2: L6 is gapped at N = 5 and gap-free at N = 8, so an UNSAT or a gap-free SAT at one N
proves nothing).  Both finders add clauses and ask for the colouring that would settle it:
  aim `gap`      colour 3 absent from the closed neighbourhood of the origin.  WLOG: translate the gapped vertex
                 to the origin, permute the gap colour to 3 and the origin's to 0.  Then colours 1, 2 are still
                 interchangeable, so the least neighbour of the origin is pinned to 1 (its colour is in {1, 2}).
  aim `sep:D`    `c(Dbar) != c(0bar)`, with the origin pinned to 0, so one unit clause `not x[Dbar][0]`.  Colours
                 1, 2, 3 are still interchangeable, so the least neighbour of the origin is pinned to 1 and a
                 precedence clause breaks 2 against 3.  Needs `D` outside `N*Lambda`.
An UNSAT from either says only that no N-periodic colouring of that shape exists (G21).

Commands
  fs70_periodic_kempe.py screen SPEC --N n [--colouring F] [--targets a,b,..] [--out F] [--note T]
  fs70_periodic_kempe.py screen-additive SPEC [--group zk|k4] [--targets ...] [--out F]
  fs70_periodic_kempe.py find SPEC --aim gap|sep --targets ... [--nmin 2] [--nmax 12] [--budget 600] [--out F]
  fs70_periodic_kempe.py degrey --nmax 12 [--out F]          # control (i): de Grey's K-lattice at 8/3
  fs70_periodic_kempe.py selftest [--plants]
Plants (--plant NAME): dedup_steps, voltage_off, p_zero, component_all, tree_only.
"""
