def cmd_verify_escape(argv):
    """The reviewer's check of an ESCAPE, using NONE of the voltage machinery.

    An escape claims: swapping `a <-> b` on the Kempe component of the origin gives a proper four-colouring of
    every graph on the lattice that separates `(0, delta)`.  On a concrete word ball that claim is checkable
    outright and the voltages never enter: BFS the two-colour component of the origin INSIDE the ball, swap it,
    and verify on the ball's own edge list.

    Sound on the ball by itself: if `x` is in the ball component and `y = x + s` lies in the ball with a colour
    in `{a, b}`, then `y` is adjacent to `x` in the ball, so `y` is in the ball component too.  Hence every edge
    leaving the swapped set has its far end coloured outside `{a, b}`, and the swap is proper on the ball.  So
    this exhibits a proper four-colouring of a real finite unit-distance graph over the field, containing `0`
    and `delta`, that gives them different colours -- `Forces` refuted on that graph, with no theorem cited."""
    spec = argv[1]
    N = _opt(argv, '--N', None, int)
    k = _opt(argv, '--k', 3, int)
    tgts = (_opt(argv, '--targets', '4/3,8/3,4')).split(',')
    colf = _opt(argv, '--colouring')
    out = _opt(argv, '--out')
    sat = '--generators' not in argv
    lat, U, saturated = fabric_lattice(spec, saturate=sat)
    if colf is None:
        tag = spec.replace(':', '_').replace('+', '_')
        colf = os.path.join(ROOT, 'data', 'fs70', 'quotient', f'{tag}-N{N}.colouring.json')
    col, _m = load_colouring(colf)
    pc = PeriodicColouring(U, N, lat.rank, col, label=spec, saturated=saturated)

    steps = [lat.vec8(z) for z in (lat.units if saturated else lat.S)]
    pts = FB.word_ball(lat, k, steps=steps)
    idx = {p: i for i, p in enumerate(pts)}
    edges = []
    for i, p8 in enumerate(pts):
        for s in steps:
            q = tuple(a + b for a, b in zip(p8, s))
            j = idx.get(q)
            if j is not None and i < j:
                edges.append((i, j))
    # the pull-back colour of each ball point
    cof = []
    for p8 in pts:
        c = lat.coords(FB.e_from_ints(FB.ints_reduce(p8, lat.M))) if False else FB.coords_in_basis(lat.H, p8)
        cof.append(pc.col[pc._ix(tuple(x % N for x in c))])
    zero = tuple([0] * 8)
    o = idx[zero]
    print(f'{spec}: word ball at sums of <= {k}: {len(pts)} points, {len(edges)} edges, '
          f'average degree {2*len(edges)/len(pts):.2f}')
    bad = sum(1 for i, j in edges if cof[i] == cof[j])
    print(f'  the pulled-back periodic colouring is proper on the ball: {bad} monochromatic edges '
          f'({"PASS" if bad == 0 else "FAIL"})')
    adj = [[] for _ in pts]
    for i, j in edges:
        adj[i].append(j)
        adj[j].append(i)
    rows = []
    for t in tgts:
        d = fabric_target(lat, t)
        if d is None:
            continue
        d8 = lat.vec8(FB.target_element(t))
        di = idx.get(tuple(d8))
        r = pc.screen(d, t)
        row = {'spec': spec, 'N': N, 'target': t, 'k': k, 'ball_points': len(pts), 'ball_edges': len(edges),
               'screen_verdict': r['verdict'], 'delta_in_ball': di is not None}
        if di is None:
            print(f'  {t:6s}: not in the ball at k = {k}; screen says {r["verdict"]}')
            rows.append(row)
            continue
        if r['verdict'] != 'escape':
            print(f'  {t:6s}: screen says {r["verdict"]}; nothing to verify')
            rows.append(row)
            continue
        a = int(cof[o])
        okany = False
        for b in range(4):
            if b == a or (r['level'] == 1 and r['per_b'][b]['delta_in_K0']):
                continue
            comp = {o}
            stack = [o]
            while stack:
                x = stack.pop()
                for y in adj[x]:
                    if y not in comp and cof[y] in (a, b):
                        comp.add(y)
                        stack.append(y)
            sw = list(cof)
            for x in comp:
                sw[x] = b if sw[x] == a else a
            mono = sum(1 for i, j in edges if sw[i] == sw[j])
            sep = sw[o] != sw[di]
            okany = okany or (mono == 0 and sep)
            row[f'b{b}'] = {'component_ball': len(comp), 'monochromatic_after_swap': mono,
                            'separates': bool(sep), 'colour_0': int(sw[o]), 'colour_delta': int(sw[di])}
            print(f'  {t:6s} b={b}: ball component {len(comp):6d}, after the swap {mono} monochromatic edges, '
                  f'c(0) = {sw[o]}, c(delta) = {sw[di]}  -> {"VERIFIED" if mono == 0 and sep else "NO"}')
        row['verified'] = okany
        if r['level'] == 0:
            row['verified'] = bool(cof[o] != cof[di])
            print(f'  {t:6s}: level-0 escape -- the periodic colouring itself gives '
                  f'c(0) = {cof[o]}, c(delta) = {cof[di]}  -> '
                  f'{"VERIFIED" if row["verified"] else "NO"}')
        rows.append(row)
    if out:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        json.dump(rows, open(out, 'w'), indent=1)
        print('wrote ' + out)
    return rows


def cmd_screen_additive(argv):
    """control (iii): every proper additive colouring as a periodic one, against the closed-form reach."""
    spec = argv[1]
    group = _opt(argv, '--group', 'zk')
    tgts = (_opt(argv, '--targets', '4/3,8/3,4')).split(',')
    out = _opt(argv, '--out')
    lat, U, saturated = fabric_lattice(spec)
    rank = lat.rank
    N = 4 if group == 'zk' else 2
    print(f'{spec}: additive {"Z/4" if group == "zk" else "Klein"} colourings as period-{N} quotient colourings')
    phis = []
    for phi in itertools.product(range(4), repeat=rank):
        if group == 'zk':
            vals = [sum(c * p for c, p in zip(u, phi)) % 4 for u in U]
        else:
            vals = [_k4(u, phi) for u in U]
        if all(v != 0 for v in vals):
            phis.append(phi)
    print(f'  {len(phis)} proper')
    pw = powers(N, rank)
    rows = []
    agree = disagree = 0
    for phi in phis:
        col = [(sum(c * p for c, p in zip(class_digits(i, N, rank), phi)) % 4 if group == 'zk'
                else _k4(class_digits(i, N, rank), phi)) for i in range(N ** rank)]
        pc = PeriodicColouring(U, N, rank, col, label=f'{spec}|phi={phi}')
        for t in tgts:
            d = fabric_target(lat, t)
            if d is None:
                continue
            r = pc.screen(d, t)
            closed = _additive_reach_verdict(U, rank, phi, d, group)
            r['closed_form'] = closed
            ok = (r['verdict'] == closed)
            agree += ok
            disagree += (not ok)
            if not ok:
                print(f'  DISAGREEMENT phi={phi} target={t}: screen {r["verdict"]}, closed form {closed}')
            rows.append(r)
    print(f'  agreement: {agree} of {agree + disagree} (lattice, phi, target) rows')
    if out:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        json.dump({'spec': spec, 'group': group, 'agree': agree, 'disagree': disagree,
                   'rows': rows[:400]}, open(out, 'w'), indent=1)
        print('wrote ' + out)
    return agree, disagree


def _k4(u, phi):
    """phi as a map to the Klein group: two bits, each a mod-2 linear form (phi_i in {0,1,2,3} = two bits)"""
    b0 = sum(c * (p & 1) for c, p in zip(u, phi)) % 2
    b1 = sum(c * ((p >> 1) & 1) for c, p in zip(u, phi)) % 2
    return b0 + 2 * b1


def _additive_reach_verdict(U, rank, phi, delta, group):
    if group == 'zk':
        vals = [sum(c * p for c, p in zip(u, phi)) % 4 for u in U]
        dv = sum(c * p for c, p in zip(delta, phi)) % 4
    else:
        vals = [_k4(u, phi) for u in U]
        dv = _k4(delta, phi)
    if dv != 0:
        return 'escape'
    for b in range(1, 4):
        nb = (-b) % 4 if group == 'zk' else b
        Z = [u for u, v in zip(U, vals) if v == b]
        W = [u for u, v in zip(U, vals) if v == nb]
        if not Z or not W:
            return 'escape'
        gens = [[x + y for x, y in zip(z, w)] for z in Z for w in W]
        B = _echelon([list(g) for g in gens], rank)
        if not member(B, list(delta), rank):
            return 'escape'
    return 'rigid'


def cmd_find(argv):
    spec = argv[1]
    aim = _opt(argv, '--aim', 'gap')
    tgts = (_opt(argv, '--targets', '4/3,8/3,4')).split(',')
    nmin = _opt(argv, '--nmin', 2, int)
    nmax = _opt(argv, '--nmax', 12, int)
    budget = _opt(argv, '--budget', 600, int)
    out = _opt(argv, '--out')
    cap = _opt(argv, '--cap', 400000, int)
    sat = '--generators' not in argv
    lat, U, saturated = fabric_lattice(spec, saturate=sat)
    rank = lat.rank
    print(f'{spec}: rank {rank}, g = {len(U)}, aim = {aim}, N = {nmin}..{nmax}, budget {budget} s each')
    rows = []
    for N in range(nmin, nmax + 1):
        if any(all(x % N == 0 for x in s) for s in U):
            print(f'  N = {N:2d}: not admissible')
            rows.append({'N': N, 'admissible': False})
            continue
        if N ** rank > cap:
            print(f'  N = {N:2d}: {N**rank} classes -- over the cap')
            rows.append({'N': N, 'admissible': True, 'verdict': 'not asked', 'classes': N ** rank})
            continue
        if aim == 'gap':
            v, secs, model, sha, note = find(U, N, rank, 'gap', budget=budget)
            row = {'N': N, 'admissible': True, 'classes': N ** rank, 'aim': 'gap', 'verdict': v,
                   'seconds': round(secs, 2), 'cnf_sha256': sha, 'note': note}
            print(f'  N = {N:2d}: {N**rank:7d} classes, gap-aimed -> {v} in {secs:.1f} s')
            if v == 'SAT':
                _commit_colouring(spec, N, model, U, rank, tag_extra='gapaimed')
            rows.append(row)
        else:
            for t in tgts:
                d = fabric_target(lat, t)
                if d is None:
                    continue
                v, secs, model, sha, note = find(U, N, rank, 'sep', delta=d, budget=budget)
                row = {'N': N, 'admissible': True, 'classes': N ** rank, 'aim': f'sep:{t}', 'verdict': v,
                       'seconds': round(secs, 2), 'cnf_sha256': sha, 'note': note}
                print(f'  N = {N:2d} {t:8s}: {N**rank:7d} classes, sep-aimed -> {v} in {secs:.1f} s'
                      + ('   **TARGET DEAD ON THIS LATTICE**' if v == 'SAT' else ''))
                if v == 'SAT':
                    _commit_colouring(spec, N, model, U, rank, tag_extra='sep-' + t.replace('/', 'over'))
                rows.append(row)
    if out:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        json.dump({'spec': spec, 'aim': aim, 'rank': rank, 'g': len(U), 'saturated': saturated,
                   'rows': rows}, open(out, 'w'), indent=1)
        print('wrote ' + out)
    return rows


