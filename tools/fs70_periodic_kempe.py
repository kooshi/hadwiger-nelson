# ---------------------------------------------------------------- integer lattice bookkeeping

def hnf_insert(basis, v, dim):
    """Insert v into a row-echelon (Hermite) basis in place-ish; returns (basis, changed)."""
    v = list(v)
    for row in basis:
        p = next(j for j in range(dim) if row[j])
        if v[p]:
            if v[p] % row[p] == 0:
                q = v[p] // row[p]
                for j in range(dim):
                    v[j] -= q * row[j]
            else:
                break
    if not any(v):
        return basis, False
    out = [r[:] for r in basis] + [v]
    # re-echelonise
    return _echelon(out, dim), True


def _echelon(rows, dim):
    work = [r[:] for r in rows if any(r)]
    basis = []
    for col in range(dim):
        while True:
            nz = [i for i in range(len(work)) if work[i][col]]
            if not nz:
                break
            i0 = min(nz, key=lambda i: abs(work[i][col]))
            p = work[i0][col]
            done = True
            for i in nz:
                if i != i0:
                    q = work[i][col] // p
                    work[i] = [a - q * b for a, b in zip(work[i], work[i0])]
                    if work[i][col]:
                        done = False
            if done:
                if p < 0:
                    work[i0] = [-x for x in work[i0]]
                basis.append(work[i0])
                work = [work[i] for i in range(len(work)) if i != i0]
                break
    return basis


def member(basis, v, dim):
    v = list(v)
    for row in basis:
        p = next(j for j in range(dim) if row[j])
        if v[p] % row[p]:
            return False
        q = v[p] // row[p]
        if q:
            for j in range(dim):
                v[j] -= q * row[j]
    return not any(v)


def powers(N, rank):
    """The class index convention, and it MUST be the one the committed colourings use.

    `fs70_quotient.py` indexes by `itertools.product(range(N), repeat=rank)`, which varies the LAST coordinate
    fastest -- big-endian.  Getting this wrong is silent everywhere except the properness assertion, which is
    why that assertion is not optional: with the little-endian convention the committed L3 colouring at N = 4
    read 117,760 monochromatic incidences."""
    return [N ** (rank - 1 - i) for i in range(rank)]


def class_digits(i, N, rank):
    """the coordinate digits of class index i, in the big-endian convention of `powers`"""
    return tuple((i // p) % N for p in powers(N, rank))


def det_of(basis, dim):
    """the index of the span in Z^dim, or 0 (meaning infinite) if the rank is deficient"""
    if len(basis) < dim:
        return 0
    d = 1
    for row in basis:
        p = next(j for j in range(dim) if row[j])
        d *= abs(row[p])
    return d


class InvariantError(Exception):
    """A structural invariant of the voltage construction failed -- a defect, never a finding."""


def index_in_top(det, top):
    """[N*Lambda : V], given [Z^r : V] = det and [Z^r : N*Lambda] = top = N^r.

    V is always inside N*Lambda (a closed walk's steps sum to 0 mod N), so det is a multiple of top and
    [N*Lambda : V] = det // top.  det = 0 means V has deficient rank, so the index is infinite.
    The plant `voltage_off` trips this, which is how it announces itself."""
    if det == 0:
        return None
    if det % top:
        raise InvariantError(f'V is not inside N*Lambda: [Z^r:V] = {det}, N^r = {top}')
    return det // top


# ---------------------------------------------------------------- the quotient with voltages

class PeriodicColouring:
    """A lattice, an admissible N, a proper four-colouring of Cay(Lambda/N Lambda, U mod N), and the Kempe screen."""

    def __init__(self, U, N, rank, col, label='', saturated=True):
        self.U = [tuple(s) for s in U]          # unit vectors in HNF coordinates, the FULL list (no dedup)
        self.N = N
        self.rank = rank
        self.col = col                          # list of length N**rank, indexed by the mixed-radix class index
        self.label = label
        self.saturated = saturated
        self.n = N ** rank
        assert len(col) == self.n, (len(col), self.n)
        self.pw = powers(N, rank)                # class index: big-endian, as fs70_quotient.py writes them
        self.Umod = [tuple(x % N for x in s) for s in self.U]
        assert all(any(x for x in s) for s in self.Umod), 'N is not admissible: a unit vector lies in N*Lambda'
        if planted('dedup_steps'):
            seen, keepU = set(), []
            for s in self.U:                        # PLANT: parallel edges lost
                r = tuple(x % N for x in s)
                if r not in seen:
                    seen.add(r)
                    keepU.append(s)
            self.U = keepU
            self.Umod = [tuple(x % N for x in s) for s in self.U]
        # add[k][i] = the class index of (class i) + (U[k] mod N); one int32 table per step
        digits = [(np.arange(self.n, dtype=np.int64) // p) % N for p in self.pw]
        self.add = []
        for s in self.Umod:
            tot = np.zeros(self.n, dtype=np.int64)
            for p in range(rank):
                tot += ((digits[p] + s[p]) % N) * self.pw[p]
            self.add.append(tot.astype(np.int32))
        self.colv = np.asarray(col, dtype=np.int8)
        self._check_proper()

    def _ix(self, cls):
        return sum(c * p for c, p in zip(cls, self.pw))

    def _check_proper(self):
        bad = 0
        for t in self.add:
            bad += int(np.count_nonzero(self.colv[t] == self.colv))
        self.monochromatic = bad
        assert bad == 0, f'the colouring is not proper on the quotient ({bad} monochromatic incidences)'

    # -- the fan gap (phase 1d's screen, recomputed here independently)
    def gapped_vertices(self):
        mask = np.zeros((self.n, 4), dtype=bool)
        mask[np.arange(self.n), self.colv] = True
        for t in self.add:
            mask[np.arange(self.n), self.colv[t]] = True
        return np.nonzero(~mask.all(axis=1))[0].tolist()

    def gap_at(self, i):
        seen = {int(self.colv[i])} | {int(self.colv[t[i]]) for t in self.add}
        return sorted(set(range(4)) - seen)

    # -- the Kempe component of the origin in the two-colour subgraph {a, b}
    def component(self, a, b, stop_at_top=True):
        """BFS from 0bar over classes coloured a or b.

        Returns (p: dict class index -> its tree voltage, V: HNF basis of the closed-walk voltages,
        edge incidences, [N*Lambda : V])."""
        rank, N = self.rank, self.N
        assert self.col[0] == a
        top = N ** rank                          # [N*Lambda : V] == 1 means V == N*Lambda, the top
        inQ = np.logical_or(self.colv == a, self.colv == b)
        p = {0: tuple([0] * rank)}
        order = [0]
        head = 0
        U, add = self.U, self.add
        # pass 1: a spanning tree by BFS, carrying the absolute voltage (an actual lattice point of the class)
        while head < len(order):
            i = order[head]
            head += 1
            pi = p[i]
            for k in range(len(U)):
                j = int(add[k][i])
                if inQ[j] and j not in p:
                    s = U[k]
                    p[j] = tuple(x + y for x, y in zip(pi, s))
                    order.append(j)
        if planted('component_all'):
            # PLANT: every class of colour a or b declared reached, with its digit vector as the voltage
            for j in range(self.n):
                if inQ[j] and j not in p:
                    p[j] = class_digits(j, N, rank)
                    order.append(j)
        # pass 2: the fundamental cycles, one per edge incidence (tree edges give 0 and are skipped by `any(g)`)
        V = []
        Vfull = False
        edges = 0
        if not planted('tree_only'):
            for i in order:
                pi = p[i]
                for k in range(len(U)):
                    j = int(add[k][i])
                    if not inQ[j]:
                        continue
                    edges += 1
                    if Vfull:
                        continue
                    s = U[k]
                    if planted('voltage_off') and i == order[0] and k == 0:
                        s = (s[0] + 1,) + tuple(s[1:])        # PLANT: one edge's voltage is wrong
                    pj = p[j]
                    if planted('p_zero'):
                        pi2 = pj2 = tuple([0] * rank)         # PLANT: the tree voltages discarded
                        g = [x + y - z for x, y, z in zip(pi2, s, pj2)]
                    else:
                        g = [x + y - z for x, y, z in zip(pi, s, pj)]
                    if any(g) and not member(V, g, rank):
                        V, _ = hnf_insert(V, g, rank)
                        if stop_at_top and det_of(V, rank) == top:
                            Vfull = True
        return p, V, edges, index_in_top(det_of(V, rank), top)

    def screen(self, delta, targets_name='', stop_at_top=True):
        """delta in HNF coordinates.  Returns a row dict."""
        rank, N = self.rank, self.N
        dbar = self._ix(tuple(x % N for x in delta))
        a = self.col[0]
        row = {'label': self.label, 'N': N, 'rank': rank, 'g': len(self.U), 'target': targets_name,
               'delta': list(delta), 'colour_origin': a, 'colour_delta': self.col[dbar],
               'saturated': self.saturated}
        if self.col[dbar] != a:
            row['verdict'] = 'escape'
            row['level'] = 0
            row['reason'] = 'the periodic colouring already separates the pair: c(delta) != c(0)'
            return row
        row['level'] = 1
        per_b = {}
        escape_b = None
        for b in range(4):
            if b == a:
                continue
            p, V, edges, quotient_index = self.component(a, b, stop_at_top)
            inQ0 = dbar in p
            reached = bool(inQ0 and member(V, [x - y for x, y in zip(delta, p[dbar])], rank))
            per_b[b] = {'component_classes': len(p), 'component_edges': edges,
                        'V_rank': len(V), 'V_index_in_NLambda': quotient_index,
                        'delta_class_in_Q0': bool(inQ0), 'delta_in_K0': reached}
            if not reached and escape_b is None:
                escape_b = b
        row['per_b'] = per_b
        row['verdict'] = 'escape' if escape_b is not None else 'rigid'
        if escape_b is not None:
            row['escape_colour'] = escape_b
            row['reason'] = (f'the (a,b) = ({a},{escape_b}) Kempe component of the origin misses delta; the swap '
                             f'is a proper four-colouring of every graph on the lattice separating the pair')
        else:
            row['reason'] = 'every Kempe component of the origin reaches delta: rigid under this periodic colouring'
        return row


def translate(pc, t):
    """c'(x) = c(x + t): another proper quotient colouring, with the class t moved to the origin.

    Row 66's theorem translates a gap at any vertex to every vertex; the screen looks only at the ORIGIN, so a
    colouring gapped elsewhere is brought here first."""
    N, rank = pc.N, pc.rank
    pw = pc.pw
    digits = [(np.arange(pc.n, dtype=np.int64) // p) % N for p in pw]
    tdig = [(t // p) % N for p in pw]
    tot = np.zeros(pc.n, dtype=np.int64)
    for p in range(rank):
        tot += ((digits[p] + tdig[p]) % N) * pw[p]
    return PeriodicColouring(pc.U, N, rank, pc.colv[tot].tolist(),
                             label=pc.label + f'|translated by class {t}', saturated=pc.saturated)


# ---------------------------------------------------------------- the SAT finders

def _cnf(n, edges, unit_clauses, extra):
    cls = []
    for v in range(n):
        cls.append([4 * v + c + 1 for c in range(4)])
    for i, j in edges:
        for c in range(4):
            cls.append([-(4 * i + c + 1), -(4 * j + c + 1)])
    cls += [[l] for l in unit_clauses]
    cls += extra
    return cls


def quotient_edges(U, N, rank):
    """the DEDUPLICATED simple graph Cay(Lambda/N Lambda, U mod N) -- the CNF's object.

    The screen deliberately does NOT use this: there the parallel edges carry different voltages and are the
    whole content (see the plant `dedup_steps`)."""
    pw = powers(N, rank)
    n = N ** rank
    Smod = sorted({tuple(x % N for x in s) for s in U})
    assert tuple([0] * rank) not in Smod, 'N not admissible'
    digits = [(np.arange(n, dtype=np.int64) // p) % N for p in pw]
    Sidx = [sum(c * p for c, p in zip(s, pw)) for s in Smod]
    ij = []
    for s in Smod:
        tot = np.zeros(n, dtype=np.int64)
        for p in range(rank):
            tot += ((digits[p] + s[p]) % N) * pw[p]
        i = np.arange(n, dtype=np.int64)
        m = i < tot
        ij.append(np.stack([i[m], tot[m]], axis=1))
    E = np.unique(np.concatenate(ij, axis=0), axis=0)
    return n, [(int(a), int(b)) for a, b in E], Sidx


def solve_cnf(cls, nvar, budget=600, solver='kissat'):
    path = os.path.join(ROOT, 'build', 'fs70', f'pk-{os.getpid()}-{abs(hash(str(len(cls))))%10**6}.cnf')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(f'p cnf {nvar} {len(cls)}\n')
        f.writelines(' '.join(map(str, c)) + ' 0\n' for c in cls)
    sha = hashlib.sha256(open(path, 'rb').read()).hexdigest()
    t = time.time()
    try:
        p = subprocess.run([solver, '-q', path], capture_output=True, text=True, timeout=budget)
        out = p.stdout
    except subprocess.TimeoutExpired:
        os.remove(path)
        return 'UNKNOWN', time.time() - t, None, sha
    secs = time.time() - t
    v = 'UNKNOWN'
    for line in out.splitlines():
        if line.startswith('s '):
            v = 'UNSAT' if 'UNSATISFIABLE' in line else 'SAT'
    model = None
    if v == 'SAT':
        lits = []
        for line in out.splitlines():
            if line.startswith('v '):
                lits += [int(x) for x in line[2:].split()]
        pos = {x for x in lits if x > 0}
        model = [next((c for c in range(4) if 4 * v_ + c + 1 in pos), None) for v_ in range(nvar // 4)]
    os.remove(path)
    return v, secs, model, sha


def find(U, N, rank, aim, delta=None, budget=600, solver='kissat'):
    """aim = 'gap' | 'sep'.  Returns (verdict, seconds, colouring, sha, note)."""
    n, edges, Sidx = quotient_edges(U, N, rank)
    pw = powers(N, rank)
    units = [4 * 0 + 0 + 1]                       # the origin takes colour 0 (colour permutation)
    extra = []
    nb = min(Sidx)
    if aim == 'gap':
        units.append(-(4 * 0 + 3 + 1))            # redundant with the origin pin; kept for readability
        for s in Sidx:
            units.append(-(4 * s + 3 + 1))
        units.append(4 * nb + 1 + 1)              # the least neighbour takes colour 1 (colours 1,2 free)
        note = 'colour 3 absent from N[0]; origin pinned 0; least neighbour pinned 1'
    elif aim == 'sep':
        dbar = sum((x % N) * p for x, p in zip(delta, pw))
        if dbar == 0:
            return 'n/a', 0.0, None, '', 'delta lies in N*Lambda, so its class is the origin'
        units.append(-(4 * dbar + 0 + 1))         # c(delta) != c(0) = 0
        units.append(4 * nb + 1 + 1)              # the least neighbour takes colour 1 (colours 1,2,3 free)
        # colours 2 and 3 are still interchangeable: precedence -- 3 at v only if 2 appears earlier.  Restricted
        # to a prefix, because the full set is O(n^2) literals; a SUBSET of a sound break is still sound.
        pre = min(n, 512)
        for v in range(pre):
            extra.append([-(4 * v + 3 + 1)] + [4 * u + 2 + 1 for u in range(v)])
        note = f'c(delta) != c(0); origin pinned 0; least neighbour pinned 1; 2<3 precedence on the first {pre}'
    else:
        raise SystemExit('aim must be gap or sep')
    cls = _cnf(n, edges, units, extra)
    v, secs, model, sha = solve_cnf(cls, 4 * n, budget, solver)
    if v == 'SAT':
        bad = sum(1 for i, j in edges if model[i] is None or model[i] == model[j])
        assert bad == 0, 'the solver returned an improper colouring'
    return v, secs, model, sha, note


