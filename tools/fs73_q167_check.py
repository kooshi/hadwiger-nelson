#!/usr/bin/env python3
"""fs73_q167_check -- standalone checker: a lattice of unit vectors over Q(sqrt d) is 3-colourable by a residue colouring.

STANDARD LIBRARY ONLY; imports nothing from tools/.  Written for a reviewer who trusts none of this repository's code.

THE CLAIM a witness makes.  Lambda = (1/M) * (Z-row-span of the 4x4 integer matrix H), a vector (a, b, c, e) standing for the point
((a + b sqrt d)/M, (c + e sqrt d)/M) of Q(sqrt d)^2.  U = EVERY unit vector of Q(sqrt d)^2 lying in Lambda.  The graph Cay(Lambda, U)
(points of Lambda, joined when they differ by an element of U -- exactly the unit-distance graph on Lambda) has the proper 3-colouring

        c(x) = floor(3 * psi(red(x)) / q),   red(x) = ((a + b s) M^-1, (c + e s) M^-1) mod q,   psi(X, Y) = alpha X + beta Y mod q,

where q is a prime not dividing M and s^2 = d (mod q).

WHY THE CHECKS BELOW PROVE IT (each step is one check).
  1. red is Z-linear in (a, b, c, e), hence additive on Lambda (it is reduction modulo the prime (q, sqrt d - s) of Z[sqrt d], whose
     residue field is F_q because q is prime and s^2 = d; Lambda's denominators divide M, a unit mod q).
  2. COMPLETENESS OF U, independent of whoever built the lattice: every unit vector of Lambda has coordinates in (1/M)Z^4, since H
     is integral; so the integer solutions of a^2 + d b^2 + c^2 + d e^2 = M^2, ab + ce = 0 (which is x^2 + y^2 = 1 in Q(sqrt d)) --
     a finite set, every coordinate bounded by M -- kept when in Lambda, are ALL of U.  They are enumerated twice, by two loops
     over different variable pairs ((b, e, a) solving for c; (a, c, b) solving for e), and the two sets must be equal.  A missed
     unit vector would make colouring EASIER, so this is the soundness edge of a colourability certificate (G68).
  3. For x ~ x + u (u in U): psi(red(x + u)) = psi(red(x)) + psi(red(u)) mod q.  If q <= 3 psi(red(u)) <= 2q for every u in U, then
     x and x + u get different colours: two residues in one third [jq/3, (j+1)q/3) differ, mod q, by less than q/3 or more than 2q/3.
  4. The colouring is constant on cosets of ker(psi o red), which contains q*Lambda: it is PERIODIC.
  5. The GAP: a point with psi(red(x)) = 0 (the origin) has colour 0 and every neighbour has colour floor(3t/q) with
     q/3 <= t <= 2q/3, i.e. colour 1 (when 3t < 2q) -- so its closed neighbourhood misses colour 2.  A gapped periodic colouring frees
     every pair of the lattice graph (row 66's fan-gap theorem, colour-generic): no two points are forced equal at three colours.
  6. Consistency with the recorded lattice: the Z-span of U has Hermite normal form H (the lattice IS generated by its unit vectors),
     and |U| equals the witness's recorded count.
  A direct check on a finite piece of Lambda (every edge of the word ball of radius 3 in U) is run as well; it is corroboration,
  not the proof, and its own failure path is exercised by a control.

VERDICTS (first failure wins; exit 0 only on CERTIFIED):
  CERTIFIED | BAD_WITNESS | Q_NOT_PRIME | Q_DIVIDES_M | ROOT_NOT_SQRT | UNIT_ENUMERATION_DISAGREES | NOT_UNIT_GENERATED |
  UNIT_COUNT | UNIT_IN_BAD_THIRD | TABLE_NOT_PROPER | NOT_ONTO |
  NO_GAP | BOX_EDGE_MONOCHROMATIC
  Witness kinds: 'interval' (q, s, alpha, beta; the default), 'table' (q, s, and a string of q^2 colours of F_q^2 indexed
  x*q + y), 'form_mod_N' (N and the form's values on the rows of H).
  --controls runs planted faults, each of which must be refused for its named reason, and the faithful twin, which must pass.
"""
import sys, json, math, copy, itertools


def is_prime(n):
    return n >= 2 and all(n % p for p in range(2, int(math.isqrt(n)) + 1))


def hnf(rows):
    """row Hermite normal form (upper triangular, positive pivots, entries above a pivot reduced into [0, pivot)) of an integer
    matrix of full column rank 4; returns the 4 nonzero rows"""
    A = [list(r) for r in rows]
    out = []
    col = 0
    while col < 4:
        nz = [r for r in A if r[col] != 0]
        if not nz:
            raise ValueError('rank < 4')
        while len([r for r in A if r[col] != 0]) > 1:
            nz = sorted([r for r in A if r[col] != 0], key=lambda r: abs(r[col]))
            p = nz[0]
            for r in nz[1:]:
                k = r[col] // p[col]
                for j in range(4):
                    r[j] -= k * p[j]
        p = next(r for r in A if r[col] != 0)
        if p[col] < 0:
            p[:] = [-t for t in p]
        A = [r for r in A if r is not p and any(r)]
        out.append(p)
        col += 1
    for i in range(4):
        for k in range(i):
            f = out[k][i] // out[i][i]
            out[k] = [x - f * y for x, y in zip(out[k], out[i])]
    return [tuple(r) for r in out]


def in_lattice(H, v):
    """v in the Z-row-span of the upper-triangular H with positive pivots"""
    r = list(v)
    for i in range(4):
        if r[i] % H[i][i]:
            return False
        t = r[i] // H[i][i]
        r = [x - t * y for x, y in zip(r, H[i])]
    return not any(r)


def unit_vectors(d, M):
    """every (a, b, c, e) with ((a + b sqrt d)/M)^2 + ((c + e sqrt d)/M)^2 = 1"""
    out = []
    M2 = M * M
    bmax = math.isqrt(M2 // d)
    for b in range(-bmax, bmax + 1):
        for e in range(-bmax, bmax + 1):
            rest = M2 - d * (b * b + e * e)
            if rest < 0:
                continue
            amax = math.isqrt(rest)
            for a in range(-amax, amax + 1):
                c2 = rest - a * a
                c = math.isqrt(c2)
                if c * c != c2:
                    continue
                for cc in ({c, -c}):
                    if a * b + cc * e == 0:
                        out.append((a, b, cc, e))
    return sorted(set(out))


def unit_vectors_by_ac(d, M):
    """the same set, enumerated the other way round (a second, independent loop): for each (a, c) with a^2 + c^2 <= M^2 and
    d | M^2 - a^2 - c^2, every (b, e) with b^2 + e^2 = (M^2 - a^2 - c^2)/d, then the cross condition ab + ce = 0"""
    out = []
    M2 = M * M
    for a in range(-M, M + 1):
        cmax = math.isqrt(M2 - a * a)
        for c in range(-cmax, cmax + 1):
            r = M2 - a * a - c * c
            if r % d:
                continue
            r //= d
            bmax = math.isqrt(r)
            for b in range(-bmax, bmax + 1):
                e2 = r - b * b
                e = math.isqrt(e2)
                if e * e != e2:
                    continue
                for ee in ({e, -e}):
                    if a * b + c * ee == 0:
                        out.append((a, b, c, ee))
    return sorted(set(out))


def check(w, words=3, quiet=False, _skip_third=False, _drop_unit=False):
    say = (lambda *a: None) if quiet else (lambda *a: print(*a, flush=True))
    try:
        d, M, H = int(w['d']), int(w['M']), [tuple(int(x) for x in r) for r in w['H']]
        kind = w.get('kind', 'interval')
        assert kind in ('interval', 'table', 'form_mod_N')
        if kind == 'form_mod_N':
            q, s, al, be = int(w['N']), None, None, None
            phiH = [int(t) for t in w['phi_on_H_rows']]
            assert len(phiH) == 4
        else:
            q, s = int(w['q']), int(w['s'])
            al, be = (int(w['alpha']), int(w['beta'])) if kind == 'interval' else (None, None)
            table = [int(ch) for ch in w['table']] if kind == 'table' else None
            assert kind != 'table' or (len(table) == q * q and set(table) <= {0, 1, 2})
        nU = int(w['unit_count'])
        assert len(H) == 4 and all(len(r) == 4 for r in H)
        assert all(H[i][j] == 0 for i in range(4) for j in range(i)) and all(H[i][i] > 0 for i in range(4))
    except Exception as ex:
        return 'BAD_WITNESS', f'{ex!r}'
    try:
        if hnf(H) != [tuple(r) for r in H]:
            return 'BAD_WITNESS', f'H is not in canonical Hermite normal form (canonical: {hnf(H)})'
    except ValueError as ex:
        return 'BAD_WITNESS', f'H: {ex}'
    if kind != 'form_mod_N':
        if not is_prime(q):
            return 'Q_NOT_PRIME', f'q = {q}'
        if M % q == 0:
            return 'Q_DIVIDES_M', f'q = {q}, M = {M}'
        if (s * s - d) % q:
            return 'ROOT_NOT_SQRT', f'{s}^2 - {d} = {s * s - d} is not divisible by {q}'
    allU = unit_vectors(d, M)
    if _drop_unit:                                        # PLANTED FAULT (controls only): the first enumerator loses one vector
        allU = [u for u in allU if u != next(v for v in allU if in_lattice(H, v))]
    allU2 = unit_vectors_by_ac(d, M)
    if allU != allU2:
        return 'UNIT_ENUMERATION_DISAGREES', (f'the two enumerations of the unit vectors over M = {M} differ: '
                                              f'{sorted(set(allU) ^ set(allU2))[:4]}')
    U = [u for u in allU if in_lattice(H, u)]
    say(f'  unit vectors over M = {M}: {len(allU)}; in the lattice: {len(U)}')
    try:
        if hnf(U) != [tuple(r) for r in H]:
            return 'NOT_UNIT_GENERATED', f'HNF of the unit vectors {hnf(U)} differs from H {H}'
    except ValueError as ex:
        return 'NOT_UNIT_GENERATED', f'{ex}'
    if len(U) != nU:
        return 'UNIT_COUNT', f'{len(U)} unit vectors in the lattice, witness records {nU}'
    if kind == 'form_mod_N':
        # c(x) = floor(3 (phi(x) mod N) / N), phi the Z-linear form with the given values on the rows of H: every x in Lambda is
        # x = sum t_i H_i with integer t (H triangular), and phi(x) = sum t_i phi_i
        def coords_H(v):
            r, t = list(v), []
            for i in range(4):
                assert r[i] % H[i][i] == 0
                t.append(r[i] // H[i][i])
                r = [x - t[-1] * y for x, y in zip(r, H[i])]
            assert not any(r)
            return t
        N = q
        colour = lambda v: (3 * (sum(a * b for a, b in zip(coords_H(v), phiH)) % N)) // N
        vals = [sum(a * b for a, b in zip(coords_H(u), phiH)) % N for u in U]
        for u, t in zip(U, vals):
            if not (N <= 3 * t <= 2 * N):
                return 'UNIT_IN_BAD_THIRD', f'u = {u}: phi(u) = {t} mod {N}, 3t not in [{N}, {2 * N}]'
        say(f'  phi(u) mod {N} over U: {sorted(set(vals))}: a circular colouring, period dividing {N} Lambda')
        nb_cols = {(3 * t) // N for t in vals}
        if (2 in nb_cols or 0 in nb_cols) and not _skip_third:
            return 'NO_GAP', f'neighbour colours of the origin {sorted(nb_cols)}'
        say(f'  gap: the origin has colour 0 and every neighbour colour {sorted(nb_cols)}')
    else:
        Mi = pow(M, -1, q)
        red = lambda v: ((v[0] + v[1] * s) * Mi % q, (v[2] + v[3] * s) * Mi % q)
        Ubar = sorted({red(u) for u in U})
        for X in Ubar:
            assert (X[0] * X[0] + X[1] * X[1]) % q == 1, 'a unit vector did not reduce to the circle (impossible if s^2 = d)'
        if kind == 'interval':
            psi = lambda X: (al * X[0] + be * X[1]) % q
            colour = lambda v: (3 * psi(red(v))) // q
            vals = []
            for u in U:
                t = psi(red(u))
                if not (q <= 3 * t <= 2 * q) and not _skip_third:
                    return 'UNIT_IN_BAD_THIRD', f'u = {u}: psi(red(u)) = {t}, 3t not in [{q}, {2 * q}]'
                vals.append(t)
            say(f'  psi(red(u)) over U: {sorted(set(vals))}; residue image {len(Ubar)} of {q + 1 if q % 4 == 3 else q - 1} circle points')
            nb_cols = {(3 * t) // q for t in vals}
            if (2 in nb_cols or 0 in nb_cols) and not _skip_third:
                return 'NO_GAP', f'neighbour colours of the origin {sorted(nb_cols)}'
            say(f'  gap: the origin has colour 0 and all {len(U)} neighbours colour {sorted(nb_cols)}; colour 2 is absent from its '
                f'closed neighbourhood')
        else:
            # the table colours Cay(F_q^2, Ubar): check every one of its q^2 |Ubar| arcs, then find a vertex with a gap
            colour = lambda v: table[red(v)[0] * q + red(v)[1]]
            for x in range(q):
                for y in range(q):
                    cv = table[x * q + y]
                    for (gx, gy) in Ubar:
                        if table[((x + gx) % q) * q + (y + gy) % q] == cv and not _skip_third:
                            return 'TABLE_NOT_PROPER', f'({x}, {y}) ~ ({(x + gx) % q}, {(y + gy) % q})'
            RH = [red(h) for h in H]                               # red is onto F_q^2 iff the rows' images have rank 2 mod q
            if not any((a[0] * b[1] - a[1] * b[0]) % q for a in RH for b in RH):
                return 'NOT_ONTO', f'the reduction of Lambda is not onto F_{q}^2, so a gap in the table need not be attained'
            gapv = next(((x, y) for x in range(q) for y in range(q)
                         if len({table[x * q + y]} | {table[((x + gx) % q) * q + (y + gy) % q] for gx, gy in Ubar}) < 3), None)
            if gapv is None and not _skip_third:
                return 'NO_GAP', 'no vertex of the residue target has a closed neighbourhood missing a colour'
            say(f'  the table properly 3-colours Cay(F_{q}^2, U mod p) ({len(Ubar)} of {q + 1 if q % 4 == 3 else q - 1} circle points); '
                f'gap at residue {gapv}')
    # corroboration on a finite piece: the word ball {sums of at most `words` unit vectors}, every edge inside it
    col = {(0, 0, 0, 0): 0}
    frontier = [(0, 0, 0, 0)]
    for _ in range(words):
        nxt = []
        for v in frontier:
            for u in U:
                wv = tuple(x + y for x, y in zip(v, u))
                if wv not in col:
                    col[wv] = colour(wv)
                    nxt.append(wv)
        frontier = nxt
    ne = 0
    for v, cv in col.items():
        for u in U:
            wv = tuple(x + y for x, y in zip(v, u))
            if wv in col:
                ne += 1
                if col[wv] == cv:
                    return 'BOX_EDGE_MONOCHROMATIC', f'{v} ~ {wv}'
    if ne == 0:
        return 'BOX_EDGE_MONOCHROMATIC', 'the corroboration piece has no edges: it could not have failed'
    say(f'  corroboration: the word ball of radius {words} ({len(col)} points, {ne // 2} edges): none monochromatic; colour counts '
        f'{[sum(1 for c in col.values() if c == j) for j in range(3)]}')
    how = f'the prime ({q}, sqrt{d} - {s})' if kind != 'form_mod_N' else f'a linear form mod {q}'
    return 'CERTIFIED', f'Cay(Lambda, U) over Q(sqrt{d}) ({len(U)} unit vectors) has a gapped periodic proper 3-colouring through {how}'


def controls(w):
    if w.get('kind', 'interval') != 'interval':
        return controls_other(w)
    bad = 0
    def expect(name, ww, want):
        nonlocal bad
        v, why = check(ww, words=2, quiet=True)
        ok = v == want
        bad += not ok
        print(f'  control {name:34s} -> {v:24s} {"ok" if ok else "WRONG, wanted " + want}   ({why})', flush=True)
    expect('faithful twin', copy.deepcopy(w), 'CERTIFIED')
    w1 = copy.deepcopy(w)
    w1['s'] = next(t for t in range(w['q']) if (t * t - w['d']) % w['q'])       # a residue that is NOT a square root of d
    expect('wrong square root', w1, 'ROOT_NOT_SQRT')
    q = w['q']
    w2 = copy.deepcopy(w)
    for al, be in itertools.product(range(q), repeat=2):         # the first form that puts some unit in a wrong third
        w2['alpha'], w2['beta'] = al, be
        if check(w2, words=1, quiet=True)[0] == 'UNIT_IN_BAD_THIRD':
            break
    expect('a form with a unit in a wrong third', w2, 'UNIT_IN_BAD_THIRD')
    w3 = copy.deepcopy(w); w3['unit_count'] = w['unit_count'] - 1
    expect('one unit vector fewer recorded', w3, 'UNIT_COUNT')
    w4 = copy.deepcopy(w)
    Hs = [list(r) for r in w['H']]
    Hs.append([0, 0, 0, Hs[3][3] // 2])                                      # adjoin (0,0,0,H33/2): a superlattice
    w4['H'] = [list(r) for r in hnf(Hs)]
    expect('a superlattice (not unit-generated)', w4, 'NOT_UNIT_GENERATED')
    w4b = copy.deepcopy(w); w4b['H'] = [list(r) for r in w['H']]; w4b['H'][0][3] += w['H'][3][3]
    expect('H not in canonical form', w4b, 'BAD_WITNESS')
    w5 = copy.deepcopy(w); w5['q'] = 5
    expect('q dividing M', w5, 'Q_DIVIDES_M')
    w6 = copy.deepcopy(w); w6['q'] = w['q'] + 2 if not is_prime(w['q'] + 2) else w['q'] + 4
    expect('q not prime', w6, 'Q_NOT_PRIME')
    # a dropped unit vector: the planted enumerator loses one vector of the lattice; the second enumeration must catch it
    v, why = check(w, words=1, quiet=True, _drop_unit=True)
    ok = v == 'UNIT_ENUMERATION_DISAGREES'
    bad += not ok
    print(f'  control {"one unit vector dropped by an enumerator":34s} -> {v:24s} {"ok" if ok else "WRONG, wanted UNIT_ENUMERATION_DISAGREES"}'
          f'   ({why})', flush=True)
    # the corroboration's own failure path: a form with a unit in a wrong third, the third-check disabled, must be caught on the ball
    v, why = check(w2, words=2, quiet=True, _skip_third=True)
    ok = v == 'BOX_EDGE_MONOCHROMATIC'
    bad += not ok
    print(f'  control {"corroboration alone, bad form":34s} -> {v:24s} {"ok" if ok else "WRONG, wanted BOX_EDGE_MONOCHROMATIC"}   ({why})',
          flush=True)
    return bad


def controls_other(w):
    """planted faults for the 'table' and 'form_mod_N' witness kinds"""
    bad = 0
    def expect(name, ww, want, **kw):
        nonlocal bad
        v, why = check(ww, words=2, quiet=True, **kw)
        ok = v == want
        bad += not ok
        print(f'  control {name:40s} -> {v:26s} {"ok" if ok else "WRONG, wanted " + want}   ({why[:110]})', flush=True)
    expect('faithful twin', copy.deepcopy(w), 'CERTIFIED')
    w3 = copy.deepcopy(w); w3['unit_count'] = w['unit_count'] - 1
    expect('one unit vector fewer recorded', w3, 'UNIT_COUNT')
    expect('one unit vector dropped by an enumerator', copy.deepcopy(w), 'UNIT_ENUMERATION_DISAGREES', _drop_unit=True)
    if w['kind'] == 'table':
        q = w['q']
        w1 = copy.deepcopy(w)
        w1['s'] = next(t for t in range(q) if (t * t - w['d']) % q)
        expect('a residue that is not a square root', w1, 'ROOT_NOT_SQRT')
        # a monochromatic arc: give vertex (0,0) the colour of one of its target neighbours
        t = list(w['table'])
        others = [i for i in range(q * q) if i != 0 and t[i] != t[0]]
        w2 = copy.deepcopy(w)
        # find a neighbour of 0 in the target by trying the colour of every vertex until the check reports an improper arc
        for i in others:
            t2 = list(t); t2[0] = t[i]
            w2['table'] = ''.join(t2)
            if check(w2, words=1, quiet=True)[0] == 'TABLE_NOT_PROPER':
                break
        expect('one table entry recoloured into a neighbour', w2, 'TABLE_NOT_PROPER')
    else:
        N = w['N']
        w2 = copy.deepcopy(w)
        for delta in itertools.product(range(N), repeat=1):
            w2['phi_on_H_rows'] = [(w['phi_on_H_rows'][0] + delta[0]) % N] + list(w['phi_on_H_rows'][1:])
            if check(w2, words=1, quiet=True)[0] == 'UNIT_IN_BAD_THIRD':
                break
        expect('the form moved on one row', w2, 'UNIT_IN_BAD_THIRD')
    return bad


def main():
    if len(sys.argv) < 2:
        print('usage: fs73_q167_check.py WITNESS.json [--controls]')
        sys.exit(2)
    w = json.load(open(sys.argv[1]))
    print(f'fs73_q167_check: {sys.argv[1]}', flush=True)
    v, why = check(w)
    print(f'{v}: {why}', flush=True)
    rc = 0 if v == 'CERTIFIED' else 1
    if '--controls' in sys.argv:
        b = controls(w)
        print(f'controls: {b} wrong', flush=True)
        rc = rc or (1 if b else 0)
    sys.exit(rc)


if __name__ == '__main__':
    main()
