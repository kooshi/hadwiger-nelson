# ================================================================ local rigidity meter
def cmd_rigidity(D, spec, R, maxwords=2, wall=5.0, cap=300_000):
    """ball piece of physical radius R about 0; for every lattice point p = sum of <= maxwords generators (p != 0, not a generator), whether
    c(p) = c(0) is forced (separation UNSAT) or c(p) != c(0) is forced (identification UNSAT) in the piece. Counts are a meter of local
    rigidity (how many near pairs the piece already pins), recorded per pool and radius."""
    import numpy as np
    from pysat.solvers import Cadical195
    from fs58_chain import walled_solve
    C, names = spec_classes(D, spec)
    M, W = pool_vectors(D, C, names)
    B, coords, cov, mc = reduce_pool(D, M, W)
    path = outdir(D) / 'rigidity.jsonl'
    done = load_jsonl(path)
    key = f'{spec}|ball{R}|words{maxwords}'
    if key in done:
        r = done[key]
        print(f"[done] {key}: {r['points']} points; forced equal {r['forced_equal']}, forced different {r['forced_different']} of {r['pairs']}")
        return r
    t0 = time.time()
    flat = all(c[3] == 0 for c in coords)
    X, n = piece(D, M, B, (0, 0, 0, 0), 'ball', R, cap, flat=flat)
    if X is None:
        print(f'{key}: over cap ({n})')
        return None
    E = piece_edges(X, coords)
    nv = len(X)
    keys = pack(X)
    pos = {int(k): i for i, k in enumerate(keys)}
    G = [tuple(g) for g in coords]
    words = {(0, 0, 0, 0)}
    frontier = {(0, 0, 0, 0)}
    for _ in range(maxwords):
        frontier = {tuple(a + b for a, b in zip(x, g)) for x in frontier for g in G}
        words |= frontier
    targets = sorted(w for w in words if w != (0, 0, 0, 0) and w not in set(G))
    sv = Cadical195()
    sv.append_formula([[3 * v + 1, 3 * v + 2, 3 * v + 3] for v in range(nv)])
    for c in range(3):
        sv.append_formula(np.stack([-(3 * E[:, 0] + c + 1), -(3 * E[:, 1] + c + 1)], axis=1).tolist())
    i0 = pos[int(pack(np.array([[0, 0, 0, 0]]))[0])]
    r0, _ = walled_solve(sv, [3 * i0 + 1], wall)
    fe = fd = unk = asked = 0
    examples = []
    nxt = 3 * nv + 1
    for tgt in targets:
        k = int(pack(np.array([tgt]))[0])
        if k not in pos:
            continue
        j = pos[k]
        asked += 1
        sv.add_clause([-nxt, -(3 * j + 1)])          # separate: c(0) = 0, c(p) != 0
        a, _ = walled_solve(sv, [3 * i0 + 1, nxt], wall)
        nxt += 1
        sv.add_clause([-nxt, 3 * j + 1])             # identify: c(p) = 0
        b, _ = walled_solve(sv, [3 * i0 + 1, nxt], wall)
        nxt += 1
        if a is False:
            fe += 1
            examples.append(['equal', list(tgt)])
        if b is False:
            fd += 1
            examples.append(['different', list(tgt)])
        if a is None or b is None:
            unk += 1
    sv.delete()
    rec = {'key': key, 'pool': spec, 'R': R, 'points': nv, 'edges': int(len(E)), 'colourable': r0, 'pairs': asked, 'forced_equal': fe,
           'forced_different': fd, 'unknown': unk, 'examples': examples[:20], 'seconds': round(time.time() - t0, 1)}
    append(path, rec)
    print(f"{key}: {nv} points, {len(E)} edges; of {asked} near pairs: forced equal {fe}, forced different {fd}, unknown {unk} "
          f"({rec['seconds']} s)", flush=True)
    return rec


