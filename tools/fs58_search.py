# ================================================================ least character mean (the ratio-bound shadow, plan D6 / R-C)
def min_character_mean(coords, G=None, starts=30):
    """float reading: min over the dual torus of (1/|W|) sum_w cos(2 pi <theta, c_w>), by a grid of G^4 points refined by BFGS from the
    best `starts` grid points. The Cayley graph's independence ratio is at most mu/(1 + mu), mu = -min; min > -1/2 would put its
    fractional chromatic number above 3. A reading, not a certificate."""
    import numpy as np
    from scipy.optimize import minimize
    Cm = np.array(coords, dtype=float)
    mc = int(np.abs(Cm).max())
    G = G or max(16, min(40, 4 * mc))
    g = np.arange(G) / G
    A, Bm = np.meshgrid(g, g, indexing='ij')
    pre = np.stack([A.ravel(), Bm.ravel()], 1)
    post = pre
    cands = []
    for i in range(0, len(pre), G):
        P = pre[i:i + G]
        T = np.concatenate([np.repeat(P, len(post), 0), np.tile(post, (len(P), 1))], 1)
        v = np.cos(2 * np.pi * (T @ Cm.T)).mean(1)
        k = np.argsort(v)[:4]
        cands += [(float(v[j]), T[j]) for j in k]
    cands.sort(key=lambda x: x[0])
    f = lambda t: float(np.cos(2 * np.pi * (Cm @ t)).mean())
    gr = lambda t: -(2 * np.pi * np.sin(2 * np.pi * (Cm @ t))[:, None] * Cm).mean(0)
    best = (cands[0][0], cands[0][1])
    for v, t in cands[:starts]:
        r = minimize(f, t, jac=gr, method='BFGS')
        if r.fun < best[0]:
            best = (float(r.fun), r.x % 1)
    return best[0], [round(float(x), 5) for x in best[1]], G


