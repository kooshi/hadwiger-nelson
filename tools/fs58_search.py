#!/usr/bin/env python3
"""fs58_search -- FS-58 phase B5: pools of unit vectors over Q(sqrt D), D in {23, 167}, and forcing probes on thick pieces.

UNTRUSTED (tools/). Every edge and membership is exact integer arithmetic; floats only choose which lattice points a piece holds
(any choice is a legitimate graph) and calibrate. Solver verdicts are the solver's claims; SAT models are verified edge by edge.

Conventions. A vector (a, b, c, e) over M is ((a + b sqrtD)/M, (c + e sqrtD)/M); a unit vector has a^2 + D b^2 + c^2 + D e^2 = M^2 and
ab + ce = 0. A CLASS is an orbit of unit vectors of least denominator N under the order-16 group generated by the quarter turn, the
swap (x, y) -> (y, x) and the Galois conjugation sqrtD -> -sqrtD (all isometries of F^2 preserving unit vectors). Class names:
'N' for the orbit of least denominator N when it is the only one, else 'N.k' (k = 1, 2, ... in order of the representative); rational
classes (b = e = 0) are prefixed 'q' (q1 = the axis, q5 = the (3/5, 4/5) family, ...). A POOL is a union of classes; its lattice
Lambda = Z[W] has an LLL-reduced basis under the trace form (the Minkowski embedding, where a unit vector has length sqrt2).

Subcommands (every record is a JSONL line flushed and fsynced; a rerun skips records already on disk):
  classes D NMAX                 -> data/fs58/search-D/classes-NMAX.out: the orbit classes with denominators <= NMAX
  survey D NMAX K SPEC            -> data/fs58/search-D/survey.jsonl: every union of <= K classes from SPEC (comma list of class names,
                                    or 'all'): size, covolume, largest reduced coordinate, bipartite?, 3-integral?, admissible linear
                                    forms mod 3, least odd cycle (BFS to a cap) and the number of odd closed walks of that length at 0
  probe D POOLSPEC R-list [--dirs K] [--cap P] [--shape ball|span]
                                 -> data/fs58/search-D/probe.jsonl: for the K shortest directions u (up to sign) of the pool, the piece
                                    of lattice points within physical radius R of the midpoint of 0 and 3u in BOTH embeddings (shape
                                    ball) or the span box widened by R (shape span); queries: plain 3-colourability, separate (0, 3u)
                                    [UNSAT = forced], identify (0, 2u) [UNSAT = virtual edge], identify (0, 3u) [control]
Plan: plans/FS58-four-colours.md R-B4 (carried to B5).
"""
