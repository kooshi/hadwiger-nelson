# ================================================================ saturated pools: a lattice spanned by a few classes, with EVERY unit vector it holds
def _saturate_one(args):
    D, key, M, W, U, cap = args
    rec = {'key': key, 'D': D, 'M': M}
    try:
        ech = hnf_basis(W)
        if len(ech) < 4:
            rec['rank'] = len(ech)
            return rec
        Binv = inverse(ech)
        S = []
        for u in U:                                   # every unit vector over M; members of the lattice join the pool
            c = [sum(Fr(x) * Binv[i][j] for i, x in enumerate(u)) for j in range(4)]
            if all(t.denominator == 1 for t in c):
                S.append(u)
        B, coords, cov, mc = reduce_pool(D, M, S)
        bip = forms_mod(coords, 2)
        og = odd_girth(coords, cap) if not bip else {'length': None, 'bipartite': True}
        rec.update({'rank': 4, 'size_generators': len(W), 'size': len(S), 'covolume': cov, 'max_coord': mc, 'bipartite': bool(bip),
                    'three_integral': M % 3 != 0, 'forms_mod3': len(forms_mod(coords, 3)), 'odd': og,
                    'merit': len(S) * cov, 'saturated': [list(u) for u in S]})
    except AssertionError as ex:
        rec['error'] = str(ex)
    return rec


