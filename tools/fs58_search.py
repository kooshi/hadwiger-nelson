# ================================================================ records
def outdir(D):
    p = ROOT / 'data' / 'fs58' / f'search-{D}'
    p.mkdir(parents=True, exist_ok=True)
    return p


def load_jsonl(path):
    done = {}
    if path.exists():
        raw = path.read_bytes()
        *complete, tail = raw.split(b'\n')
        for ln in complete:
            if ln.strip():
                r = json.loads(ln)
                done[r['key']] = r
        if tail:
            with open(path, 'r+b') as f:
                f.truncate(len(raw) - len(tail))
    return done


def append(path, rec):
    with open(path, 'a') as f:
        f.write(json.dumps(rec, sort_keys=True, separators=(',', ':')) + '\n')
        f.flush()
        os.fsync(f.fileno())


# ================================================================ classes
def least_den(w, N):
    L = 1
    for x in w:
        q = Fr(x, N).denominator
        L = L * q // math.gcd(L, q)
    return L


def orbit(w):
    out = set()
    for g in range(2):
        a, b, c, e = w if g == 0 else (w[0], -w[1], w[2], -w[3])
        for _ in range(4):
            out.add((a, b, c, e))
            out.add((c, e, a, b))
            a, b, c, e = -c, -e, a, b
    return out


def classes(D, NMAX):
    """name -> (N, sorted list of vectors over N)"""
    found = []
    seen = set()
    for N in range(1, NMAX + 1):
        for w in units_d(N, D):
            if least_den(w, N) != N or w in seen:
                continue
            o = orbit(w)
            seen |= o
            found.append((N, max(o), sorted(o)))
    found.sort()
    out = {}
    byN = {}
    for N, rep, vecs in found:
        byN.setdefault(N, []).append((rep, vecs))
    for N, lst in byN.items():
        for rat in (True, False):
            sub = [(rep, vecs) for rep, vecs in lst if (rep[1] == 0 and rep[3] == 0) == rat]
            for k, (rep, vecs) in enumerate(sub):
                for w in vecs:
                    assert w[0] ** 2 + D * w[1] ** 2 + w[2] ** 2 + D * w[3] ** 2 == N * N and w[0] * w[1] + w[2] * w[3] == 0
                    assert (w[1] == 0 and w[3] == 0) == rat
                name = ('q' if rat else '') + str(N) + (f'.{k + 1}' if len(sub) > 1 else '')
                out[name] = (N, vecs)
    return out


def cmd_classes(D, NMAX):
    C = classes(D, NMAX)
    path = outdir(D) / f'classes-{NMAX}.out'
    lines = [f'classes of unit vectors of Q(sqrt{D})(i), least denominator <= {NMAX} (orbits under quarter turn, swap, Galois)']
    for name, (N, vecs) in C.items():
        rep = max(vecs)
        v2 = (N & -N).bit_length() - 1
        v3 = 0
        n = N
        while n % 3 == 0:
            n //= 3
            v3 += 1
        lines.append(f'  {name:8s} N={N:4d} size {len(vecs):2d} v2={v2} v3={v3} rep {rep}')
    path.write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


# ================================================================ pools
def pool_vectors(D, C, names):
    M = 1
    for n in names:
        N = C[n][0]
        M = M * N // math.gcd(M, N)
    W = sorted({tuple(x * (M // C[n][0]) for x in w) for n in names for w in C[n][1]})
    return M, W


def reduce_pool(D, M, W):
    """(basis, coords of W, covolume, largest |coordinate|)"""
    form = (1, D, 1, D)
    ech = hnf_basis(W)
    assert len(ech) in (3, 4), 'rank < 3'
    B = lll(ech, form)
    flat = len(B) == 3
    if flat:       # rank 3: a dummy fourth row outside the span, so coordinates are 4-tuples with last entry 0 on the pool
        for j in range(4):
            dummy = [int(i == j) for i in range(4)]
            from fs58_chain import det as _idet
            if _idet(B + [dummy]) != 0:
                B = B + [dummy]
                break
    Binv = inverse(B)
    coords = []
    for w in W:
        c = [sum(Fr(x) * Binv[i][j] for i, x in enumerate(w)) for j in range(4)]
        assert all(t.denominator == 1 for t in c)
        c = tuple(int(t) for t in c)
        assert tuple(sum(c[i] * B[i][j] for i in range(4)) for j in range(4)) == w
        coords.append(c)
    Bs = B[:3] if flat else B
    gram = [[Fr(2 * sum(f * x * y for f, x, y in zip(form, u, v)), M * M) for v in Bs] for u in Bs]
    cov = math.sqrt(float(_det_frac(gram)))
    if flat:
        assert all(c[3] == 0 for c in coords)
    return B, coords, cov, max(abs(x) for c in coords for x in c)


def odd_girth(coords, cap=BFS_CAP):
    """least odd cycle of Cay(Z^4, coords) (vertex-transitive: BFS from 0) and the number of edges inside the first level holding one"""
    G = [tuple(c) for c in coords]
    prev, cur, explored, L = set(), {(0, 0, 0, 0)}, 1, 0
    while True:
        nb = set()
        inside = 0
        for x in cur:
            for g in G:
                y = (x[0] + g[0], x[1] + g[1], x[2] + g[2], x[3] + g[3])
                if y in cur:
                    inside += 1
                elif y not in prev:
                    nb.add(y)
        if inside:
            return {'length': 2 * L + 1, 'closed_walk_edges_in_level': inside // 2, 'levels': L, 'explored': explored}
        if explored + len(nb) > cap:
            return {'length': None, 'none_up_to': 2 * L + 1, 'levels': L, 'explored': explored}
        prev, cur, explored, L = cur, nb, explored + len(nb), L + 1


def forms_mod(coords, p):
    """linear forms Z^4 -> Z/p (in basis coordinates) nonzero on every generator (p = 2: sending every generator to 1)"""
    out = []
    for f in itertools.product(range(p), repeat=4):
        vals = [sum(a * b for a, b in zip(f, c)) % p for c in coords]
        if (p == 2 and all(v == 1 for v in vals)) or (p == 3 and all(vals)):
            out.append(list(f))
    return out


def _survey_one(args):
    D, M, W, key, cap = args
    rec = {'key': key, 'D': D, 'M': M, 'size': len(W)}
    r = len(hnf_basis(W))
    if r < 4:
        rec['rank'] = r
        return rec
    t = time.time()
    B, coords, cov, mc = reduce_pool(D, M, W)
    bip = forms_mod(coords, 2)
    f3 = forms_mod(coords, 3)
    og = odd_girth(coords, cap) if not bip else {'length': None, 'bipartite': True}
    rec.update({'rank': 4, 'covolume': cov, 'max_coord': mc, 'bipartite': bool(bip), 'three_integral': M % 3 != 0,
                'forms_mod3': len(f3), 'odd': og, 'bfs_cap': cap, 'seconds': round(time.time() - t, 3)})
    return rec


def cmd_survey_wide(D, NMAX, NMAX3, cap, jobs=16):
    """bases {}, q1, q1+q5 joined with every pair of non-rational classes of denominator <= NMAX and every triple <= NMAX3"""
    C = classes(D, NMAX)
    nr = [n for n in C if not n.startswith('q')]
    combos = []
    for base in ((), ('q1',), ('q1', 'q5')):
        for r, bound in ((1, NMAX), (2, NMAX), (3, NMAX3)):
            for c in itertools.combinations([n for n in nr if C[n][0] <= bound], r):
                combos.append(base + c)
    run_survey(D, C, combos, cap, jobs)


def run_survey(D, C, combos, cap, jobs):
    import multiprocessing as mp
    path = outdir(D) / 'survey.jsonl'
    done = load_jsonl(path)
    t0 = time.time()
    todo = []
    for combo in combos:
        key = '+'.join(combo)
        if key not in done:
            M, W = pool_vectors(D, C, combo)
            todo.append((D, M, W, key, cap))
    print(f'survey D={D}: {len(todo)} pools to do, {len(done)} on disk', flush=True)
    with mp.get_context('fork').Pool(jobs) as P:
        for k, rec in enumerate(P.imap_unordered(_survey_one, todo, chunksize=8)):
            append(path, rec)
            if (k + 1) % 2000 == 0:
                print(f'  {k + 1}/{len(todo)} ({time.time() - t0:.0f} s)', flush=True)
    print(f'survey D={D}: {len(todo)} new records in {time.time() - t0:.0f} s ({path.relative_to(ROOT)})')


def cmd_survey(D, NMAX, K, spec, cap=BFS_CAP, jobs=16):
    import multiprocessing as mp
    C = classes(D, NMAX)
    names = list(C) if spec == 'all' else spec.split(',')
    for n in names:
        assert n in C, f'unknown class {n}; known: {list(C)}'
    path = outdir(D) / 'survey.jsonl'
    done = load_jsonl(path)
    t0 = time.time()
    todo = []
    for r in range(1, K + 1):
        for combo in itertools.combinations(names, r):
            key = '+'.join(combo)
            if key not in done:
                M, W = pool_vectors(D, C, combo)
                todo.append((D, M, W, key, cap))
    print(f'survey D={D}: {len(todo)} pools to do, {len(done)} on disk', flush=True)
    with mp.get_context('fork').Pool(jobs) as P:
        for k, rec in enumerate(P.imap_unordered(_survey_one, todo, chunksize=4)):
            append(path, rec)
            if (k + 1) % 200 == 0:
                print(f'  {k + 1}/{len(todo)} ({time.time() - t0:.0f} s)', flush=True)
    print(f'survey D={D}: {len(todo)} new records in {time.time() - t0:.0f} s ({path.relative_to(ROOT)})')


