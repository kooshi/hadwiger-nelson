# ================================================================ direct colourability of balls (no pair: is the piece itself 3-colourable?)
def _colour_ball(args):
    import numpy as np
    from pysat.solvers import Cadical195
    from fs58_chain import walled_solve
    D, spec, R, cap, wall = args
    try:
        C, names = spec_classes(D, spec)
        M, W = pool_vectors(D, C, names)
        B, coords, cov, mc = reduce_pool(D, M, W)
        t0 = time.time()
        flat = all(c[3] == 0 for c in coords)
        X, n = piece(D, M, B, (0, 0, 0, 0), 'ball', R, cap, flat=flat)
        if X is None:
            return {'key': f'{spec}|ball{R}', 'pool': spec, 'R': R, 'points': str(n), 'verdict': 'over cap'}
        E = piece_edges(X, coords)
        nv = len(X)
        sv = Cadical195()
        sv.append_formula([[3 * v + 1, 3 * v + 2, 3 * v + 3] for v in range(nv)])
        for c in range(3):
            sv.append_formula(np.stack([-(3 * E[:, 0] + c + 1), -(3 * E[:, 1] + c + 1)], axis=1).tolist())
        i0 = index_of(X, (0, 0, 0, 0))
        units = [3 * i0 + 1]
        if len(E):
            j = int(E[E[:, 0] == i0][0, 1]) if (E[:, 0] == i0).any() else int(E[E[:, 1] == i0][0, 0])
            units.append(3 * j + 2)
        r, dt = walled_solve(sv, units, wall)
        verdict = {None: 'Unknown (budget)', False: 'NOT 3-COLOURABLE (solver claim)'}.get(r)
        if r:
            col = (np.array(sv.get_model()[:3 * nv]).reshape(nv, 3) > 0).argmax(axis=1)
            assert (col[E[:, 0]] != col[E[:, 1]]).all()
            verdict = '3-colourable (model verified)'
        sv.delete()
        return {'key': f'{spec}|ball{R}', 'pool': spec, 'R': R, 'points': nv, 'edges': int(len(E)), 'covolume': cov, 'size': len(W),
                'verdict': verdict, 'solve_seconds': round(dt, 2), 'seconds': round(time.time() - t0, 2)}
    except AssertionError as ex:
        return {'key': f'{spec}|ball{R}', 'pool': spec, 'R': R, 'verdict': f'ERROR {ex}'}


