"""FS-73 P3b — standalone exact checker for the three-colour rotation set Θ of an FS-61 lattice.

Trusts nothing but Python integers and Fractions, and imports nothing from this repository. The same contract as the
committed `data/fs73/coxeter-c3/certcheck.py` (Coxeter, FS-73 C-7), written independently:

  point  FILE   FILE names {key, d, psi}: ψ is a functional on (a,b,c,e) coordinates. Checks ψ(u) mod 1 ∈ [1/3, 2/3] for
                every unit vector u of the lattice, re-enumerated here from the key. That is a proper 3-colouring
                x ↦ ⌊3{ψ(x)}⌋ of the lattice's unit-distance graph (H-i, the trivial direction).
  cert   FILE   FILE is a branch-and-bound certificate (certcheck.py's format: key, d, basis, S, nodes, leaves). Checks that
                S is every unit vector up to sign, in coordinates of a ℤ-basis of the lattice the unit vectors span, and
                walks the tree recomputing every bound; no leaves ⟹ Θ = ∅ ⟹ (H-i) the graph is not 3-colourable.

The unit vectors are enumerated with a different loop order from both tools/fs73_theta_lib.py and certcheck.py:
over (b, e) first, then a, solving for c; lattice membership by exact solution against the key's HNF rows.
"""
import json
import math
import sys
from fractions import Fraction as Fr


def enumerate_units(key, d):
    M = int(key.split("|")[0])
    H = [list(map(int, r.split(","))) for r in key.split("|")[1].split(";")]
    out = set()
    lim = M * M
    bm = 0
    while d * (bm + 1) ** 2 <= lim:
        bm += 1
    for b in range(-bm, bm + 1):
        for e in range(-bm, bm + 1):
            rest = lim - d * (b * b + e * e)
            if rest < 0:
                continue
            for a in range(-M, M + 1):
                c2 = rest - a * a
                if c2 < 0:
                    continue
                c = math.isqrt(c2)
                if c * c != c2:
                    continue
                for cc in (c, -c):
                    if a * b + cc * e == 0 and member((a, b, cc, e), H):
                        out.add((a, b, cc, e))
    return M, H, sorted(out)


def member(v, H):
    """v in the row lattice of H: solve x H = v exactly (H square, nonsingular), require x integral."""
    x = solve_rows(H, v)
    return x is not None and all(t.denominator == 1 for t in x)


def solve_rows(Brows, v):
    """x with Σ x_k Brows[k] = v (Brows square nonsingular), exactly."""
    n = len(Brows)
    Mx = [[Fr(Brows[k][i]) for k in range(n)] + [Fr(v[i])] for i in range(n)]
    for col in range(n):
        piv = next((i for i in range(col, n) if Mx[i][col] != 0), None)
        if piv is None:
            return None
        Mx[col], Mx[piv] = Mx[piv], Mx[col]
        p = Mx[col][col]
        Mx[col] = [t / p for t in Mx[col]]
        for i in range(n):
            if i != col and Mx[i][col] != 0:
                f = Mx[i][col]
                Mx[i] = [Mx[i][t] - f * Mx[col][t] for t in range(n + 1)]
    return [Mx[i][n] for i in range(n)]


def hnf_rows(vectors):
    """Canonical upper-triangular row HNF (positive pivots, entries above each pivot reduced into [0, pivot))."""
    A = [list(v) for v in vectors if any(v)]
    n = len(A[0])
    out = []
    col = 0
    while A and col < n:
        while True:
            nz = [r for r in A if r[col] != 0]
            if len(nz) <= 1:
                break
            p = min(nz, key=lambda r: abs(r[col]))
            A = [r if r is p or r[col] == 0 else [r[t] - (r[col] // p[col]) * p[t] for t in range(n)] for r in A]
        nz = [r for r in A if r[col] != 0]
        if nz:
            p = nz[0] if nz[0][col] > 0 else [-t for t in nz[0]]
            out.append(p)
            A = [r for r in A if r[col] == 0 and any(r)]
        col += 1
    for i in range(len(out)):
        pc = next(c for c in range(n) if out[i][c] != 0)
        for k in range(i):
            q = out[k][pc] // out[i][pc]
            out[k] = [out[k][t] - q * out[i][t] for t in range(n)]
    return out


def band(x):
    f = x - math.floor(x)
    return Fr(1, 3) <= f <= Fr(2, 3)


def check_point(path):
    C = json.load(open(path))
    key, d = C["key"], int(C["d"])
    psi = [Fr(x) for x in C["psi"]]
    M, H, U = enumerate_units(key, d)
    vals = [sum(p * t for p, t in zip(psi, u)) for u in U]
    bad = [u for u, v in zip(U, vals) if not band(v)]
    fr = [v - math.floor(v) for v in vals]
    assert not bad, f"{len(bad)} unit vectors outside the band, e.g. {bad[:3]}"
    assert len(U) > 0
    # the period group: the image of the lattice under ψ mod 1 is generated by ψ of the HNF rows
    den = 1
    for row in H:
        den = math.lcm(den, sum(p * t for p, t in zip(psi, row)).denominator)
    print(f"POINT OK: {key} over Q(sqrt{d}): {len(U)} unit vectors, psi(u) mod 1 in [{min(fr)}, {max(fr)}] ⊆ [1/3, 2/3];"
          f" the key lattice's image under psi mod 1 is cyclic of order {den}")


def lower(A, b, c, y, r):
    assert len(y) == len(A) and all(t >= 0 for t in y)
    yA = [sum(y[k] * A[k][i] for k in range(len(A))) for i in range(r)]
    u = [max(Fr(0), -(yA[i] + c[i])) for i in range(r)]
    return -(sum(y[k] * b[k] for k in range(len(A))) + sum(u))


def check_cert(path):
    C = json.load(open(path))
    key, d, Bm, S = C["key"], int(C["d"]), C["basis"], C["S"]
    r = len(Bm)
    M, H, U = enumerate_units(key, d)
    # 1. the basis spans exactly the lattice the unit vectors span
    assert hnf_rows(Bm) == hnf_rows(U), "basis does not span the same lattice as the unit vectors"
    # 2. S is every unit vector up to sign, in basis coordinates
    coords = set()
    for u in U:
        x = solve_rows(Bm, u)
        assert x is not None and all(t.denominator == 1 for t in x)
        coords.add(tuple(int(t) for t in x))
    Sset = {tuple(s) for s in S}
    assert all(s in coords and tuple(-t for t in s) in coords for s in Sset), "S has a vector that is not a unit vector"
    assert all(c in Sset or tuple(-t for t in c) in Sset for c in coords), "a unit vector is missing from S"
    print(f"lattice OK: {len(U)} unit vectors, S has {len(S)} (one per ± pair: {len(Sset) * 2 == len(U)})")
    # 3. the tree
    nodes = {tuple(tuple(p) for p in n["p"]): n for n in C["nodes"]}
    leaves = {tuple(tuple(p) for p in lf) for lf in C["leaves"]}
    Sf = [[Fr(t) for t in s] for s in S]
    todo = [()]
    seen = 0
    while todo:
        p = todo.pop()
        seen += 1
        if len(p) == len(S):
            assert p in leaves, "a full-depth path that is not a declared leaf"
            continue
        n = nodes[p]
        A, b = [], []
        for (i, j) in p:
            A.append(Sf[i]); b.append(Fr(3 * j + 2, 3))
            A.append([-t for t in Sf[i]]); b.append(Fr(-(3 * j + 1), 3))
        if "farkas" in n:
            assert lower(A, b, [Fr(0)] * r, [Fr(t) for t in n["farkas"]], r) > 0, "Farkas vector does not refute"
            continue
        c = Sf[len(p)]
        L = lower(A, b, c, [Fr(t) for t in n["yl"]], r)
        Uu = -lower(A, b, [-t for t in c], [Fr(t) for t in n["yu"]], r)
        need = [j for j in range(math.floor(L) - 1, math.ceil(Uu) + 1)
                if Fr(3 * j + 1, 3) <= Uu and Fr(3 * j + 2, 3) >= L]
        assert sorted(n["ch"]) == need, f"children {n['ch']} do not match the certified range {need}"
        for j in need:
            todo.append(p + ((len(p), j),))
    print(f"CERTIFICATE OK: {seen} nodes walked, {len(leaves)} leaves =>",
          "Theta EMPTY (not 3-colourable, by H-i)" if not leaves else "leaves present (candidate cells)")


if __name__ == "__main__":
    {"point": check_point, "cert": check_cert}[sys.argv[1]](sys.argv[2])
