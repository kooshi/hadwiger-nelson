#!/usr/bin/env python3
"""FS124-I1: the axioms of every theorem of the three modules of the radius clause, against the planner's § 3.5.

    axioms_check.py gen <statements-after.txt> <out.lean>      write one `#print axioms` line per theorem
    axioms_check.py check <statements-after.txt> <print.txt>   check the print
    axioms_check.py control <print-of-control.txt>              the planted faults must each be reported

Expected (plans/FS124-kernel-plan.md § 3.5):
  on the standard three and `Outside.OAI158.proper_to_borel_weak`, exactly: the four names in T;
  on the standard three and `Outside.OAI158.no_proper_five_coloring`, exactly: `radius_five`;
  every other theorem of the three modules: a subset of the standard three.
A record is checked as a set.  `sorryAx`, any other axiom, a missing import and a second import each fail.
`check` also fails if a theorem of the three modules (read from the statements print) has no record.

The control (`data/fs124/i1/lean/AxiomsControl.lean`) declares three theorems outside the library and prints them:
one proved by `sorry`, expected clean; C124-RADIUS-FIVE's sentence proved from `radius_five`, expected clean; one
resting on both imports, expected on the transfer alone.  `control` exits 0 iff exactly those three are reported.
"""
import re, sys

STD = {"propext", "Classical.choice", "Quot.sound"}
P = "HadwigerNelson.Plane."
T_AX = "HadwigerNelson.Outside.OAI158.proper_to_borel_weak"
H_AX = "HadwigerNelson.Outside.OAI158.no_proper_five_coloring"
ON_T = {P + n for n in ("exists_isWeakColouringOn_of_colorable", "radius_down", "colorable_iff_forall_ball",
                        "seven_le_chromaticNumber_plane_iff_exists_ball")}
ON_H = {P + "radius_five"}
GENERATED = re.compile(r"(\._simp_\d+_\d+|\._proof_\d+(_\d+)?|\.match_\d+|\._auxLemma\.\d+|\.congr_simp|\._eq_\d+)$")

def theorems(statements_path):
    out = []
    for ln in open(statements_path).read().splitlines():
        if ln.startswith("theorem "):
            name = ln.split(" | ")[0].split(" ", 1)[1]
            if not GENERATED.search(name):
                out.append(name)
    return out

def records(print_path):
    """name -> set of axioms; `#print axioms` wraps long lists, so rejoin each record first."""
    text = open(print_path).read()
    recs, other = {}, []
    joined, buf = [], None
    for ln in text.splitlines():
        if buf is not None:
            buf += " " + ln.strip()
            if "]" in ln:
                joined.append(buf); buf = None
            continue
        if ln.startswith("'") and " depends on axioms: [" in ln:
            if "]" in ln: joined.append(ln)
            else: buf = ln
        else:
            joined.append(ln)
    if buf is not None:
        joined.append(buf)
    for ln in joined:
        m = re.match(r"^'([^']+)' depends on axioms: \[(.*)\]\s*$", ln)
        if m:
            recs[m.group(1)] = {a.strip() for a in m.group(2).split(",") if a.strip()}
            continue
        m = re.match(r"^'([^']+)' does not depend on any axioms\s*$", ln)
        if m:
            recs[m.group(1)] = set(); continue
        if ln.strip():
            other.append(ln)
    return recs, other

def verdict(name, axioms, expect):
    """expect: 'clean' | 'T' | 'H'.  Returns a failure string or None."""
    allowed = set(STD) | ({T_AX} if expect == "T" else {H_AX} if expect == "H" else set())
    extra = axioms - allowed
    if extra:
        return f"FAIL {name}: expected {expect}, carries {sorted(extra)}"
    if expect == "T" and T_AX not in axioms:
        return f"FAIL {name}: expected on proper_to_borel_weak, does not carry it"
    if expect == "H" and H_AX not in axioms:
        return f"FAIL {name}: expected on no_proper_five_coloring, does not carry it"
    return None

def expectation(name):
    return "T" if name in ON_T else "H" if name in ON_H else "clean"

def main():
    mode = sys.argv[1]
    if mode == "gen":
        names = theorems(sys.argv[2])
        with open(sys.argv[3], "w") as f:
            f.write("import Proofs.HadwigerNelson.Plane.RadiusOutside\n"
                    "-- FS124-I1: generated by data/fs124/i1/axioms_check.py gen — every theorem of the three modules.\n"
                    "set_option pp.fullNames true\n")
            for n in names:
                f.write(f"#print axioms {n}\n")
        print(f"wrote {len(names)} records to {sys.argv[3]}")
    elif mode == "check":
        names = theorems(sys.argv[2])
        recs, other = records(sys.argv[3])
        fails = []
        for ln in other:
            fails.append(f"FAIL unexpected line in the print: {ln[:160]}")
        for n in names:
            if n not in recs:
                fails.append(f"FAIL {n}: no record in the print")
                continue
            v = verdict(n, recs[n], expectation(n))
            if v: fails.append(v)
        for n in (ON_T | ON_H) - set(names):
            fails.append(f"FAIL {n}: expected on an import, not a theorem of the three modules")
        for f in fails: print(f)
        cnt = {"clean": 0, "T": 0, "H": 0}
        for n in names: cnt[expectation(n)] += 1
        print(f"theorems: {len(names)}; expected clean {cnt['clean']}, on proper_to_borel_weak {cnt['T']}, "
              f"on no_proper_five_coloring {cnt['H']}; failures: {len(fails)}")
        sys.exit(1 if fails or len(names) < 57 else 0)
    elif mode == "control":
        recs, _ = records(sys.argv[2])
        C = "FS124I1Control."
        planted = {C + "clean_but_sorry": "clean", C + "clean_but_imported": "clean", C + "transfer_but_both": "T"}
        partner = {C + "clean_partner": "clean"}          # must pass: the checker is not failing everything
        got = []
        for n, exp in {**planted, **partner}.items():
            if n not in recs:
                print(f"control: no record for {n}"); sys.exit(1)
            v = verdict(n, recs[n], exp)
            print(("reported: " + v) if v else f"passed:   {n} ({exp}) {sorted(recs[n])}")
            if v: got.append(n)
        ok = sorted(got) == sorted(planted)
        print("control: OK — the three planted faults reported, the partner passed" if ok else "control: FAILED")
        sys.exit(0 if ok else 1)
    else:
        print(__doc__); sys.exit(2)

if __name__ == "__main__":
    main()
