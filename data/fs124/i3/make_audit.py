#!/usr/bin/env python3
"""FS124-I3 — the audit block for this job's two modules, and the scratch file that prints it.

Reads the two source files for every `theorem <name>` (in file order, tracking `namespace`/`end`), and takes the three
definitions that hold proofs as fields (`sectorPoint`, `petalPoint`, `ClosePair.symm`: `PROOF_DEFS`); resolves each to the
full name the kernel stores (looked up in a StatementDump output, so a name this script gets wrong is an error here, not a
silent omission), and writes

  data/fs124/i3/audit-block.txt          the block a landing pastes into scripts/Axioms.lean (CLEAN section)
  data/fs124/i3/lean/PrintAxioms.lean    the same lines behind an import of the two modules, then the controls

Exit 0 iff every theorem of the source resolves and every named theorem (THM, not INTERNAL) of the dump that the source
declares by hand is in the block: the two counts are printed.
Usage: make_audit.py <statements-after.txt>
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
FILES = [("Plane/ThreePiece", "Proofs/HadwigerNelson/Plane/ThreePiece.lean"),
         ("Plane/ClosePair", "Proofs/HadwigerNelson/Plane/ClosePair.lean")]
# definitions of the two files that hold proofs as fields: audited as records beside the theorems
PROOF_DEFS = {"Plane/ThreePiece": ["HadwigerNelson.Plane.sectorPoint", "HadwigerNelson.Plane.petalPoint"],
              "Plane/ClosePair": ["HadwigerNelson.Plane.ClosePair.symm"]}


def dump_names(path):
    names = {}
    for ln in pathlib.Path(path).read_text().splitlines():
        if ln.startswith("@@ "):
            p = ln.split(" ")
            names[p[2]] = (p[1], p[-1] == "INTERNAL")
    return names


def source_theorems(text):
    ns, out = [], []
    for ln in text.splitlines():
        m = re.match(r"^namespace\s+(\S+)", ln)
        if m:
            ns.append(m.group(1)); continue
        m = re.match(r"^end\s+(\S+)", ln)
        if m and ns and ns[-1] == m.group(1):
            ns.pop(); continue
        m = re.match(r"^(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+)?theorem\s+(\S+)", ln)
        if m:
            out.append(".".join(ns + [m.group(1)]))
    return out


def main():
    names = dump_names(sys.argv[1])
    block, total, bad = [], 0, 0
    block.append("/-! ## FS124-I3 — FS-124's second module, its last two files (planned by FS124-K2): `Plane/ThreePiece` (the")
    block.append("decomposition at a three-piece point, edges, separation, fullness, arc edges; the models `sectorPoint`, `petalPoint`)")
    block.append("and `Plane/ClosePair` (C124-FORCED-PIECES, -LONE, -BOTH, -FOUR: `closePair_forced_pieces`, `closePair_lone`,")
    block.append("`closePair_both_separate`, `closePair_both_saved`, `closePair_four`). No record here rests on a declared outside")
    block.append("theorem. Three records are definitions that hold proofs as fields. -/")
    declared = set()
    for label, f in FILES:
        block.append(f"-- FS124-I3: {label}")
        for full in source_theorems((ROOT / f).read_text()):
            total += 1
            if full not in names or names[full][0] != "THM":
                print(f"UNRESOLVED {full}: declared in {f}, not a theorem of the dump"); bad += 1; continue
            declared.add(full)
            block.append(f"#print axioms {full}")
        for full in PROOF_DEFS[label]:
            total += 1
            if full not in names or names[full][0] != "DEF":
                print(f"UNRESOLVED {full}: named as a definition of {f}, not a definition of the dump"); bad += 1; continue
            block.append(f"#print axioms {full}")
    block.append("-- FS124-I3 block end")
    # every hand-written theorem of the dump is in the block: a named THM of the dump that the source declares
    hand = {n for n, (k, internal) in names.items() if k == "THM" and not internal}
    generated = sorted(hand - declared)
    (ROOT / "data/fs124/i3/audit-block.txt").write_text("\n".join(block) + "\n")
    scratch = ["import Proofs.HadwigerNelson.Plane.ClosePairModel",
               "import Proofs.HadwigerNelson.Plane.SectorPoint",
               "/-! FS124-I3 — the axioms of every theorem of `Plane/ThreePiece` and `Plane/ClosePair` (and of the three",
               "definitions there that hold proofs), printed from the build; then four controls. Generated by",
               "`data/fs124/i3/make_audit.py`; read by `data/fs124/i3/read_axioms.py`. -/",
               "set_option pp.fullNames true"] + block[5:] + [
               "-- CONTROLS (each must print `sorryAx`): a theorem planted here on `sorry`; a theorem planted here that cites it;",
               "-- and two theorems of the third job's files, which this branch holds as skeletons",
               "theorem FS124I3.control_planted : (2 : Nat) + 2 = 4 := by sorry",
               "theorem FS124I3.control_cites : (2 : Nat) + 2 = 4 := FS124I3.control_planted",
               "#print axioms FS124I3.control_planted",
               "#print axioms FS124I3.control_cites",
               "#print axioms HadwigerNelson.Plane.exists_closePair_full",
               "#print axioms HadwigerNelson.Plane.closePair_both_saved_of_isSector"]
    (ROOT / "data/fs124/i3/lean/PrintAxioms.lean").write_text("\n".join(scratch) + "\n")
    print(f"theorems declared in the two sources, and definitions holding proofs: {total}; theorems in the block: {len(declared)}; unresolved: {bad}")
    print(f"named theorems of the dump not declared by a `theorem` line (generated by Lean for a structure or an inductive): {len(generated)}")
    for g in generated:
        print(f"  GENERATED {g}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
