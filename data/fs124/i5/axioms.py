#!/usr/bin/env python3
"""FS124-I5: the axioms of every theorem written in Plane/ThreeArcs.lean, printed from the BUILT library.

  axioms.py gen      write data/fs124/i5/lean/Axioms.lean: one `#print axioms` per `theorem` of the module (names read
                     from the source with its namespaces) and two controls declared in the scratch file itself — a
                     theorem closed by `sorry`, and a theorem resting on a local axiom
  axioms.py check <output>   read the print: every module theorem must be printed, on a subset of the standard three;
                     the two controls must print `sorryAx` and the planted axiom.  exit 0 iff so.
Run between:  lake env lean data/fs124/i5/lean/Axioms.lean > <output>
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "Proofs/HadwigerNelson/Plane/ThreeArcs.lean"
OUT = ROOT / "data/fs124/i5/lean/Axioms.lean"
STD = {"propext", "Classical.choice", "Quot.sound"}

def names():
    ns, out = [], []
    for l in SRC.read_text().split("\n"):
        m = re.match(r"namespace (\S+)", l)
        if m: ns.append(m.group(1)); continue
        m = re.match(r"end (\S+)", l)
        if m and ns and ns[-1] == m.group(1): ns.pop(); continue
        m = re.match(r"theorem (\S+)", l)
        if m: out.append(".".join(ns + [m.group(1)]))
    return out

def gen():
    ns = names()
    body = ["import Proofs.HadwigerNelson.Plane.ThreeArcs", "",
            "/-! FS124-I5: the axioms of every theorem of `Plane/ThreeArcs`, printed from the built library (generated by",
            "`data/fs124/i5/axioms.py gen`); the last two are controls declared here. -/", ""]
    body += [f"#print axioms {n}" for n in ns]
    body += ["", "-- controls", "theorem fs124_i5_control_sorry : (2 : ℕ) + 2 = 4 := sorry",
             "axiom fs124_i5_control_axiom : (2 : ℕ) + 2 = 5",
             "theorem fs124_i5_control_planted : (2 : ℕ) + 2 = 5 := fs124_i5_control_axiom",
             "#print axioms fs124_i5_control_sorry", "#print axioms fs124_i5_control_planted", ""]
    OUT.write_text("\n".join(body))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ns)} theorems and 2 controls")

def parse(txt):
    res = {}
    for m in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", txt):
        res[m.group(1)] = {a.strip() for a in m.group(2).replace("\n", " ").split(",") if a.strip()}
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", txt):
        res[m.group(1)] = set()
    return res

def check(path):
    txt = pathlib.Path(path).read_text()
    res, ns, bad = parse(txt), names(), 0
    for n in ns:
        if n not in res: print(f"NOT PRINTED  {n}"); bad += 1
        elif not res[n] <= STD: print(f"NOT CLEAN    {n}: {sorted(res[n] - STD)}"); bad += 1
    c1 = res.get("fs124_i5_control_sorry"); c2 = res.get("fs124_i5_control_planted")
    ok1 = c1 is not None and "sorryAx" in c1
    ok2 = c2 is not None and "fs124_i5_control_axiom" in c2
    print(f"control (a theorem closed by sorry prints sorryAx): {'fired' if ok1 else 'DID NOT FIRE'}")
    print(f"control (a theorem on a planted axiom prints it):   {'fired' if ok2 else 'DID NOT FIRE'}")
    if "error" in txt: print("the print holds the word `error`"); bad += 1
    clean = sum(1 for n in ns if n in res and res[n] <= STD)
    print(f"{len(ns)} theorems written in the module; {clean} printed on a subset of {sorted(STD)}; {bad} failing")
    ok = bad == 0 and ok1 and ok2
    print("RESULT:", "PASS" if ok else "FAIL")
    sys.exit(0 if ok else 1)

if sys.argv[1] == "gen": gen()
elif sys.argv[1] == "check": check(sys.argv[2])
else: sys.exit(__doc__)
