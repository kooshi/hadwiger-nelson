#!/usr/bin/env python3
"""FS132-I4: emit Print.lean from targets.txt — the axioms of every theorem this job proved, and the package's
declarations under each whose own stored term names `sorryAx` (its "sorry frontier"), with three controls."""
import pathlib
here = pathlib.Path(__file__).parent
rows = [l.split() for l in (here/'targets.txt').read_text().splitlines() if l.strip() and not l.startswith('#')]
names = ', '.join(f'(`{k}, `HadwigerNelson.SixRing.{n})' for k, n in rows)
(here/'Print.lean').write_text(f'''import Proofs.HadwigerNelson.Plane.SixRing.Orbit
import Proofs.HadwigerNelson.Plane.SixRing.TwoPairs

/-!
FS132-I4 — generated by `data/fs132/i4/axioms/gen.py` from `targets.txt`; run with `lake env lean` after the build.

For each target: `AXIOMS` — what `#print axioms` reads (`Lean.collectAxioms`); `FRONTIER` — every declaration of this
package in the target's cone whose own stored type or value names `sorryAx`, with the module that declares it. A
target whose axioms hold `sorryAx` rests on exactly the frontier's declarations for it. Three controls at the end:
an outside theorem seen under a record that rests on one, a second outside theorem likewise, and a `sorry` planted
in this file seen in the frontier of a theorem that uses it.
-/

open Lean Elab Command

/-- The value a constant stores, theorems and opaque definitions included. -/
def storedValue? : ConstantInfo → Option Expr
  | .thmInfo v => some v.value
  | .defnInfo v => some v.value
  | .opaqueInfo v => some v.value
  | _ => none

/-- The module declaring `n`, or `(this file)`. -/
def moduleOf (env : Environment) (n : Name) : Name :=
  match env.getModuleIdxFor? n with
  | some idx => env.header.moduleNames[idx.toNat]!
  | none => `«(this file)»

/-- The package's declarations in the cone of `root` whose own stored term names `sorryAx`. Only declarations of
modules under `Proofs` (and of this file) are followed: no other library refers to this one. -/
def sorryFrontier (env : Environment) (root : Name) : Array Name := Id.run do
  let mut seen : NameSet := {{}}
  let mut stack : Array Name := #[root]
  let mut out : Array Name := #[]
  let mut fuel := 2000000
  while !stack.isEmpty && fuel > 0 do
    fuel := fuel - 1
    let n := stack.back!
    stack := stack.pop
    if seen.contains n then continue
    seen := seen.insert n
    let some ci := env.find? n | continue
    let m := moduleOf env n
    if !(m.getRoot == `Proofs || m == `«(this file)») then continue
    let used := ci.type.getUsedConstants ++ (match storedValue? ci with | some v => v.getUsedConstants | none => #[])
    if used.contains ``sorryAx then out := out.push n
    for u in used do
      if !seen.contains u then stack := stack.push u
  return out

/-- Print the two lines of one record. -/
def report (tag : String) (kind n : Name) : CommandElabM Unit := do
  let env ← getEnv
  if (env.find? n).isNone then
    logInfo m!"{{tag}} MISSING {{kind}} {{n}}"
    return
  let axs ← Lean.collectAxioms n
  let axs := axs.qsort Name.lt
  let fr := (sorryFrontier env n).qsort Name.lt
  logInfo m!"{{tag}} AXIOMS {{kind}} {{n}} | {{axs.toList}}"
  logInfo m!"{{tag}} FRONTIER {{kind}} {{n}} | {{fr.size}} | {{fr.toList.map fun d => s!"{{d}}@{{moduleOf env d}}"}}"

/-- CONTROL: a planted `sorry`. -/
theorem i4_control_planted : (1 : ℕ) = 1 := sorry
/-- CONTROL: a theorem that rests on the planted `sorry` through one step. -/
theorem i4_control_user : (1 : ℕ) = 1 := i4_control_planted

set_option maxRecDepth 100000 in
run_cmd do
  for (k, n) in [{names}] do
    report "TARGET" k n
  report "CONTROL" `outside ``HadwigerNelson.Outside.OAI158.not_colorable_five
  report "CONTROL" `outside ``HadwigerNelson.Outside.OAI158.chromaticNumber_plane_eq_chiM0
  report "CONTROL" `planted ``i4_control_user
  logInfo m!"DONE {len(rows)} targets 3 controls"
''')
print(f'Print.lean: {len(rows)} targets')
