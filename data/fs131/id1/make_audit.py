#!/usr/bin/env python3
"""FS131-ID1 — the audit block for `Arith/DyadicQuadratic`, and the check file that prints the same records' axioms.

Reads a dump of the compiled module (data/fs131/id1/lean/StatementDump.lean's format) for the kernel's list of named
constants, and the module's source for the order in which a person typed them; writes

  data/fs131/id1/audit-block.txt   — the lines for `scripts/Axioms.lean` (one `#print axioms` per public declaration)
  data/fs131/id1/lean/Axioms.lean  — the same lines under the module's import, run after the build

and fails if a declaration written in the source is not a named constant of the dump, or the dump holds a named
public constant the source does not write (so the block is the kernel's list and the file's list at once).
Usage: make_audit.py <dump.txt>          (Pattern: data/fs131/iu1/make_audit.py, branch fs131-wnf.)
"""
import re, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "Proofs/HadwigerNelson/Arith/DyadicQuadratic.lean"
dump = pathlib.Path(sys.argv[1]).read_text().splitlines()
named = {}
for ln in dump:
    if ln.startswith("@@ ") and not ln.endswith(" INTERNAL"):
        _, kind, name = ln.split(" ", 2)
        if not name.startswith("_private."):
            named[name] = kind
text = re.sub(r"/-.*?-/", "", SRC.read_text(), flags=re.S)
written = re.findall(r"^(private )?(?:noncomputable )?(?:@\[simp\] )?(?:theorem|def|abbrev) ([A-Za-z0-9_.']+)", text, flags=re.M)
public = [w for priv, w in written if not priv]
private = [w for priv, w in written if priv]
order, missing = [], []
for w in public:
    cands = [n for n in named if n == w or n.endswith("." + w)]
    if len(cands) != 1:
        missing.append((w, cands)); continue
    order.append(cands[0])
extra = sorted(set(named) - set(order))
if missing or extra or not order:
    print(f"FAIL: written but not one named constant of the dump: {missing}; named in the dump but not written: {extra}")
    sys.exit(1)
nthm = sum(named[n] == "THM" for n in order); ndef = sum(named[n] == "DEF" for n in order)
head = (f"-- FS131-ID1: Arith/DyadicQuadratic ({len(order)}: {nthm} theorems, {ndef} definitions; every public declaration a person typed, in the\n"
        f"-- file's order — the kernel's list, data/fs131/id1/statements-built.txt, through data/fs131/id1/make_audit.py).\n"
        f"-- Statements FS131-KN4's and FS131-KN5's; the ten leaves' proofs FS131-ID1's.  The file's {len(private)} private helpers are not\n"
        f"-- nameable here; each is read by a record below.  Every record CLEAN: no declared outside theorem is read.\n")
body = "".join(f"#print axioms {n}\n" for n in order)
(ROOT / "data/fs131/id1/audit-block.txt").write_text(head + body)
(ROOT / "data/fs131/id1/lean/Axioms.lean").write_text(
    "import Proofs.HadwigerNelson.Arith.DyadicQuadratic\n"
    "/-! FS131-ID1 — the axioms of every public declaration of `Arith/DyadicQuadratic`, from the compiled module (run after the\n"
    "build): `lake env lean data/fs131/id1/lean/Axioms.lean`. Generated by `data/fs131/id1/make_audit.py`. -/\n"
    "set_option pp.fullNames true\n" + body)
print(f"wrote {len(order)} records ({nthm} theorems, {ndef} definitions); private helpers in the source: {len(private)}: {private}")
