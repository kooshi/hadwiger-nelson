#!/usr/bin/env python3
"""FS131-IC1 — the audit block for `Arith/ThreeColourCharacter`, and the check file that prints the same records' axioms.

Reads a dump of the compiled module (data/fs131/ic1/lean/StatementDump.lean's format) for the kernel's list of named
constants, and the module's source for the order in which a person typed them; writes

  data/fs131/ic1/audit-block.txt   — the lines for `scripts/Axioms.lean` (one `#print axioms` per public declaration)
  data/fs131/ic1/lean/Axioms.lean  — the same lines under the module's import, run after the build

and fails if a declaration written in the source is not exactly one named constant of the dump, or the dump holds a
named constant the source does not write (so the block is the kernel's list and the file's list at once).
Usage: make_audit.py <dump.txt>          (Pattern: data/fs131/iu1/make_audit.py on branch fs131-wnf.)
"""
import re, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "Proofs/HadwigerNelson/Arith/ThreeColourCharacter.lean"
dump = pathlib.Path(sys.argv[1]).read_text().splitlines()
named = {}
for ln in dump:
    if ln.startswith("@@ ") and not ln.endswith(" INTERNAL"):
        _, kind, name = ln.split(" ", 2)
        named[name] = kind
if not named:
    print("FAIL: no named constant in the dump — the dumper or this reader is broken"); sys.exit(2)
text = re.sub(r"/-.*?-/", "", SRC.read_text(), flags=re.S)
written = re.findall(r"^(private )?(?:noncomputable )?(?:@\[simp\] )?(?:theorem|def|abbrev) ([A-Za-z0-9_.]+)", text, flags=re.M)
public = [w for priv, w in written if not priv]
private = [w for priv, w in written if priv]
order, missing = [], []
for w in public:
    w = w.removeprefix("_root_.")
    cands = [n for n in named if n == w or n.endswith("." + w)]
    if len(cands) != 1:
        missing.append((w, cands)); continue
    order.append(cands[0])
extra = sorted(set(named) - set(order))
if missing or extra:
    print(f"FAIL: written but not one named constant of the dump: {missing}; named in the dump but not written: {extra}")
    sys.exit(1)
nthm = sum(named[n] == "THM" for n in order); ndef = sum(named[n] == "DEF" for n in order)
head = (f"-- FS131-IC1: Arith/ThreeColourCharacter ({len(order)}: {nthm} theorems, {ndef} definitions; every public declaration a\n"
        f"-- person typed, in the file's order — the kernel's list, data/fs131/ic1/statements-built.txt, through\n"
        f"-- data/fs131/ic1/make_audit.py).  Statements FS131-KN4's and FS131-KN5's; the eight leaves' proofs FS131-IC1's.\n"
        f"-- The file's {len(private)} private helpers ({', '.join(private)}) are not nameable here;\n"
        f"-- each is read by `ThreeColour.Winding.exists_box_point` below.  Every record CLEAN: no declared outside theorem\n"
        f"-- is read.  One name is declared outside the module's namespace: HadwigerNelson.ThreeColour.Winding.exists_box_point.\n")
body = "".join(f"#print axioms {n}\n" for n in order)
(ROOT / "data/fs131/ic1/audit-block.txt").write_text(head + body)
(ROOT / "data/fs131/ic1/lean/Axioms.lean").write_text(
    "import Proofs.HadwigerNelson.Arith.ThreeColourCharacter\n"
    "/-! FS131-IC1 — the axioms of every public declaration of `Arith/ThreeColourCharacter`, from the compiled module (run\n"
    "after the build): `lake env lean data/fs131/ic1/lean/Axioms.lean`. Generated by `data/fs131/ic1/make_audit.py`. -/\n"
    "set_option pp.fullNames true\n" + body)
print(f"wrote {len(order)} records ({nthm} theorems, {ndef} definitions); private helpers in the source: {len(private)}: {private}")
