#!/usr/bin/env python3
"""FS131-IQ1: the axioms of every public theorem of Arith/QuadraticPrime.lean.

  axioms.py gen [--copy]   write data/fs131/iq1/lean/Axioms.lean: one `#print axioms` per public `theorem` and named
                           `instance` of the module (names read from the source), and two controls declared in the
                           check file itself — a theorem closed by `sorry`, and a theorem resting on a local axiom.
                           Default: the check file IMPORTS the module (so it reads the built `.olean`: run after the
                           build).  --copy: the check file is a COPY of the module's source with the prints appended
                           (no build needed: the interim check, elaborated by `lake env lean`).
  axioms.py check <output> read the print: every module theorem must be printed, on a subset of the standard three;
                           the two controls must print `sorryAx` and the planted axiom.  exit 0 iff so.
Run between:  data/fs131/iq1/lean1.sh data/fs131/iq1/lean/Axioms.lean   (its output: data/fs131/iq1/logs/Axioms.out)
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "Proofs/HadwigerNelson/Arith/QuadraticPrime.lean"
OUT = ROOT / "data/fs131/iq1/lean/Axioms.lean"
STD = {"propext", "Classical.choice", "Quot.sound"}
NS = "HadwigerNelson.QuadraticPrime"
EXPECT = 13

def names():
    out = []
    for l in SRC.read_text().split("\n"):
        m = re.match(r"(?:theorem|instance) ([A-Za-z0-9_.']+)", l)
        if m: out.append(f"{NS}.{m.group(1)}")
    return out

def gen(copy):
    ns = names()
    if len(ns) != EXPECT:
        print(f"FAIL: {len(ns)} public theorems read from the source, {EXPECT} expected"); sys.exit(2)
    tail = ["", "/-! FS131-IQ1: the axioms of every public theorem of `Arith/QuadraticPrime` (generated by",
            "`data/fs131/iq1/axioms.py gen`); the last two are controls declared here. -/", ""]
    tail += [f"#print axioms {n}" for n in ns]
    tail += ["", "-- controls", "theorem fs131_iq1_control_sorry : (2 : ℕ) + 2 = 4 := sorry",
             "axiom fs131_iq1_control_axiom : (2 : ℕ) + 2 = 5",
             "theorem fs131_iq1_control_planted : (2 : ℕ) + 2 = 5 := fs131_iq1_control_axiom",
             "#print axioms fs131_iq1_control_sorry", "#print axioms fs131_iq1_control_planted", ""]
    head = SRC.read_text() if copy else "import Proofs.HadwigerNelson.Arith.QuadraticPrime\n"
    OUT.write_text(head + "\n".join(tail))
    print(f"wrote {OUT.relative_to(ROOT)} ({'a copy of the source' if copy else 'importing the built module'}): {len(ns)} theorems and 2 controls")

def parse(txt):
    res = {}
    for m in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", txt):
        res[m.group(1)] = {a.strip() for a in m.group(2).replace("\n", " ").split(",") if a.strip()}
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", txt):
        res[m.group(1)] = set()
    return res

def check(path):
    txt = pathlib.Path(path).read_text()
    res, ns, bad = parse(txt), names(), 0
    if len(ns) != EXPECT: print(f"FAIL: {len(ns)} names read, {EXPECT} expected"); bad += 1
    for n in ns:
        if n not in res: print(f"NOT PRINTED  {n}"); bad += 1
        elif not res[n] <= STD: print(f"NOT CLEAN    {n}: {sorted(res[n] - STD)}"); bad += 1
        else: print(f"clean        {n}: {sorted(res[n])}")
    c1 = res.get("fs131_iq1_control_sorry"); c2 = res.get("fs131_iq1_control_planted")
    ok1 = c1 is not None and "sorryAx" in c1
    ok2 = c2 is not None and "fs131_iq1_control_axiom" in c2
    print(f"control (a theorem closed by sorry prints sorryAx): {'fired' if ok1 else 'DID NOT FIRE'}")
    print(f"control (a theorem on a planted axiom prints it): {'fired' if ok2 else 'DID NOT FIRE'}")
    if "error" in txt.lower().replace("fs131_iq1_control", ""):
        errs = [l for l in txt.splitlines() if ": error" in l]
        if errs: print(f"ERRORS in the print ({len(errs)}): {errs[0][:200]}"); bad += 1
    ok = bad == 0 and ok1 and ok2
    print(f"RESULT: {'PASS' if ok else 'FAIL'} — {len(ns) - bad if bad <= len(ns) else 0} of {len(ns)} on a subset of the standard three")
    sys.exit(0 if ok else 1)

if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "gen": gen("--copy" in sys.argv)
    elif len(sys.argv) == 3 and sys.argv[1] == "check": check(sys.argv[2])
    else: print(__doc__); sys.exit(2)
