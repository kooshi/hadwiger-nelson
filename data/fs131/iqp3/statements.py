#!/usr/bin/env python3
"""FS131-IQP3 — no stored statement or definition of the p-adic plane's landing changed but the ruled ones, from the
kernel's side. Shaped like FS131-ICO2's `data/fs131/ico2/statements.py`.

Reads three prints:
  BEFORE — FS131-IQP1's print of the compiled skeleton, made before any proof (`data/fs131/iqp1/statements-before.txt`;
           the five `PadicPlane/` modules; format `## MODULE <m> constants=<n>`, then per constant `@@ <KIND> <name>
           [INTERNAL | PRIVATE <user name>] [PROPTYPE]`, `TYPE <hash> <raw>`, and for a definition `VALUE <hash> <raw>` and,
           when its type is not a proposition, `DATA <hash> <raw>` — the value with every proof subterm erased);
  AFTER  — this job's print of the build being gated (`data/fs131/iqp3/lean/StatementDump.lean`: the same five modules
           and the three `Arith/FibreCert7*` modules the plan's leaf C7 adds);
  READD  — `data/fs131/iqp3/lean/ReAdd.lean`'s print: each ruled drop's binder put back into AFTER's stored type by term
           surgery, `READD|CONTROL-TRUE|CONTROL-NEAR <name> <hash> <raw>`.

For every constant of BEFORE that is not INTERNAL (a public or a private declaration of the file):
  SAME     present in AFTER's same module, same kind, same stored type (raw text and Lean's hash), and for a definition the
           same DATA when BEFORE printed one (a definition holding proofs moves its VALUE when a proof is filled), else the
           same VALUE;
  RULED    a drop of RULED_DROPS (item 1014, ruling (1)): AFTER's type with the binder put back (READD) has BEFORE's hash and
           BEFORE's raw text character for character, and both controls (the domain `True`; a near miss) differ from
           BEFORE's in hash and in text — else RULED-DIFFERS or CONTROL-BLIND;
  REMOVED  absent from AFTER and one of RULED_REMOVED (item 1002: the three leaves at 23 that wait on search request 26);
  CHANGED  anything else that differs                                                                 -> FAIL;
  MISSING  absent from AFTER and not ruled                                                            -> FAIL.
AFTER's non-INTERNAL constants absent from BEFORE are ADDED: public, private and GENERATED (`f.congr_simp`, `f.eq_n`,
`f.eq_def`: reserved names Lean writes on demand) apart. A public one that is not GENERATED must be in ALLOWED_PUBLIC, and a
private one in EXPECTED_PRIVATE (the helpers each implementer named) -> else FAIL. A module of AFTER absent from BEFORE must be
in NEW_MODULES, and its public constants exactly NEW_MODULES' list -> else FAIL.
INTERNAL constants (`_proof_n`, `match_n`, …) are counted per module, never compared.

--plant runs the comparison five more times on AFTER (or READD) changed in memory and requires each fault reported by name,
and nothing else new: one character of one public stored type; one public constant dropped; one unlisted public constant
added; one unlisted constant in a new module; and a ruled drop's re-added type one character off.
Usage: statements.py BEFORE AFTER READD [--plant]     exit 0 iff the comparison is clean (and, with --plant, every plant fired)
"""
import copy
import gzip
import re
import sys

GENERATED = re.compile(r"\.(congr_simp|eq_\d+|eq_def)$")
PP = "HadwigerNelson.PadicPlane."

RULED_DROPS = {
    PP + "exists_levelEmbedding": "(hk : 1 ≤ k), item 1014 (1)",
    PP + "charSum_levelOne_of_unitCircle": "(hpP : ((p : ℕ) : 𝓞 (fieldI ⊥)) ∈ P.P), item 1014 (1)",
}
RULED_REMOVED = {
    PP + "fibreShareBound_twentyThree": "item 1002 (search request 26)",
    PP + "unitQuadrance_zmod_twentyThree_pow_not_colorable_five": "item 1002 (search request 26)",
    PP + "six_le_borelChromaticNumber_padicPlane_twentyThree": "item 1002 (search request 26)",
}
ALLOWED_PUBLIC = {
    PP + "five_le_borelChromaticNumber_padicPlane_twentyThree": "item 1014 (2), FS131-IQP3",
}
EXPECTED_PRIVATE = {
    PP + "not_sq_eq_neg_one": "FS131-IQP1", PP + "norm_le_one_of_le_of_sq_add_sq": "FS131-IQP1",
    PP + "normOne_iff_pow": "FS131-IQP1", PP + "card_normOneSet_one": "FS131-IQP1",
    PP + "finrank_int_le_two": "FS131-IQP1", PP + "charP_quot_pow": "FS131-IQP1",
    PP + "isAddHaarMeasure_haar": "FS131-IQP1", PP + "res_eq_iff_dist_le": "FS131-IQP1",
    PP + "res_eq_of_le": "FS131-IQP1", PP + "haar_bad_le": "FS131-IQP1",
    PP + "charSum_unitCircle_ge_of_circleCos": "FS131-IQP3",
}
# The plan's leaf C7 (`plans/FS131-KPA1-padic-plan.md`): FS-66's certificate at 7, generated by `tools/fs131_ikc1_gen.py`
# (FS131-IQP1, its record's stage 4). Every public constant of the three modules, named.
NEW_MODULES = {
    "Proofs.HadwigerNelson.Arith.FibreCert7": {"HadwigerNelson.FibreCert.cert7"},
    "Proofs.HadwigerNelson.Arith.FibreCert7Check": {"HadwigerNelson.FibreCert.cert7_global",
                                                    "HadwigerNelson.FibreCert.cert7_seg0",
                                                    "HadwigerNelson.FibreCert.cert7_psd"},
    "Proofs.HadwigerNelson.Arith.FibreCert7Bound": {"HadwigerNelson.FibreCert.cert7_p", "HadwigerNelson.FibreCert.cert7_unum",
                                                    "HadwigerNelson.FibreCert.cert7_scale",
                                                    "HadwigerNelson.FibreCert.cert7_nseg",
                                                    "HadwigerNelson.FibreCert.cert7_ok",
                                                    "HadwigerNelson.FibreCertSound.sum_le_seven",
                                                    "HadwigerNelson.FibreCertSound.model_seven"},
}


def read(path):
    opener = gzip.open if path.endswith(".gz") else open
    mods, cur, last = {}, None, None
    with opener(path, "rt", encoding="utf-8") as f:
        for ln in f:
            ln = ln.rstrip("\n")
            if ln.startswith("## MODULE "):
                cur = ln.split()[2]
                mods[cur] = {}
            elif ln.startswith("@@ "):
                parts = ln.split()
                kind, name, flags = parts[1], parts[2], parts[3:]
                private = "PRIVATE" in flags
                mods[cur][name] = {"kind": kind, "internal": "INTERNAL" in flags, "private": private,
                                   "user": flags[flags.index("PRIVATE") + 1] if private else name}
                last = mods[cur][name]
            elif ln.startswith(("TYPE ", "VALUE ", "DATA ")):
                tag, rest = ln.split(" ", 1)
                h, raw = rest.split(" ", 1) if " " in rest else (rest, "")
                last[tag] = raw
                last[tag + "_HASH"] = h
    return mods


def read_readd(path):
    out = {}
    opener = gzip.open if path.endswith(".gz") else open
    for ln in opener(path, "rt", encoding="utf-8"):
        m = re.match(r"(READD|CONTROL-TRUE|CONTROL-NEAR) (\S+) (\d+) (.*)$", ln.rstrip("\n"))
        if m:
            out[(m.group(1), m.group(2))] = (m.group(3), m.group(4))
    return out


def compare(before, after, readd, quiet=False):
    fails, report = [], []
    for mod, consts in before.items():
        amod = after.get(mod)
        if amod is None:
            fails.append(f"MODULE-MISSING {mod}")
            continue
        n_same = n_int = 0
        for name, c in consts.items():
            if c["internal"]:
                n_int += 1
                continue
            a = amod.get(name)
            if a is None:
                if name in RULED_REMOVED:
                    report.append(f"REMOVED {name}: {RULED_REMOVED[name]}")
                else:
                    fails.append(f"MISSING {name} ({mod})")
                continue
            if name in RULED_DROPS:
                r = readd.get(("READD", name))
                bt = (c.get("TYPE_HASH"), c.get("TYPE"))
                ok = r is not None and a["kind"] == c["kind"] and r == bt
                blind = [t for t in ("CONTROL-TRUE", "CONTROL-NEAR")
                         if readd.get((t, name)) is None or readd[(t, name)][0] == bt[0] or readd[(t, name)][1] == bt[1]]
                report.append(f"RULED {'OK' if ok else 'DIFFERS'} {name}: the binder {RULED_DROPS[name]} put back gives "
                              f"{'the before-print exactly (hash ' + bt[0] + ', raw text equal)' if ok else 'another type'}; "
                              f"controls {'both differ' if not blind else 'BLIND: ' + str(blind)}")
                if not ok:
                    fails.append(f"RULED-DIFFERS {name}")
                if blind:
                    fails.append(f"CONTROL-BLIND {name} {blind}")
                continue
            same = (a["kind"] == c["kind"] and a.get("TYPE") == c.get("TYPE")
                    and a.get("TYPE_HASH") == c.get("TYPE_HASH"))
            if c["kind"] == "DEF":
                key = "DATA" if "DATA" in c else "VALUE"
                same = same and a.get(key) == c.get(key)
            if same:
                n_same += 1
            else:
                what = "kind" if a["kind"] != c["kind"] else "type" if a.get("TYPE") != c.get("TYPE") else "value"
                fails.append(f"CHANGED ({what}) {name} ({mod})")
        added = [(n, a) for n, a in amod.items() if n not in consts and not a["internal"]]
        a_int = sum(1 for n, a in amod.items() if a["internal"])
        gen = sorted(n for n, a in added if not a["private"] and GENERATED.search(n))
        pub = sorted(n for n, a in added if not a["private"] and not GENERATED.search(n))
        priv = sorted(a["user"] for n, a in added if a["private"])
        for n in pub:
            if n not in ALLOWED_PUBLIC:
                fails.append(f"ADDED-PUBLIC-UNLISTED {n} ({mod})")
        for n in priv:
            if n not in EXPECTED_PRIVATE:
                fails.append(f"ADDED-PRIVATE-UNLISTED {n} ({mod})")
        report.append(f"{mod}: before {len(consts)} constants ({n_int} internal); SAME {n_same}; "
                      f"added public {len(pub)} {pub}; added private {len(priv)}; generated on demand {gen}; "
                      f"internal after {a_int}")
        if priv:
            report.append(f"    private added: {priv}")
    for m, amod in after.items():
        if m in before:
            continue
        if m not in NEW_MODULES:
            fails.append(f"MODULE-NEW-UNLISTED {m}")
            continue
        pub = {n for n, a in amod.items() if not a["internal"] and not a["private"] and not GENERATED.search(n)}
        priv = sorted(a["user"] for n, a in amod.items() if a["private"])
        n_int = sum(1 for a in amod.values() if a["internal"])
        if pub != NEW_MODULES[m]:
            fails.append(f"NEW-MODULE-CONSTANTS {m}: unlisted {sorted(pub - NEW_MODULES[m])}, "
                         f"absent {sorted(NEW_MODULES[m] - pub)}")
        report.append(f"NEW MODULE {m} (the plan's C7): public {len(pub)} {sorted(pub)}; private {len(priv)} {priv}; "
                      f"internal {n_int}")
    for name in RULED_REMOVED:
        if not any(name in consts for consts in before.values()):
            fails.append(f"RULED-REMOVED-NOT-IN-BEFORE {name}")
    if not quiet:
        for r in report:
            print(r)
    return fails


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    before, after, readd = read(args[0]), read(args[1]), read_readd(args[2])
    if not before or not after or not readd:
        print("NOTHING READ — a print or the reader is broken")
        return 2
    fails = compare(before, after, readd)
    for f in fails:
        print("FAIL", f)
    print(f"VERDICT {'CLEAN' if not fails else 'FAIL'}: {len(fails)} failure(s)")
    if "--plant" not in sys.argv:
        return 1 if fails else 0
    ok = True
    mod = "Proofs.HadwigerNelson.PadicPlane.Values"
    victim = PP + "not_exists_bound_borelChromaticNumber_padicPlane"
    plants = []
    a1 = copy.deepcopy(after)
    t = a1[mod][victim]["TYPE"]
    a1[mod][victim]["TYPE"] = t[:-1] + ("Y" if t[-1:] == "X" else "X")
    plants.append(("a changed stored type", a1, readd, f"CHANGED (type) {victim} ({mod})"))
    a2 = copy.deepcopy(after)
    del a2[mod][victim]
    plants.append(("a dropped constant", a2, readd, f"MISSING {victim} ({mod})"))
    a3 = copy.deepcopy(after)
    a3[mod][PP + "planted_new"] = {"kind": "THM", "internal": False, "private": False, "user": PP + "planted_new",
                                   "TYPE": "True", "TYPE_HASH": "0"}
    plants.append(("an unlisted public constant", a3, readd, f"ADDED-PUBLIC-UNLISTED {PP}planted_new ({mod})"))
    a4 = copy.deepcopy(after)
    cm = "Proofs.HadwigerNelson.Arith.FibreCert7Bound"
    a4[cm]["HadwigerNelson.FibreCert.planted_new"] = {"kind": "THM", "internal": False, "private": False,
                                                       "user": "HadwigerNelson.FibreCert.planted_new", "TYPE": "True"}
    plants.append(("an unlisted constant in a new module", a4, readd,
                   f"NEW-MODULE-CONSTANTS {cm}: unlisted ['HadwigerNelson.FibreCert.planted_new'], absent []"))
    r5 = dict(readd)
    key = ("READD", PP + "exists_levelEmbedding")
    h, raw = r5[key]
    r5[key] = (h, raw.replace("(OfNat.ofNat.{0} Nat 1 (instOfNatNat 1)) k", "(OfNat.ofNat.{0} Nat 1 (instOfNatNat 1)) k ", 1))
    plants.append(("a re-added type one character off", after, r5, f"RULED-DIFFERS {PP}exists_levelEmbedding"))
    for label, a, r, expect in plants:
        got = compare(before, a, r, quiet=True)
        new = sorted(set(got) - set(fails))
        hit = expect in new
        extra = [g for g in new if g != expect]
        print(f"PLANT {label}: {'FIRED' if hit and not extra else 'NOT FIRED'} — new failures {new}")
        ok = ok and hit and not extra
    print(f"PLANTS {'ALL FIRED' if ok else 'SOME DID NOT FIRE'}")
    return 0 if ok and not fails else 1


if __name__ == "__main__":
    sys.exit(main())
