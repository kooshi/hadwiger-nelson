#!/usr/bin/env python3
"""FS131-ISF1: the ARCHITECTURE.md § 3.11 rows of the `Plane/G27/` modules, their imports read from
`scripts/build_order.py` (the checker's own source of truth), descriptions from the module kind. Prints the rows."""
import importlib.util
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location('bo', REPO / 'scripts/build_order.py')
bo = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bo)
graph = bo.modules()
P = 'Proofs.HadwigerNelson.'


def short(k):
    return k[len(P):].replace('.', '/')


man = json.loads((REPO / 'data/fs131/isf1/gen/manifest.json').read_text())['stats']
DESC = {
    'Check': "**FS-131 (FS131-ISF1).** `G27`'s certificate checker, in core (imports only `X23Check`, whose `Q4`/`C4` and congruence rows `rowOk` it reads): terms `key + 2²⁷·(c + OFFC)`; the residual DFS (`stepOut`, `stepIn`, `mergeR`, `dfsR`, `collectR`, `leafOk`), `goodB`, `splitOk`, the sort `sortRounds`/`sortR`, `rowsTerms`, `rowsFit`, `adjOk`, `wfB`, `pathsOk`, `singSumOk`; `noncomputable` (`List.rec`), evaluated by the kernel alone.",
    'Sound': "**FS-131 (FS131-ISF1).** The checker is sound: `val_mergeR`, `val_sortR`, `val_stepOut`, `val_stepIn`, `dfsR_sound`, `dfsR_append`, `dfsR_eq_all`, `goodB_of_split`, `segsOk_spec`.",
    'Law': "**FS-131 (FS131-ISF1).** `[MatolcsiEtAl2025]` Thm 3 read against an invariant law: the 27 points in `ℤ[U]` (`xpt_mem`), each congruence row an isometry of `R` preserving `φ(Y) = P(Y ⊆ I) + P(Ȳ ⊆ I)` (`row_phi`), the terms' expectation (`expect_le`), `density_le_of_cert`.",
    'Bound': "**FS-131 (FS131-ISF1).** `cert_bound` (the certificate's condition (iii), from the residual DFS), `density_le_quarter`: every invariant random independent set of `Cay(R, U)` over `ℚ(√3, √11)` has density at most `1/4`.",
    'Data': "**FS-131 (FS131-ISF1), generated by `tools/fs131_kfs1_g27.py`.** `G27`'s 27 points (`ptsL`), adjacency masks (`adjL`), paths (`pathsL`), `Dn`, the singletons (`singL`); `adj_ok`, `wf_ok`, `paths_ok`, `origin_ok`, `sing_ok`, `Dn_pos`.",
    'RootData': "**FS-131 (FS131-ISF1), generated.** The certificate's 28,496 terms sorted and merged (`rootL`, `rootSt`).",
    'RootSort': "**FS-131 (FS131-ISF1), generated.** `root_ok`: the rows' sorted terms and the singletons merge to `rootL`.",
    'All': "**FS-131 (FS131-ISF1), generated.** The checks assembled: `segR`, `segC`, `segS`, `segs_ok`, `root_sorted`, `good_root`.",
}
rows = []
for k in sorted(graph):
    if not k.startswith(P + 'Plane.G27.'):
        continue
    m = short(k)
    base = m.split('/')[-1]
    if base in DESC:
        d = DESC[base]
    elif base.startswith('Rows'):
        n = int(base[4:])
        d = (f"**FS-131 (FS131-ISF1), generated.** Congruence rows {600 * n}–{min(600 * (n + 1), man['rows']) - 1} "
             f"(`rows{n:02d}`, `coefs{n:02d}`, `sorted{n:02d}`): `rows{n:02d}_ok0`, `rows{n:02d}_ok1`, `rows{n:02d}_fit`, "
             f"`rows{n:02d}_sort`.")
    elif base.startswith('St'):
        d = f"**FS-131 (FS131-ISF1), generated.** Split {int(base[2:])} of the residual DFS: its literal states one level down (`out{base[2:]}`)."
    elif base.startswith('Chk'):
        d = f"**FS-131 (FS131-ISF1), generated.** Residual DFS checks, part {int(base[3:])}: splits (`spNNN_ok`) and leaf groups (`gpNNNxMM_ok`)."
    else:
        raise SystemExit(f'no description for {m}')
    imps = ', '.join(f'`{short(i)}`' for i in sorted(graph[k])) or '—'
    rows.append(f'| `{m}` | {d} | {imps} | — | FS-131 |')
print('\n'.join(rows))
