from spectral import *
from zlin import *
from math import lcm
import collections
S9,_,_=theta(list(range(-4,5)))
S9=sorted(S9)
# describe the 42 points: order, and whether 2t is one of the order-2 points, etc.
def order(t): return lcm(*[x.denominator for x in t])
print(collections.Counter(order(t) for t in S9))
o2=[t for t in S9 if order(t)==2]
print('order-2 points (as 2t in F2^4):',[tuple(int(2*x) for x in t) for t in o2])
# group: lattice of periods P = {x in Z^4 : t.x in Z for all t}; compute via dual: rows = den*t
den=8
rows=[[int(den*x) for x in t] for t in S9]
# P = {x : rows.x = 0 mod den}. Compute HNF of the lattice generated by rows and den*I  (dual lattice), then P = den * dual^{-1}...
from sympy import Matrix
A=Matrix(rows+[[den if i==j else 0 for j in range(4)] for i in range(4)])
from sympy.matrices.normalforms import hermite_normal_form
H=hermite_normal_form(A.T).T
print('generators of the dual lattice (times 8):',H.tolist())
Hs=Matrix([r for r in H.tolist() if any(r)])
Pm=(Hs.inv()*den).T if Hs.shape[0]==4 else None
print('period lattice basis (coords9), rows:', Pm.tolist() if Pm is not None else None)
import sympy
print('index of period lattice in Lambda:', abs(Pm.det()) if Pm is not None else None, ' (8Lambda has index 4096)')
