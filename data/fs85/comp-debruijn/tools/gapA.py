"""Gap A aid: classes of U modulo M = T0 + eta^2 T0 (index 729 in Lambda), and each class's reductions mod p and mod p' (in F4^x = mu3).
A non-residue coset W bordering the residue region through two unit vectors of one M-class with different reductions (and eps-bar
among them) contradicts the complementary-pair alignment."""
import sympy
from lam import *
from twoadic import emb
from collections import defaultdict
eta=(Fr(0),Fr(1,6),Fr(0),Fr(-1,6))
def pw(a,k):
    r=ONE
    if k<0: a=inv(a); k=-k
    for _ in range(k): r=mul(r,a)
    return r
def lc(a): return [int(9*x) for x in coords(a)]
Mgen = [lc(ONE), lc(Z6), lc(mul(eta,eta)), lc(mul(Z6,mul(eta,eta)))]
Mm = sympy.Matrix(Mgen).T      # columns generate M
Minv = Mm.inv()
def Mclass(a):
    v = Minv * sympy.Matrix(lc(a))
    return tuple(sympy.Rational(x) % 1 for x in v)
def red1(a, s):   # reduction mod the prime (level 1) as element of Z/2[zeta3]
    e = emb(a, s); return (e[0] % 2, e[1] % 2)
cls = defaultdict(list)
for b in range(-4,5):
    for k in range(6):
        u = mul(pw(Z6,k), pw(eta,b))
        cls[Mclass(u)].append((k, b, red1(u,1), red1(u,-1)))
print('index of M in Lambda:', abs(Mm.det()), '  number of M-classes met by U:', len(cls))
for key, mem in cls.items():
    rp = sorted({m[2] for m in mem}); rq = sorted({m[3] for m in mem})
    print(len(mem), 'vectors', [(m[0], m[1]) for m in mem], ' red mod p:', rp, ' red mod p\':', rq)

# does the subgroup of Lambda/M generated by the four 3-element classes exhaust Lambda/M?
triple = [k for k, mem in cls.items() if len(mem) == 3]
print('3-element classes:', len(triple))
seen = {tuple([sympy.Rational(0)]*4)}; frontier = list(seen)
while frontier:
    new = []
    for x in frontier:
        for g in triple:
            for sgn in (1, -1):
                y = tuple((a + sgn*b) % 1 for a, b in zip(x, g))
                if y not in seen: seen.add(y); new.append(y)
    frontier = new
print('subgroup generated by the 3-element classes has order', len(seen), 'of', 729)
